"""P121: replace experiment/campaign jargon in NTRU+768 assembly comments with neutral
descriptions, and collapse generator logs of removed instructions.  Comments and
local-label names only; verified by comparing disassembly.  usage: comments.py TREE"""
import re, sys, pathlib
T = pathlib.Path(sys.argv[1])
def edit(name, pairs, regex=()):
    p = T / name; s = p.read_text()
    for a, b in pairs:
        assert s.count(a) >= 1, (name, a[:60]); s = s.replace(a, b)
    for pat, rep, flags in regex:
        s, n = re.subn(pat, rep, s, flags=flags); print(f'  {name}: {n} x {pat[:50]!r}')
    p.write_text(s)

