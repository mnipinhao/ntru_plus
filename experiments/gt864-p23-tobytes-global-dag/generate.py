#!/usr/bin/env python3
"""Generate exact symbolic P23 ToBytes from the register-capped DAG trace."""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load_search():
    spec = importlib.util.spec_from_file_location("p23_search", HERE / "search.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def wrapper(mode: str) -> list[str]:
    public = f"gt864_p23_tobytes_{mode}_asm"
    top = f"p23_top_{mode}"
    lines = [
        "/* Generated by P23 generate.py; do not edit. */",
        "#ifdef __APPLE__", f"#define {public} _{public}", "#endif",
        ".text", ".p2align 4", f".global {public}", f"{public}:",
        " stp x29,x30,[sp,#-112]!", " mov x29,sp", " stp x19,x20,[sp,#16]",
        " stp d8,d9,[sp,#32]", " stp d10,d11,[sp,#48]",
        " stp d12,d13,[sp,#64]", " stp d14,d15,[sp,#80]",
        " mov x19,x0", " mov x20,x1", f" bl {top}",
        " add x0,x19,#648", " add x1,x20,#864", f" bl {top}",
    ]
    lines += [f" movi v{index}.16b,#0" for index in range(32)]
    lines += [
        " ldp d8,d9,[sp,#32]", " ldp d10,d11,[sp,#48]",
        " ldp d12,d13,[sp,#64]", " ldp d14,d15,[sp,#80]",
        " ldp x19,x20,[sp,#16]", " ldp x29,x30,[sp],#112", " ret",
        ".p2align 4", f"{top}:", f" adr x2,p23_pack_index_{mode}",
        " ldr q26,[x2]", " mov w8,#3457", " dup v27.8h,w8",
    ]
    if mode == "full":
        lines += [" mov w8,#9", " dup v28.8h,w8"]
    lines += [" mov x5,x0", " add x6,x0,#216", " add x7,x0,#432"]
    return lines


def route_instruction(item: dict, physical: bool = False) -> str:
    destination = str(item["slot"]) if physical else f"r{item['instance']}"
    operation = item["operation"]
    inputs = ([str(value) for value in item["input_slots"]] if physical
              else [f"r{value}" for value in item["inputs"]])
    prefix = "v" if physical else "V<"
    suffix = "" if physical else ">"
    if operation == "load":
        register = f"q{destination}" if physical else f"Q<{destination}>"
        return f" ldr {register},[x1,#{16 * item['source']}]"
    if operation.startswith("ext"):
        amount = 2 * int(operation[3:])
        return (f" ext {prefix}{destination}{suffix}.16b,{prefix}{inputs[0]}{suffix}.16b,"
                f"{prefix}{inputs[0]}{suffix}.16b,#{amount}")
    mnemonic, shape = operation.split(".", 1)
    return (f" {mnemonic} {prefix}{destination}{suffix}.{shape},"
            f"{prefix}{inputs[0]}{suffix}.{shape},{prefix}{inputs[1]}{suffix}.{shape}")


def consume(mode: str, output: int, instance: int, slot: int | None = None) -> list[str]:
    physical = slot is not None
    value = str(slot) if physical else f"r{instance}"
    vector = f"v{value}" if physical else f"V<{value}>"
    scalar_d = f"d{value}" if physical else f"D<{value}>"
    lines = []
    if mode == "full":
        lines += [
            f" sqrdmulh v29.8h,{vector}.8h,v28.8h",
            f" mls {vector}.8h,v29.8h,v27.8h",
        ]
    lines += [
        f" sshr v29.8h,{vector}.8h,#15",
        " and v29.16b,v29.16b,v27.16b",
        f" add {vector}.8h,{vector}.8h,v29.8h",
        f" uzp1 v30.8h,{vector}.8h,{vector}.8h",
        f" uzp2 v31.8h,{vector}.8h,{vector}.8h",
        " shl v29.8h,v31.8h,#12",
        " orr v30.16b,v30.16b,v29.16b",
        " ushr v31.8h,v31.8h,#4",
        f" tbl {vector}.16b,{{v30.16b,v31.16b}},v26.16b",
    ]
    base = ("x5", "x6", "x7")[output // 18]
    offset = 12 * (output % 18)
    lines += [
        f" stur {scalar_d},[{base},#{offset}]",
        f" mov x9,{vector}.d[1]",
        f" stur w9,[{base},#{offset + 8}]",
    ]
    return lines


def emit(mode: str, trace: list[dict], physical: bool = False) -> str:
    lines = wrapper(mode)
    lines += [
        " // Live-in: x0 output, x1 FR0 input, v26 pack index, v27 q; Full also v28 reciprocal9.",
        " // Live-out: exact 648 canonical wire bytes at public fixed offsets.",
        " // Range: Full arbitrary signed int16; Small strict (-3457,3457).",
        " // Reserved physical registers: v26-v31 and x18-x30/sp; route allocation uses v0-v25.",
        f"p23_top_{mode}_slothy_start:",
        f"p23_{mode}_group6_0_start:",
        f"p23_{mode}_group3_0_start:",
        f"p23_{mode}_window_0_start:",
    ]
    window = 0
    for item in trace:
        if item["kind"] == "compute":
            lines.append(route_instruction(item, physical))
        else:
            lines += consume(mode, item["output"], item["instance"],
                             item["slot"] if physical else None)
            lines.append(f"p23_{mode}_window_{window}_end:")
            window += 1
            if window % 3 == 0:
                lines.append(f"p23_{mode}_group3_{window // 3 - 1}_end:")
                if window < 54:
                    lines.append(f"p23_{mode}_group3_{window // 3}_start:")
            if window % 6 == 0:
                lines.append(f"p23_{mode}_group6_{window // 6 - 1}_end:")
                if window < 54:
                    lines.append(f"p23_{mode}_group6_{window // 6}_start:")
            if window < 54:
                lines.append(f"p23_{mode}_window_{window}_start:")
    assert window == 54
    lines += [
        f"p23_top_{mode}_slothy_end:", " ret", ".p2align 4",
        f"p23_pack_index_{mode}:",
        " .byte 0,1,16,2,3,18,4,5,20,6,7,22,255,255,255,255", "",
    ]
    return "\n".join(lines)


def main() -> None:
    search = load_search()
    report = json.loads((HERE / "search-results.json").read_text())
    outputs, _ = search.build_dag()
    order = report["searched_order"]
    result = search.simulate(outputs, order, report["capacity_route_registers"],
                             with_trace=True)
    assert result["instructions"] == 285
    assert result["source_loads"] == 61
    assert result["routing_arithmetic"] == 224
    assert result["peak_route_registers"] == 26

    live_instances = {}
    consumed = []
    for item in result["trace"]:
        if item["kind"] == "compute":
            live_instances[item["instance"]] = item
        else:
            consumed.append(item["output"])
            # Structural identity is guaranteed by simulate; oracle.py checks lane values.
    assert consumed == order and sorted(consumed) == list(range(54))
    instance_slots = {item["instance"]: item["slot"] for item in result["trace"]
                      if item["kind"] == "compute"}
    for item in result["trace"]:
        if item["kind"] == "compute":
            item["input_slots"] = [instance_slots[value] for value in item["inputs"]]
        else:
            item["slot"] = instance_slots[item["instance"]]
    for mode in ("full", "small"):
        (HERE / f"candidate-{mode}.sym.S").write_text(emit(mode, result["trace"]))
        (HERE / f"candidate-{mode}.phys.S").write_text(
            emit(mode, result["trace"], physical=True))
    # A single contract-scannable source carries both independent Slothy regions.
    combined = emit("full", result["trace"]) + "\n" + emit("small", result["trace"])
    (HERE / "candidate.sym.S").write_text(combined)
    trace_report = {key: value for key, value in result.items() if key != "trace"}
    trace_report["trace_records"] = len(result["trace"])
    (HERE / "trace-results.json").write_text(json.dumps(trace_report, indent=2) + "\n")
    print(json.dumps(trace_report, indent=2))


if __name__ == "__main__":
    main()
