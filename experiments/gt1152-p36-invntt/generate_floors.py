"""Emit issue-floor probes for packed_i9 and invntt16_asm, correctly this time.

The first attempt grouped the instructions by opcode -- 86 consecutive `ldr q`,
then 128 consecutive umov/strh pairs -- and came out 12% and 53% SLOWER than
the kernels it was meant to bound.  Clustering by opcode manufactures a
serialization on one resource that the real kernel avoids by interleaving, so
it measures a worse schedule, not a floor.

This keeps the shipped kernel's instruction sequence exactly as Slothy emitted
it -- same opcodes, same operand forms, same order, same GPR names, so the same
umov/strh pairing distances -- and rewrites only the vector SOURCE operands to
a pool of registers the body never writes.  What is left is the throughput
limit of that mix in that order.  Dependencies that are inherent are kept: an
`mls` still reads its own destination, because Montgomery reduction cannot
avoid that.
"""
import re
from pathlib import Path

PKG = Path("../gt1152-p10-kem")
POOL = ["v0", "v1", "v2", "v3", "v4", "v5", "v6", "v7"]

# vN.<arr> or vN.<lane-form>; capture the register number and the suffix
VREG = re.compile(r'\bv(\d+)(\.\w+(?:\[\d+\])?)')

# Instructions whose FIRST vector operand is also read (accumulators), so that
# operand must not be renamed or the dependency structure changes.
ACCUM = {"mls", "mla", "smlal", "smlal2", "smlsl", "smlsl2"}


def rewrite(line, k):
    m = re.match(r'^(\s+)([a-z][a-z0-9.]*)\s+(.*)$', line)
    if not m:
        return line
    ind, op, rest = m.groups()
    # split off the first operand (the destination, or the accumulator)
    parts = rest.split(",")
    head, tail = parts[0], parts[1:]
    if not tail:
        return line
    def sub(t, i=[0]):
        def r(mm):
            i[0] += 1
            return POOL[(k + i[0]) % len(POOL)] + mm.group(2)
        return VREG.sub(r, t)
    # `st1 {vN.D}[1], [x12], x14` -- the braced operand is the source, rename it
    if op.startswith("st") and head.strip().startswith("{"):
        return f"{ind}{op} {sub(head)},{','.join(tail)}"
    return f"{ind}{op} {head},{','.join(sub(t) for t in tail)}"


def build(name, src, reps, base_reg, scratch_setup):
    lines = (PKG / src).read_text().splitlines()
    body, n = [], 0
    for ln in lines:
        if not re.match(r'^\s+[a-z]', ln):
            continue
        if re.match(r'^\s+ret\b', ln):
            continue
        if ln.rstrip().endswith(":"):          # indented labels, e.g. slothy_start
            continue
        body.append(rewrite(ln, n))
        n += 1
    return n, (f"\n.global {name}\n{name}:\n    SAVE_ALL\n"
               f"    mov x19, x0\n    mov x20, x1\n"
               f"    mov x21, #{reps}\n.L{name}_loop:\n{scratch_setup}"
               + "\n".join(body) + "\n"
               f"    subs x21, x21, #1\n    b.ne .L{name}_loop\n"
               "    RESTORE_ALL\n    ret\n")


HEAD = """/* Generated by generate_floors.py; do not edit.  See its docstring for why
 * the instruction ORDER is preserved and only vector sources are renamed.
 * x0: 4096 writable bytes.  x1: 4096 readable bytes.
 */
.text
.p2align 2
.macro SAVE_ALL
    stp x29, x30, [sp, #-160]!
    mov x29, sp
    stp x19, x20, [sp, #16]
    stp x21, x22, [sp, #32]
    stp x23, x24, [sp, #48]
    stp x25, x26, [sp, #64]
    stp x27, x28, [sp, #80]
    stp d8,  d9,  [sp, #96]
    stp d10, d11, [sp, #112]
    stp d12, d13, [sp, #128]
    stp d14, d15, [sp, #144]
.endm
.macro RESTORE_ALL
    ldp x19, x20, [sp, #16]
    ldp x21, x22, [sp, #32]
    ldp x23, x24, [sp, #48]
    ldp x25, x26, [sp, #64]
    ldp x27, x28, [sp, #80]
    ldp d8,  d9,  [sp, #96]
    ldp d10, d11, [sp, #112]
    ldp d12, d13, [sp, #128]
    ldp d14, d15, [sp, #144]
    ldp x29, x30, [sp], #160
.endm
"""

# packed_i9 reads x1,x2,x3 and writes x0 and x12 (st1 post-index by x14);
# invntt16_asm reads x1..x4 and writes x0.  Point them all at the two buffers.
# Re-established each iteration, because packed_i9's `st1 {v.D}[1], [x12], x14`
# post-increments x12 and would otherwise walk off the buffer.
# Restored at the top of every iteration from the bases stashed in x19/x20.
# packed_i9 does not merely read x1 -- it STORES through it
# (`st1 {v28.H}[k], [x1], x14`, eight post-increments of 16 bytes) and it
# post-increments x12 and x4 as well, so nothing the body touches may be
# assumed to survive an iteration.
SETUP = ("    mov x0, x19\n    mov x1, x20\n"
         "    mov x2, x20\n    mov x3, x20\n    mov x4, x20\n"
         "    mov x12, x19\n    mov x14, #16\n")

n9, f9 = build("floor_i9_asm", "inverse9.S", 16, "x1", SETUP)
n16, f16 = build("floor_i16_asm", "inverse16.S", 8, "x1", SETUP)
Path("inv_floors.S").write_text(
    HEAD + f9 + f16 + '\n#if defined(__ELF__)\n.section .note.GNU-stack,"",%progbits\n#endif\n')
print(f"wrote inv_floors.S: packed_i9 {n9} instrs x16, invntt16_asm {n16} instrs x8")
