"""Emit driver variants of invntt_ternary_asm with one stage removed each.

Stage cost = full - (full without that stage).  This attributes without
re-deriving the driver's address arithmetic, which is itself part of what we
are trying to measure.  Every kernel here is straight-line and constant-time,
so removing a `bl` changes the data the later stages see but not the cycle
count -- that is the assumption this decomposition rests on, and it is the same
assumption the package's own constant-time claim rests on.
"""
import re
import sys
from pathlib import Path

SRC = Path("../gt1152-p10-kem/inverse_ntt.S")
text = SRC.read_text()

# the wipe loop, exactly as the driver writes it
WIPE = """    movi v0.16b, #0
    mov x9, sp
    mov x10, #18
.Lp13inv_wipe:
    stp q0, q0, [x9], #32
    stp q0, q0, [x9], #32
    stp q0, q0, [x9], #32
    stp q0, q0, [x9], #32
    subs x10, x10, #1
    b.ne .Lp13inv_wipe
"""
assert text.count(WIPE) == 1, "wipe loop anchor drift"

VARIANTS = {
    "full":        [],
    "no_i9":       ["bl C(packed_i9)"],
    "no_main":     ["bl C(invntt16_asm)"],
    "no_tail":     ["bl C(invntt16_tail_asm)"],
    "no_crep":     ["bl C(crepmod3_ternary_asm)"],
    "no_wipe":     ["WIPE"],
    "skeleton":    ["bl C(packed_i9)", "bl C(invntt16_asm)",
                    "bl C(invntt16_tail_asm)", "bl C(crepmod3_ternary_asm)", "WIPE"],
}

out = []
for name, drop in VARIANTS.items():
    t = text
    # rename the entry point and its labels so all variants can link together
    t = t.replace("C(invntt_ternary_asm)", f"inv_{name}")
    for lbl in ("Lp8inv_top", "Lp8inv_component", "Lp8inv_i9", "Lp8inv_main_component",
                "Lp8inv_main", "Lp13inv_wipe"):
        t = t.replace(lbl, f"{lbl}_{name}")
    t = t.replace("SAVE_PUBLIC", f"SAVE_PUBLIC_{name}").replace("RESTORE_PUBLIC", f"RESTORE_PUBLIC_{name}")
    wipe_here = WIPE.replace("Lp13inv_wipe", f"Lp13inv_wipe_{name}")
    for d in drop:
        if d == "WIPE":
            assert t.count(wipe_here) == 1, f"{name}: wipe anchor drift after rename"
            t = t.replace(wipe_here, "")
        else:
            n = t.count(f"    {d}\n")
            assert n == 1, f"{name}: {d} appears {n} times"
            t = t.replace(f"    {d}\n", "")
    # strip the guard and the shared header so only the function body is emitted
    t = t.split("#if defined(__ELF__)")[0]
    if out:                                    # keep one copy of .text
        t = re.sub(r'^\.text\n', '', t, flags=re.M)
    out.append(t)

Path("inv_variants.S").write_text(
    "/* Generated by generate_variants.py; do not edit. */\n"
    + "\n".join(out)
    + '\n#if defined(__ELF__)\n.section .note.GNU-stack,"",%progbits\n#endif\n')
print("wrote inv_variants.S:", ", ".join(f"inv_{k}" for k in VARIANTS))
