#!/usr/bin/env python3
"""Emit NTRU+1152's invntt16_asm in the (component, half) lane basis.

P66 established that the main kernel and the tail differ only in what their
inner four lanes mean -- s_local for the main, branch for the tail -- and that
the terminal table is shared: invntt16_main_constants and
invntt16_tail_constants are 64/64 identical, and every row is
[A,A,A,A,B,B,B,B], so the constant depends on `half` alone.  Swapping the inner
lanes therefore needs no table change.

The fold already rotates four halfwords (`ext ... #8`), which is the fold over
`half` in either basis.  So the only change here is the output.

The natural index is n = component + 4*s + 36*t + 576*half.  The present kernel
writes, per call, n = (c + 16*g) + 4*s_local + 36*t + 576*half; since 576 = 16*36
and 4*s_local < 16 < 36, `divmod(off//2, 36)` splits an offset into the group
index t + 16*half and 4*s_local.  In the new basis the same group is four
consecutive halfwords, so it becomes one `str d` at 2*36*group -- exactly the
mapping gt1152-p22-tail-asm/generate_tail.py uses for the tail.

The store is emitted where the `umov` was, not where the `strh` was: Slothy
reuses these registers hard and several are overwritten in between.
"""
import re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC  = HERE.parents[0] / "gt1152-p10-kem/inverse16.S"
STRIDE = 36                       # int16 between consecutive t within a half
DEG    = 4                        # components

raw  = SRC.read_text().splitlines()
body = [l.split("//")[0].rstrip() for l in raw]

# the fold must already be the four-halfword rotation
exts = [l for l in body if re.match(r"\s*ext\s", l, re.I)]
assert len(exts) == 32, f"expected 32 ext, found {len(exts)}"
for l in exts:
    m = re.match(r"\s*ext\s+v(\d+)\.16B,\s*v(\d+)\.16B,\s*v(\d+)\.16B,\s*#8\s*$", l, re.I)
    assert m and m.group(2) == m.group(3), f"not a four-halfword self-rotate: {l}"

UMOV = re.compile(r"^\s*umov\s+w(\d+),\s*v(\d+)\.h\[(\d+)\]\s*$")
STRH = re.compile(r"^\s*strh\s+w(\d+),\s*\[x0(?:,\s*#(\d+))?\]\s*$")

held, store_at = {}, {}
umovs = strhs = 0
for i, l in enumerate(body):
    m = UMOV.match(l)
    if m:
        held[m.group(1)] = (int(m.group(2)), int(m.group(3)), i); umovs += 1; continue
    m = STRH.match(l)
    if not m: continue
    gpr, off = m.group(1), int(m.group(2) or 0)
    vreg, lane, at = held.pop(gpr)
    k, r = divmod(off // 2, STRIDE)
    assert r % DEG == 0 and r // DEG == lane, f"lane/s_local mismatch at {l}: r={r} lane={lane}"
    strhs += 1
    if k not in {kk for _, kk in store_at.values()}:
        store_at[at] = (vreg, k); continue
    first = min(j for j, (_, kk) in store_at.items() if kk == k)
    assert store_at[first][0] == vreg, f"group {k} extracted from more than one register"

out = []
for i, l in enumerate(body):
    if i in store_at:
        vreg, k = store_at[i]
        out.append(f"        str d{vreg}, [x0, #{2 * STRIDE * k}]"); continue
    if UMOV.match(l) or STRH.match(l): continue
    out.append(l)

assert umovs == 128 and strhs == 128, (umovs, strhs)
assert {k for _, k in store_at.values()} == set(range(32)), sorted({k for _, k in store_at.values()})
assert not held, held

hdr = ("/* NTRU+1152 invntt16_asm in the (component, half) lane basis.\n"
       " * Generated by gt1152-p67-main-lane-basis/generate_main.py; do not edit.\n"
       " * The inner four lanes become the four components instead of four s\n"
       " * values, so each output group is four consecutive halfwords and its\n"
       " * 4 UMOV + 4 STRH collapse to one STR D.  The terminal table is unchanged:\n"
       " * every row is [A,A,A,A,B,B,B,B], so the constant depends on `half` alone.\n"
       " * The caller must supply the scratch packed as lane = 4*half + component.\n"
       " */\n")
Path(HERE / "invntt16_lane.S").write_text(hdr + "\n".join(out) + "\n")
n = len([l for l in out if re.match(r"\s+[a-z]", l)])
print(f"  invntt16_lane.S: {n} instructions "
      f"(was {len([l for l in body if re.match(r'^\s+[a-z]', l)])}; "
      f"-{umovs} umov -{strhs} strh +{len(store_at)} str d)")
