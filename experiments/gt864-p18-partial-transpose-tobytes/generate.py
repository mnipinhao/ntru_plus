#!/usr/bin/env python3
"""Generate exact P18 class-local partial-transpose ToBytes candidates."""

from __future__ import annotations

import hashlib
import importlib.util
import json
from collections import Counter
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BUILD = HERE / "build"
P14 = ROOT / "experiments/gt864-p14-class-tbl-tobytes/generate.py"


def load_p14():
    spec = importlib.util.spec_from_file_location("p14_generate", P14)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def mappings():
    p14 = load_p14()
    full = p14.exact_map()
    path, classes = p14.class_path(full[:432])
    states = p14.build_slots(path)
    return full, path, classes, states


def output_edges(forward: list[int], output: int):
    result = {}
    for output_lane in range(8):
        source_q, source_lane = divmod(forward[8 * output + output_lane], 8)
        result[source_q] = (output_lane, source_lane)
    assert len(result) == 8
    return result


def class_plan(forward, sources, outputs):
    first = output_edges(forward, outputs[0])
    rows = sorted(sources, key=lambda source: first[source][0])
    plans = []
    rotations = None
    for output in outputs:
        edges = output_edges(forward, output)
        assert [edges[source][0] for source in rows] == list(range(8))
        column = Counter(edges[source][1] for source in rows).most_common(1)[0][0]
        here = tuple((edges[source][1] - column) % 8 for source in rows)
        if rotations is None:
            rotations = here
        assert here == rotations
        plans.append({"output": output, "column": column})
    assert rotations is not None
    assert sum(amount != 0 for amount in rotations) in (2, 4)
    return rows, rotations, plans


def stage2_dependencies(columns):
    return sorted({column % 4 + half for column in columns for half in (0, 4)})


def emit(mode, forward, path, classes, states):
    assert mode in ("full", "small")
    public = f"gt864_p18_tobytes_{mode}_asm"
    top = f"p18_top_{mode}"
    lines = [
        "/* Generated by P18 generate.py; do not edit. */",
        "#ifdef __APPLE__", f"#define {public} _{public}", "#endif",
        ".text", ".p2align 4", f".global {public}", f"{public}:",
        " stp x29,x30,[sp,#-112]!", " mov x29,sp", " stp x19,x20,[sp,#16]",
        " stp d8,d9,[sp,#32]", " stp d10,d11,[sp,#48]",
        " stp d12,d13,[sp,#64]", " stp d14,d15,[sp,#80]",
        " mov x19,x0", " mov x20,x1", f" bl {top}",
        " add x0,x19,#648", " add x1,x20,#864", f" bl {top}",
    ]
    lines += [f" movi v{index}.16b,#0" for index in range(32)]
    lines += [
        " ldp d8,d9,[sp,#32]", " ldp d10,d11,[sp,#48]",
        " ldp d12,d13,[sp,#64]", " ldp d14,d15,[sp,#80]",
        " ldp x19,x20,[sp,#16]", " ldp x29,x30,[sp],#112", " ret",
        ".p2align 4", f"{top}:", " adr x2,p18_pack_index_" + mode,
        " ldr q26,[x2]", " mov w8,#3457", " dup v27.8h,w8",
    ]
    if mode == "full":
        lines += [" mov w8,#9", " dup v28.8h,w8"]
    lines += [" mov x5,x0", " add x6,x0,#216", " add x7,x0,#432"]

    previous = None
    total_ext = total_trn = total_load = 0
    class_records = []
    for class_index, sources in enumerate(path):
        outputs = sorted(classes[sources])
        state = states[class_index]
        rows, rotations, plans = class_plan(forward, sources, outputs)
        slot_for_source = {source: slot for slot, source in enumerate(state)}
        lines.append(f"p18_{mode}_class_{class_index}_start:")
        for slot, source in enumerate(state):
            if previous is None or previous[slot] != source:
                lines.append(f" ldr q{slot},[x1,#{16 * source}]")
                total_load += 1

        for pair in range(4):
            pair_regs = []
            next_rotation = 24
            for row in (2 * pair, 2 * pair + 1):
                register = slot_for_source[rows[row]]
                if rotations[row]:
                    lines.append(
                        f" ext v{next_rotation}.16b,v{register}.16b,v{register}.16b,#{2 * rotations[row]}")
                    pair_regs.append(next_rotation)
                    next_rotation += 1
                    total_ext += 1
                else:
                    pair_regs.append(register)
            a, b = pair_regs
            lines.append(f" trn1 v{8 + 2 * pair}.8h,v{a}.8h,v{b}.8h")
            lines.append(f" trn2 v{9 + 2 * pair}.8h,v{a}.8h,v{b}.8h")
            total_trn += 2

        columns = [plan["column"] for plan in plans]
        needed = stage2_dependencies(columns)
        for index in needed:
            group = (index // 4) * 4
            local = index % 4
            source_a = 8 + group + local % 2
            source_b = source_a + 2
            mnemonic = "trn1" if local < 2 else "trn2"
            lines.append(
                f" {mnemonic} v{16 + index}.4s,v{source_a}.4s,v{source_b}.4s")
            total_trn += 1

        for result_slot, plan in enumerate(plans):
            column = plan["column"]
            low = column % 4
            mnemonic = "trn1" if column < 4 else "trn2"
            outreg = 8 + result_slot
            lines.append(
                f" {mnemonic} v{outreg}.2d,v{16 + low}.2d,v{20 + low}.2d")
            total_trn += 1
            if mode == "full":
                lines += [
                    f" sqrdmulh v29.8h,v{outreg}.8h,v28.8h",
                    f" mls v{outreg}.8h,v29.8h,v27.8h",
                ]
            lines += [
                f" sshr v29.8h,v{outreg}.8h,#15",
                " and v29.16b,v29.16b,v27.16b",
                f" add v{outreg}.8h,v{outreg}.8h,v29.8h",
                f" uzp1 v30.8h,v{outreg}.8h,v{outreg}.8h",
                f" uzp2 v31.8h,v{outreg}.8h,v{outreg}.8h",
                " shl v29.8h,v31.8h,#12",
                " orr v30.16b,v30.16b,v29.16b",
                " ushr v31.8h,v31.8h,#4",
                f" tbl v{outreg}.16b,{{v30.16b,v31.16b}},v26.16b",
            ]
            output = plan["output"]
            base = ("x5", "x6", "x7")[output // 18]
            offset = 12 * (output % 18)
            lines += [
                f" stur d{outreg},[{base},#{offset}]",
                f" mov x9,v{outreg}.d[1]",
                f" stur w9,[{base},#{offset + 8}]",
            ]
        lines.append(f"p18_{mode}_class_{class_index}_end:")
        class_records.append({
            "class": class_index, "sources": list(sources), "outputs": outputs,
            "rows": rows, "row_rotations": list(rotations), "columns": columns,
            "stage2": needed,
        })
        previous = state

    lines += [" ret", ".p2align 4", f"p18_pack_index_{mode}:",
              " .byte 0,1,16,2,3,18,4,5,20,6,7,22,255,255,255,255", ""]
    assert total_load == 64
    assert total_ext == 40
    assert total_trn == 278
    return "\n".join(lines), {
        "mode": mode, "source_q_loads_per_top": total_load,
        "ext_per_top": total_ext, "trn_per_top": total_trn,
        "route_instructions_per_top": total_ext + total_trn,
        "p9_route_instructions_per_top": 54 + 432,
        "route_instruction_delta_per_complete_call":
            2 * (total_ext + total_trn - 54 - 432),
        "classes": class_records,
    }


def emit_header(forward):
    lines = ["#ifndef GT864_P18_MAP_H", "#define GT864_P18_MAP_H",
             "#include <stdint.h>", "static const uint16_t p18_map[864]={"]
    for start in range(0, 864, 12):
        lines.append(" " + ",".join(map(str, forward[start:start + 12])) + ",")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main():
    forward, path, classes, states = mappings()
    BUILD.mkdir(exist_ok=True)
    reports = []
    for mode in ("full", "small"):
        source, report = emit(mode, forward[:432], path, classes, states)
        (BUILD / f"p18_tobytes_{mode}.S").write_text(source)
        reports.append(report)
    (BUILD / "p18_map.h").write_text(emit_header(forward))
    digest = hashlib.sha256(b"".join(value.to_bytes(2, "little")
                                      for value in forward)).hexdigest()
    result = {"experiment": "GT864-P18-PARTIAL-TRANSPOSE-TOBYTES-20260912",
              "map_sha256": digest, "map_bijection": sorted(forward) == list(range(864)),
              "reports": reports, "register_peak": 32, "spill_allowed": False}
    assert digest == "087b7193886e9f3e33ac457452642d64ae70ec780a0961d10036c8e5530da270"
    (BUILD / "model.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
