"""Generate codec_pairs.h: the group-pair tiling of the NTRU+1152 codec.

Measured structure (verified exhaustively here): the 36 Good-Thomas groups
split into 18 pairs (g, g+9), and for every pair and every lane k the two
leaves are consecutive with the first one even.  A leaf is four coefficients,
so two consecutive leaves are eight coefficients, which the 12-bit wire format
stores as exactly twelve contiguous bytes at offset 6*m.  m even makes every
such block 12-byte aligned, so the 144 blocks tile the 1728-byte output with no
overlap and no gap.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
PERM = [int(x) for x in (HERE.parent / "gt1152-p03-gt-layout/perm864.txt").read_text().split()]
assert sorted(PERM) == list(range(288))

pairs = [(g, g + 9) for g in range(36) if g % 18 < 9]
assert len(pairs) == 18
assert sorted(x for p in pairs for x in p) == list(range(36))
for g, h in pairs:
    for k in range(8):
        m = PERM[8 * g + k]
        assert PERM[8 * h + k] == m + 1 and m % 2 == 0, (g, k)

blocks = sorted(6 * PERM[8 * g + k] for g, _ in pairs for k in range(8))
assert blocks == list(range(0, 1728, 12)), "the 144 blocks must tile the output"

out = ['/* Generated by generate_pairs.py.  Do not edit. */',
       '#ifndef NTRUPLUS1152_CODEC_PAIRS_H',
       '#define NTRUPLUS1152_CODEC_PAIRS_H',
       '',
       '#define CODEC_PAIRS 18',
       '',
       '/* First group of each pair; the second is always this plus nine. */',
       'static const unsigned char pair_group[CODEC_PAIRS] = {',
       '    ' + ', '.join(str(g) for g, _ in pairs) + '',
       '};',
       '',
       '/* Wire byte offset of the twelve-byte block held by lane k of pair p. */',
       'static const unsigned short pair_wire[CODEC_PAIRS][8] = {']
for g, _ in pairs:
    out.append('    {' + ', '.join(f'{6 * PERM[8 * g + k]:4d}' for k in range(8)) + '},')
out += ['};', '', '#endif', '']
(HERE / "codec_pairs.h").write_text('\n'.join(out))
print("wrote codec_pairs.h:", len(pairs), "pairs,", len(blocks), "blocks tiling 0..1728 exactly")
