#!/usr/bin/env python3
"""Emit NTRU+864's invntt16_asm with the inner four lanes holding four
consecutive output positions p = 3j + c instead of four j at one c.

The kernel body and its tables are untouched: invntt16_main_constants is
[A,A,A,A,B,B,B,B] in 64 of 64 rows and invntt16_main_scale in 32 of 32, so the
twiddles are blind to what the inner lanes carry.  Only the output changes.

Today a group's four outputs are at 3*lane within it, never adjacent, so each
costs a UMOV and a STRH.  In the new packing they are p..p+3 -- four contiguous
halfwords -- and collapse to one STR D at 2*27*group.

The store is emitted where the UMOV was, not where the STRH was: the scheduler
reuses these registers hard and several are overwritten in between.
"""
import re, sys
from pathlib import Path
SRC = Path(sys.argv[1]); DST = Path(sys.argv[2])
STRIDE = 27            # halfwords between consecutive groups
DEG    = 3             # base-ring components

raw  = SRC.read_text().splitlines()
body = [l.split("//")[0].rstrip() for l in raw]

exts = [l for l in body if re.match(r"\s*ext\s", l, re.I)]
assert len(exts) == 32, f"expected 32 ext, found {len(exts)}"
for l in exts:
    m = re.match(r"\s*ext\s+v(\d+)\.16B,\s*v(\d+)\.16B,\s*v(\d+)\.16B,\s*#8\s*$", l, re.I)
    assert m and m.group(2) == m.group(3), f"not a four-halfword self-rotate: {l}"

UMOV = re.compile(r"^\s*umov\s+w(\d+),\s*v(\d+)\.h\[(\d+)\]\s*$")
STRH = re.compile(r"^\s*strh\s+w(\d+),\s*\[x0(?:,\s*#(\d+))?\]\s*$")

held, store_at = {}, {}
umovs = strhs = 0
for i, l in enumerate(body):
    m = UMOV.match(l)
    if m:
        held[m.group(1)] = (int(m.group(2)), int(m.group(3)), i); umovs += 1; continue
    m = STRH.match(l)
    if not m: continue
    gpr, off = m.group(1), int(m.group(2) or 0)
    vreg, lane, at = held.pop(gpr)
    k, r = divmod(off // 2, STRIDE)
    assert r % DEG == 0 and r // DEG == lane, f"lane/j mismatch at {l}: r={r} lane={lane}"
    strhs += 1
    if k not in {kk for _, kk in store_at.values()}:
        store_at[at] = (vreg, k); continue
    first = min(j for j, (_, kk) in store_at.items() if kk == k)
    assert store_at[first][0] == vreg, f"group {k} extracted from more than one register"

# A group is 2*27 = 54 bytes on from the last, and STR D scales its immediate
# by eight, so [x0, #54k] does not encode.  54*4 = 216 does, so four bases --
# x0 itself and three more, one per residue of k mod 4 -- reach every group
# with a plain immediate and leave the scheduler free to order the stores.
BASES = ["x0", "x5", "x6", "x9"]
# x5 and the rest are free only once the UMOV/STRH pairs are gone; they were the
# extraction scratch.  Check what survives, not what was there.
survivors = "\n".join(l for i, l in enumerate(body)
                      if not (UMOV.match(l) or STRH.match(l)))
for b in BASES[1:]:
    assert not re.search(rf"\b[wx]{b[1:]}\b", survivors), f"{b} is live"

out, seeded = [], False
for i, l in enumerate(body):
    if i in store_at:
        vreg, k = store_at[i]
        r, m = k % 4, k // 4
        out.append(f"        str d{vreg}, [{BASES[r]}, #{216 * m}]"); continue
    if UMOV.match(l) or STRH.match(l): continue
    out.append(l)
    if not seeded and l.strip().endswith("_slothy_start:"):
        out += [f"        add {b}, x0, #{54 * r}" for r, b in enumerate(BASES) if r]
        seeded = True
assert seeded, "no slothy_start anchor to seed the bases after"

assert umovs == 128 and strhs == 128, (umovs, strhs)
assert {k for _, k in store_at.values()} == set(range(32)), sorted({k for _, k in store_at.values()})
assert not held, held

hdr = ("/* NTRU+864 invntt16_asm with the inner four lanes holding four consecutive\n"
       " * output positions p = 3j + c, generated by gen16.py; do not edit.\n"
       " * A group's four outputs become four contiguous halfwords and its\n"
       " * 4 UMOV + 4 STRH collapse to one STR D.  The tables are unchanged:\n"
       " * invntt16_main_constants is [A,A,A,A,B,B,B,B] in all 64 rows, so the\n"
       " * twiddles do not depend on what the inner lanes carry.\n"
       " * The caller must supply the scratch packed as lane = (p - 4*call) and\n"
       " * pass x0 = out + 8*call.\n"
       " */\n")
DST.write_text(hdr + "\n".join(out) + "\n")
n = len([l for l in out if re.match(r"\s+[a-z]", l)])
print(f"  {DST.name}: {n} 條 (原 {len([l for l in body if re.match(r'^\s+[a-z]', l)])}; "
      f"-{umovs} umov -{strhs} strh +{len(store_at)} str d)")
