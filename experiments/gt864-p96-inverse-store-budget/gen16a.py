#!/usr/bin/env python3
"""Emit NTRU+864's invntt16_asm storing straight from the vector lanes.

The kernel extracts each output with UMOV into one of four general registers
and then STRH it out: 128 pairs per call, 768 UMOV over the six calls, all
funnelled through those four registers.  ST1 {v.H}[lane] writes a lane to
memory directly, so the round trip and the register recycling both go.

It has no immediate-offset form, so a group needs a base; its four outputs sit
three halfwords apart, which the register post-index supplies.  A group costs
one ADD and four ST1 in place of four UMOV and four STRH.

This leaves the lane packing alone -- it is the half of P95 that does not push
work back into packed_i9.
"""
import re, sys
from pathlib import Path
SRC, DST = Path(sys.argv[1]), Path(sys.argv[2])
STRIDE, DEG = 27, 3
BASES, STEP = ["x5", "x6"], "x9"

raw  = SRC.read_text().splitlines()
body = [l.split("//")[0].rstrip() for l in raw]
UMOV = re.compile(r"^\s*umov\s+w(\d+),\s*v(\d+)\.h\[(\d+)\]\s*$")
STRH = re.compile(r"^\s*strh\s+w(\d+),\s*\[x0(?:,\s*#(\d+))?\]\s*$")

survivors = "\n".join(l for l in body if not (UMOV.match(l) or STRH.match(l)))
for r in BASES + [STEP]:
    assert not re.search(rf"\b[wx]{r[1:]}\b", survivors), f"{r} is live"

held, groups = {}, {}          # group -> (vreg, {lane}, last umov index)
for i, l in enumerate(body):
    m = UMOV.match(l)
    if m:
        held[m.group(1)] = (int(m.group(2)), int(m.group(3)), i); continue
    m = STRH.match(l)
    if not m: continue
    vreg, lane, at = held.pop(m.group(1))
    k, r = divmod(int(m.group(2) or 0) // 2, STRIDE)
    assert r % DEG == 0 and r // DEG == lane, f"lane/j mismatch: {l}"
    v, lanes, last = groups.get(k, (vreg, set(), -1))
    assert v == vreg, f"group {k} extracted from more than one register"
    groups[k] = (vreg, lanes | {lane}, max(last, at))

assert not held and set(groups) == set(range(32))
assert all(lanes == {0, 1, 2, 3} for _, lanes, _ in groups.values())
emit = {last: (k, vreg) for k, (vreg, _, last) in groups.items()}
assert len(emit) == 32, "two groups want to be emitted at the same instruction"

out, seeded = [], False
for i, l in enumerate(body):
    if i in emit:
        k, vreg = emit[i]
        b = BASES[k % len(BASES)]
        out.append(f"        add {b}, x0, #{2 * STRIDE * k}")
        out += [f"        st1 {{v{vreg}.H}}[{n}], [{b}], {STEP}" for n in range(4)]
        continue
    if UMOV.match(l) or STRH.match(l): continue
    out.append(l)
    if not seeded and l.strip().endswith("_slothy_start:"):
        out.append(f"        mov {STEP}, #{2 * DEG}"); seeded = True
assert seeded

DST.write_text(
    "/* NTRU+864 invntt16_asm storing from the vector lanes, generated by\n"
    " * gen16a.py; do not edit.  Each group's four outputs leave as four\n"
    " * ST1 {v.H}[lane] off a post-incremented base instead of four UMOV and\n"
    " * four STRH through a recycled general register.  Layout unchanged.\n"
    " */\n" + "\n".join(out) + "\n")
n0 = len([l for l in body if re.match(r"^\s+[a-z]", l)])
n1 = len([l for l in out  if re.match(r"^\s+[a-z]", l)])
print(f"  {DST.name}: {n1} 條 (原 {n0}, 每次呼叫省 {n0 - n1}, 六次共 {6 * (n0 - n1)})")
