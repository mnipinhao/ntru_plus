"""Generate NTRU+1152's fused SHAKE256 kernels from NTRU+864's.

NTRU+864's P53 and P55 produced `ntruplus_hash_g_fused_aarch64` and
`ntruplus_hash_f_fused_aarch64` by adapting NTRU+768's, with anchored
replacements for the size-dependent parts.  This does the same for 1152.

Both kernels hash a one-byte domain prefix followed by the message -- 0x01 for
hash_g, 0x00 for hash_f -- with the
whole 25-word Keccak state live in registers: there is no state array, and the
domain byte is folded into the first word with `lsl #8; orr #1` rather than
memcpy'ing the message to prepend it.

What is size-dependent, and what it becomes:

                       768        864        1152
  input + prefix      1153       1297        1729
  full blocks            8          9          12      (rate 136)
  tail bytes            65         73          97
  output               192        216         288  (hash_g)
  squeeze blocks     1 + 56     1 + 80      2 + 16

1152 is the first of the three to need **two** full squeeze blocks, so the
dispatch gains a range test and `Lhash_g_squeeze_first` increments the stage
counter instead of assigning it.
"""
import re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "ntruplus-GT-Production/Additional_Implementation/aarch64/NTRU+864/keccakf1600.S"

RATE = 136
# lane index -> register, read off the full-block absorb
LANE = ["x1","x6","x11","x16","x21","x2","x7","x12","x17","x22",
        "x3","x8","x13","x28","x23","x4","x9"]

IN_864, IN_1152 = 1 + 1296, 1 + 1728
BLK_864, TAIL_864 = divmod(IN_864, RATE)
BLK_1152, TAIL_1152 = divmod(IN_1152, RATE)
assert (BLK_864, TAIL_864) == (9, 73) and (BLK_1152, TAIL_1152) == (12, 97)

text = SRC.read_text()


def once(old, new, label, count=1):
    global text
    n = text.count(old)
    if n != count:
        sys.exit(f"anchor drift for {label}: found {n}, expected {count}")
    text = text.replace(old, new)


def absorb(lane, off):
    return f"        ldr x26, [x0, #{off}]\n        eor {LANE[lane]}, {LANE[lane]}, x26\n"


# ---- 1. the tail absorb, in both kernels -----------------------------------
# 864 absorbs nine whole words then one byte into lane 9; 1152 absorbs twelve
# then one byte into lane 12.
old_tail = (absorb(8, 64) +
            "        ldrb w26, [x0, #72]\n"
            "        orr x26, x26, #0x1f00\n"
            f"        eor {LANE[9]}, {LANE[9]}, x26\n")
new_tail = (absorb(8, 64) + absorb(9, 72) + absorb(10, 80) + absorb(11, 88) +
            "        ldrb w26, [x0, #96]\n"
            "        orr x26, x26, #0x1f00\n"
            f"        eor {LANE[12]}, {LANE[12]}, x26\n")
once(old_tail, new_tail, "tail absorb", count=2)

# ---- 2. block counts in both dispatches ------------------------------------
for k in ("f", "g"):
    once(f"        cmp x0, #{BLK_864}\n        b.lo Lhash_{k}_full\n"
         f"        b.eq Lhash_{k}_tail\n",
         f"        cmp x0, #{BLK_1152}\n        b.lo Lhash_{k}_full\n"
         f"        b.eq Lhash_{k}_tail\n",
         f"hash_{k} block count")

# ---- 3. the stage the tail hands to, in both kernels -----------------------
once(f"        mov x26, #{BLK_864 + 1}\n        str x26, [sp, #136]\n",
     f"        mov x26, #{BLK_1152 + 1}\n        str x26, [sp, #136]\n",
     "tail next stage", count=2)

# ---- 4. hash_g: two full squeeze blocks, then sixteen bytes ----------------
# The dispatch tested one value; it now tests a range, and the first squeeze
# increments rather than assigning so it can run twice.
once(f"        cmp x0, #{BLK_864 + 1}\n        b.eq Lhash_g_squeeze_first\n",
     f"        cmp x0, #{BLK_1152 + 3}\n        b.lo Lhash_g_squeeze_first\n",
     "hash_g squeeze dispatch")
once(f"        mov x26, #{BLK_864 + 2}\n        str x26, [sp, #136]\n"
     "        b Lhash_g_live_round\n\nLhash_g_squeeze_last:",
     "        ldr x26, [sp, #136]\n        add x26, x26, #1\n        str x26, [sp, #136]\n"
     "        b Lhash_g_live_round\n\nLhash_g_squeeze_last:",
     "hash_g squeeze counter")
once("Lhash_g_squeeze_last:\n"
     "        ldr x0, [sp, #128]\n"
     "        stp x1, x6, [x0, #0]\n"
     "        stp x11, x16, [x0, #16]\n"
     "        stp x21, x2, [x0, #32]\n"
     "        stp x7, x12, [x0, #48]\n"
     "        stp x17, x22, [x0, #64]\n",
     "Lhash_g_squeeze_last:\n"
     "        ldr x0, [sp, #128]\n"
     "        stp x1, x6, [x0, #0]\n",
     "hash_g final squeeze, 16 bytes")

# ---- 5. the signature comments --------------------------------------------
once("x0=out[216], x1=msg[1296]", "x0=out[288], x1=msg[1728]", "hash_g signature")
once("x0=out[32], x1=msg[1296]", "x0=out[32], x1=msg[1728]", "hash_f signature")

banner = f"""/*
 * NTRU+1152 fused SHAKE256 kernels.  Generated by
 * experiments/gt1152-p32-hash-fused/generate_keccak.py from NTRU+864's
 * keccakf1600.S; do not edit.
 *
 * Size-dependent parts, and nothing else, differ:
 *   input + prefix {IN_864} -> {IN_1152} bytes, so {BLK_864} -> {BLK_1152} full
 *   absorb blocks and a {TAIL_864} -> {TAIL_1152} byte tail;
 *   hash_g output 216 -> 288 bytes, so one full squeeze block plus 80 becomes
 *   two plus 16, which is why the squeeze dispatch became a range test.
 */
"""
(HERE / "keccakf1600.S").write_text(banner + text)
n = sum(1 for l in text.splitlines() if re.match(r"\s+[a-z]", l))
print(f"wrote keccakf1600.S: {n} instructions, {BLK_1152} absorb blocks + "
      f"{TAIL_1152}-byte tail, hash_g squeeze 2x{RATE}+16")
