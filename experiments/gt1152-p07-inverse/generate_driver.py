"""Emit NTRU+1152's invntt_ternary_asm driver from NTRU+864's.

The driver is hand-written assembly, not Slothy output, but it is transcribed
rather than retyped so the transformation is a declared, auditable list rather
than a diff nobody can check.

It must stay assembly: packed_i9 and invntt16_asm clobber v8-v15 (48 and 170
references), so a C driver would violate AAPCS64.  SAVE_PUBLIC preserving
d8-d15 once per public call is exactly why this file exists.
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / \
    "ntruplus-GT-Production/Additional_Implementation/aarch64/NTRU+864/inverse.S"

# Each rule is (exact source line, replacement, why).  Applied in order, and
# every rule must fire at least once or the generator fails.
RULES = [
    ("    sub sp, sp, #1792", "    sub sp, sp, #2304",
     "scratch: 8 banks x 256 + 256 tail"),
    ("    add sp, sp, #1792", "    add sp, sp, #2304", "matching restore"),
    ("    add x9, sp, #1536", "    add x9, sp, #2048", "tail padding base"),
    ("    add x1, x25, #1536", "    add x1, x25, #2048", "tail scratch base"),
    ("    mov x8, #6\n    madd x1, x26, x8, x1",
     "    mov x8, #8\n    madd x1, x26, x8, x1",
     "tail lane stride: 2 tops x 4 branches fills all eight lanes"),
    ("    mov x8, #864\n    madd x2, x26, x8, x20",
     "    mov x8, #1152\n    madd x2, x26, x8, x20",
     "GT input top stride"),
    ("    mov x8, #48\n    madd x2, x28, x8, x2",
     "    mov x8, #64\n    madd x2, x28, x8, x2",
     "GT input half-column stride"),
    ("    cmp x27, #3\n    b.ne .Lp8inv_component",
     "    cmp x27, #4\n    b.ne .Lp8inv_component",
     "packed_i9 component count"),
    ("    mov x8, #24\n    madd x0, x27, x8, x0",
     "    mov x8, #32\n    madd x0, x27, x8, x0",
     "natural-order half stride: 4 m-values x 4 branches x 2 bytes"),
    ("    cmp x26, #3\n    b.ne .Lp8inv_main_component",
     "    cmp x26, #4\n    b.ne .Lp8inv_main_component",
     "invntt16 component count"),
    ("    add x0, x19, #48", "    add x0, x19, #64",
     "tail output base: 4*8*2 bytes"),
    ("    mov x10, #14", "    mov x10, #18",
     "wipe iterations: 18 x 128 = 2304"),
    ("    // Exact 1792-byte wipe, 128 bytes per fixed iteration.",
     "    // Exact 2304-byte wipe, 128 bytes per fixed iteration.",
     "comment"),
]


def slice_between(text, start, end):
    i = text.index(start)
    j = text.index(end, i)
    return text[i:j]


def main():
    text = SRC.read_text()

    macros = slice_between(text, ".macro SAVE_PUBLIC", ".macro COPY_TRIPLE")
    body = slice_between(text, ".global C(invntt_ternary_asm)", "#endif")

    applied = []
    for old, new, why in RULES:
        if old not in body:
            raise SystemExit(f"rule did not match: {why}\n{old!r}")
        count = body.count(old)
        body = body.replace(old, new)
        applied.append({"why": why, "occurrences": count})

    # Nothing else may carry an 864-specific size.
    leftovers = sorted({int(m) for m in re.findall(r"#(\d+)", body)}
                       & {1792, 1536, 864, 48, 24, 14})
    if leftovers:
        # 48 and 24 legitimately survive as SAVE_PUBLIC frame offsets only,
        # which live in the macro block, not here.
        raise SystemExit(f"unconverted 864 constants remain in the body: {leftovers}")

    out = [
        "/* NTRU+1152 fused inverse-to-ternary driver.",
        " *",
        " * Generated by generate_driver.py from NTRU+864's inverse.S; do not edit.",
        " * This stays assembly on purpose: packed_i9 and invntt16_asm clobber",
        " * v8-v15, so SAVE_PUBLIC must preserve d8-d15 around them and a C driver",
        " * would violate AAPCS64.  invntt16_tail_asm is a C function here and is",
        " * called through the ordinary AAPCS64 argument registers.",
        " */",
        "#ifdef __APPLE__",
        "#define C(name) _##name",
        "#else",
        "#define C(name) name",
        "#endif",
        ".text",
        "",
        macros.rstrip(),
        "",
        body.rstrip(),
        "",
        "#if defined(__ELF__)",
        '.section .note.GNU-stack,"",%progbits',
        "#endif",
        "",
    ]
    dst = HERE.parent / "gt1152-p08-inverse-port/inverse_ntt.S"
    dst.parent.mkdir(exist_ok=True)
    dst.write_text("\n".join(out))

    (dst.parent / "driver-rules.json").write_text(
        json.dumps({"source": str(SRC.relative_to(HERE.parents[1])),
                    "rules": applied}, indent=2) + "\n")
    print(f"wrote {dst.relative_to(HERE.parents[1])}: {len(RULES)} declared rules, "
          f"all matched")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
