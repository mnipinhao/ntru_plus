"""Emit NTRU+1152's inverse9.S, inverse16.S and crepmod3_raw.S from NTRU+864's.

These are immediate remaps: the instruction multiset is preserved exactly, so
the NTRU+864 A76 schedule stays legal.  G6a established that this holds for
packed_i9 and invntt16_asm but NOT for invntt16_tail_asm, which is why the tail
is absent here and written in C instead.

Every file is checked after rewriting: same instruction multiset, and only the
declared offsets changed.
"""

import json
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
GT864 = HERE.parents[1] / \
    "ntruplus-GT-Production/Additional_Implementation/aarch64/NTRU+864"
DST = HERE.parent / "gt1152-p08-inverse-port"

report = []


def mnemonics(text):
    c = Counter()
    for line in text.splitlines():
        line = line.split("//")[0].strip()
        if not line or line.startswith((".", "/*", "*", "#")) or line.endswith(":"):
            continue
        m = re.match(r"([a-z][a-z0-9_.]*)", line)
        if m:
            c[m.group(1)] += 1
    return c


def strip_slothy_annotations(text):
    """Drop Slothy's cycle map and its commented copy of the pre-schedule order.

    Those annotations describe the schedule Slothy produced for NTRU+864.  No
    solver was run for 1152, so carrying them over -- edited or not -- would
    document a schedule that does not exist.  The live-in/live-out contract
    above _slothy_start is kept; everything after it is stripped to bare code.
    """
    out, past_start = [], False
    for line in text.splitlines():
        if not past_start:
            out.append(line)
            if "_slothy_start:" in line:
                past_start = True
            continue
        code = line.split("//")[0].rstrip()
        if code.strip():
            out.append(code)
        elif not line.strip():
            out.append("")
    return "\n".join(out) + "\n"


def remap(name, pattern, scale, why):
    """Rewrite [<base>, #imm] offsets matching `pattern` by `scale`."""
    src = strip_slothy_annotations((GT864 / name).read_text())
    changed = []

    def sub(m):
        old = int(m.group("imm"))
        num, den = scale
        assert old * num % den == 0, f"{name}: offset {old} does not scale exactly"
        new = old * num // den
        if new != old:
            changed.append((old, new))
        return m.group(0).replace(f"#{old}", f"#{new}")

    out = re.sub(pattern, sub, src)

    diff_lines = sum(1 for a, b in zip(src.splitlines(), out.splitlines()) if a != b)
    header = (f"/* NTRU+1152 {name}, generated by generate_kernels.py; do not edit.\n"
              f" * Immediate remap of NTRU+864's {name} ({why}).\n"
              " * The instruction multiset is preserved, so NTRU+864's A76 schedule\n"
              " * stays legal -- but no solver was run for 1152, so Slothy's cycle\n"
              " * annotations were stripped rather than carried over.\n"
              " * The coefficient-range comment below is NTRU+864's; for 1152 it is\n"
              " * inherited under decision D7 and must be re-verified.\n"
              " */\n")
    out = header + out
    before, after = mnemonics(src), mnemonics(out)
    assert before == after, f"{name}: instruction multiset changed"

    (DST / name).write_text(out)
    report.append({
        "file": name, "why": why, "offsets_changed": len(changed),
        "distinct": sorted({c for c in changed})[:6],
        "lines_changed": diff_lines,
        "instruction_multiset_preserved": True,
        "instructions": sum(before.values()),
    })
    print(f"  {name:20s} {len(changed):4d} offsets, {diff_lines:4d} lines, "
          f"{sum(before.values())} instructions, multiset preserved")


DST.mkdir(exist_ok=True)

# packed_i9: only x2 carries a layout stride, the Good-Thomas row pitch.
remap("inverse9.S",
      r"\[\s*x2\s*,\s*#(?P<imm>\d+)\s*\]", (4, 3),
      "Good-Thomas row stride 96 -> 128 bytes")

# invntt16_asm: every strh offset is 6m, the branch being folded into the base
# pointer by the driver, so they scale exactly by 8/6.
remap("inverse16.S",
      r"(?<=strh )(?:\w+,\s*)\[\s*x0\s*,\s*#(?P<imm>\d+)\s*\]", (4, 3),
      "natural-order store pitch 6m -> 8m")

# crepmod3_raw: one loop count, 27 x 32 = 864 becomes 36 x 32 = 1152.
src = (GT864 / "crepmod3_raw.S").read_text()
assert "mov x8, #27" in src
out = src.replace("mov x8, #27", "mov x8, #36")
assert mnemonics(src) == mnemonics(out)
(DST / "crepmod3_raw.S").write_text(out)
report.append({"file": "crepmod3_raw.S", "why": "loop count 27 -> 36",
               "offsets_changed": 0, "lines_changed": 1,
               "instruction_multiset_preserved": True,
               "instructions": sum(mnemonics(src).values())})
print(f"  {'crepmod3_raw.S':20s} loop 27 -> 36, multiset preserved")

(DST / "kernel-remap-report.json").write_text(json.dumps(report, indent=2) + "\n")
print("\n-> kernel-remap-report.json")
