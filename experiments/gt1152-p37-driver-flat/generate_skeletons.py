"""Skeleton variants of both drivers: every `bl` and the wipe removed, so the
difference isolates the address arithmetic, the loop bookkeeping and the
prologue.  Static `bl` counts differ by construction -- the loop-nest driver
has four call sites reached 26 times, the flattened one has 26 call sites."""
import pathlib
import re

WIPE_RE = re.compile(r'    movi v0\.16b, #0\n    mov x9, sp\n    mov x10, #18\n'
                     r'\.Lp13inv_wipe(?:_\w+)?:\n(?:    stp q0, q0, \[x9\], #32\n){4}'
                     r'    subs x10, x10, #1\n    b\.ne \.Lp13inv_wipe(?:_\w+)?\n')
EXPECT_BL = {"inverse_ntt_ref.S": 4, "inverse_ntt.S": 26}

out = []
for src, entry, sfx in (("inverse_ntt_ref.S", "invntt_ternary_ref", "ref"),
                        ("inverse_ntt.S", "C(invntt_ternary_asm)", "flat")):
    t = pathlib.Path(src).read_text().split("#if defined(__ELF__)")[0]
    t = t.replace(entry, f"skel_{sfx}")
    for lbl in ("Lp8inv_top", "Lp8inv_component", "Lp8inv_i9",
                "Lp8inv_main_component", "Lp8inv_main", "Lp13inv_wipe"):
        t = re.sub(rf'\b{lbl}(_ref)?\b', lambda m: m.group(0) + "_s", t)
    t = t.replace("SAVE_PUBLIC", f"SAVE_P_{sfx}").replace("RESTORE_PUBLIC", f"RESTORE_P_{sfx}")
    n = len(WIPE_RE.findall(t))
    assert n == 1, f"{src}: wipe anchor found {n}"
    t = WIPE_RE.sub("", t)
    nbl = len(re.findall(r'^    bl .*$', t, re.M))
    assert nbl == EXPECT_BL[src], f"{src}: {nbl} bl, expected {EXPECT_BL[src]}"
    t = re.sub(r'^    bl .*\n', '', t, flags=re.M)
    if out:
        t = re.sub(r'^\.text\n', '', t, flags=re.M)
    out.append(t)

pathlib.Path("skeletons.S").write_text(
    "/* Generated by generate_skeletons.py; do not edit. */\n" + "\n".join(out)
    + '\n#if defined(__ELF__)\n.section .note.GNU-stack,"",%progbits\n#endif\n')
print("wrote skeletons.S: skel_ref (4 bl removed), skel_flat (26 bl removed), "
      "wipe removed from both")
