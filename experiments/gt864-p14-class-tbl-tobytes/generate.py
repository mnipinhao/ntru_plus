#!/usr/bin/env python3
"""Generate the exact P14 class-local TBL4 full/small candidates."""

from __future__ import annotations

import importlib.util
from collections import defaultdict
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
BUILD = HERE / "build"
MAP_SOURCE = ROOT / (
    "ntruplus-ntt-Optimized/Additional_Implementation/aarch64/Experiment/"
    "NTRU+864/good_thomas_campaign/experiments/"
    "gt_fr0_d1_byte_abi_architecture/analyze_architecture.py"
)


def exact_map() -> list[int]:
    spec = importlib.util.spec_from_file_location("p3a", MAP_SOURCE)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    mapping, _ = module.official_map(ROOT)
    shuffle2 = [value for start in range(0, 864, 48)
                for value in module.shuffle2_block(start)]
    result = [mapping[shuffle2[index]] for index in range(864)]
    assert all(result[index + 432] == result[index] + 432
               for index in range(432))
    return result


def class_path(forward: list[int]) -> tuple[list[tuple[int, ...]], dict[tuple[int, ...], list[int]]]:
    classes: dict[tuple[int, ...], list[int]] = defaultdict(list)
    for output_q in range(54):
        sources = tuple(sorted({forward[8 * output_q + lane] // 8
                                for lane in range(8)}))
        assert len(sources) == 8
        classes[sources].append(output_q)
    keys = list(classes)
    assert len(keys) == 15
    count = len(keys)
    dp: dict[tuple[int, int], tuple[int, list[int]]] = {
        (1 << index, index): (0, [index]) for index in range(count)
    }
    for mask in range(1, 1 << count):
        for last in range(count):
            state = dp.get((mask, last))
            if state is None:
                continue
            score, path = state
            for nxt in range(count):
                if mask & (1 << nxt):
                    continue
                overlap = len(set(keys[last]) & set(keys[nxt]))
                key = (mask | (1 << nxt), nxt)
                candidate = (score + overlap, path + [nxt])
                if key not in dp or candidate[0] > dp[key][0]:
                    dp[key] = candidate
    full = (1 << count) - 1
    score, path_indices = max(
        (value for (mask, _), value in dp.items() if mask == full),
        key=lambda value: value[0],
    )
    assert score == 56
    path = [keys[index] for index in path_indices]
    assert 8 + 8 * 14 - score == 64
    return path, classes


def build_slots(path: list[tuple[int, ...]]) -> list[list[int]]:
    states = [list(path[0])]
    for sources in path[1:]:
        previous = states[-1]
        current = previous.copy()
        wanted = set(sources)
        missing = iter(sorted(wanted - set(previous)))
        for slot, value in enumerate(current):
            if value not in wanted:
                current[slot] = next(missing)
        assert set(current) == wanted and len(current) == 8
        states.append(current)
    return states


def make_indices(forward: list[int], path: list[tuple[int, ...]],
                 classes: dict[tuple[int, ...], list[int]],
                 states: list[list[int]]) -> tuple[list[list[list[int]]], dict[int, int]]:
    indices = [[[255] * 16 for _ in range(2)] for _ in range(54)]
    class_for_output: dict[int, int] = {}
    for class_index, sources in enumerate(path):
        slots = states[class_index]
        rank = {source: slot for slot, source in enumerate(slots)}
        for output_q in classes[sources]:
            class_for_output[output_q] = class_index
            for output_lane in range(8):
                source_index = forward[8 * output_q + output_lane]
                source_q, source_lane = divmod(source_index, 8)
                slot = rank[source_q]
                bank = slot // 4
                table_slot = slot % 4
                for byte in range(2):
                    indices[output_q][bank][2 * output_lane + byte] = (
                        16 * table_slot + 2 * source_lane + byte
                    )
    assert sorted(class_for_output) == list(range(54))
    return indices, class_for_output


def emit_header(forward: list[int], indices: list[list[list[int]]]) -> str:
    lines = [
        "/* Generated by generate.py; do not edit. */",
        "#ifndef GT864_P14_TABLES_H",
        "#define GT864_P14_TABLES_H",
        "#include <stdint.h>",
        "static const uint16_t p14_map[864] = {",
    ]
    for start in range(0, 864, 12):
        lines.append("  " + ",".join(map(str, forward[start:start + 12])) + ",")
    lines += ["};", "static const uint8_t p14_indices[54][2][16] __attribute__((aligned(16))) = {"]
    for output in indices:
        lines.append("  {{" + ",".join(map(str, output[0])) + "},{" +
                     ",".join(map(str, output[1])) + "}},")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def emit_source(mode: str, path: list[tuple[int, ...]],
                classes: dict[tuple[int, ...], list[int]],
                states: list[list[int]]) -> str:
    assert mode in ("full", "small")
    suffix = "full" if mode == "full" else "small"
    norm = [
        "static inline int16x8_t normq(int16x8_t x) {",
        " const int16x8_t q=vdupq_n_s16(3457);",
    ]
    if mode == "full":
        norm += [
            " const int16x8_t r=vdupq_n_s16(9);",
            " int16x8_t t=vqrdmulhq_s16(x,r); x=vmlsq_s16(x,t,q);",
        ]
    norm += [
        " return vaddq_s16(x,vandq_s16(vshrq_n_s16(x,15),q));",
        "}",
    ]
    lines = [
        "/* Generated by generate.py; do not edit. */",
        "#include \"p14_tobytes.h\"",
        "#include \"p14_tables.h\"",
        "#include <arm_neon.h>",
        "#include <string.h>",
        "static const uint8_t pack_index[16] __attribute__((aligned(16))) =",
        " {0,1,16,2,3,18,4,5,20,6,7,22,255,255,255,255};",
        *norm,
        "static inline void pack8(uint8_t *out,int16x8_t x) {",
        " uint16x8_t u=vreinterpretq_u16_s16(x);",
        " uint16x8_t e=vuzp1q_u16(u,u),o=vuzp2q_u16(u,u);",
        " uint16x8_t lo=vorrq_u16(e,vshlq_n_u16(o,12)),hi=vshrq_n_u16(o,4);",
        " uint8x16x2_t t={{vreinterpretq_u8_u16(lo),vreinterpretq_u8_u16(hi)}};",
        " uint8x16_t b=vqtbl2q_u8(t,vld1q_u8(pack_index));",
        " uint32_t tail=vgetq_lane_u32(vreinterpretq_u32_u8(b),2);",
        " vst1_u8(out,vget_low_u8(b)); memcpy(out+8,&tail,4);",
        "}",
        f"__attribute__((noinline)) static void p14_class_top_{suffix}(uint8_t *out,const int16_t *in) {{",
        " int16x8_t s0,s1,s2,s3,s4,s5,s6,s7;",
    ]
    previous: list[int] | None = None
    for class_index, sources in enumerate(path):
        slots = states[class_index]
        for slot, source_q in enumerate(slots):
            if previous is None or previous[slot] != source_q:
                lines.append(f" s{slot}=vld1q_s16(in+{8 * source_q});")
        lines += [
            f" uint8x16x4_t bank0_{class_index}={{{{vreinterpretq_u8_s16(s0),vreinterpretq_u8_s16(s1),vreinterpretq_u8_s16(s2),vreinterpretq_u8_s16(s3)}}}};",
            f" uint8x16x4_t bank1_{class_index}={{{{vreinterpretq_u8_s16(s4),vreinterpretq_u8_s16(s5),vreinterpretq_u8_s16(s6),vreinterpretq_u8_s16(s7)}}}};",
        ]
        for output_q in sorted(classes[sources]):
            lines += [
                f" uint8x16_t a{output_q}=vqtbl4q_u8(bank0_{class_index},vld1q_u8(p14_indices[{output_q}][0]));",
                f" uint8x16_t b{output_q}=vqtbl4q_u8(bank1_{class_index},vld1q_u8(p14_indices[{output_q}][1]));",
                f" int16x8_t y{output_q}=vreinterpretq_s16_u8(vorrq_u8(a{output_q},b{output_q}));",
                f" pack8(out+{12 * output_q},normq(y{output_q}));",
            ]
        lines.append(' __asm__ volatile("" : : "w"(s0),"w"(s1),"w"(s2),"w"(s3),"w"(s4),"w"(s5),"w"(s6),"w"(s7));')
        previous = slots
    lines += [
        "}",
        f"void gt864_p14_tobytes_{suffix}_inner(uint8_t out[1296],const int16_t in[864]) {{",
        f" p14_class_top_{suffix}(out,in);",
        f" p14_class_top_{suffix}(out+648,in+432);",
        "}",
        "",
    ]
    return "\n".join(lines)


def emit_public() -> str:
    source = (ROOT / "ntruplus-GT-Production/Additional_Implementation/aarch64/"
              "NTRU+864/p9_tobytes_public.S").read_text()
    source = source.replace("P9_PUBLIC", "P14_PUBLIC")
    source = source.replace("P9_BUILD", "P14_BUILD")
    source = source.replace("gt864_p9_tobytes", "gt864_p14_tobytes")
    source = source.replace("gt864_p9_input_once", "gt864_p14_tobytes")
    return source.replace("P9 public", "P14 public")


def emit_asm(mode: str, path: list[tuple[int, ...]],
             classes: dict[tuple[int, ...], list[int]],
             states: list[list[int]], indices: list[list[list[int]]]) -> str:
    """Emit the fixed-bank instruction DAG; Slothy later schedules class windows."""
    assert mode in ("full", "small")
    name = f"gt864_p14_tobytes_{mode}_asm"
    top = f"p14_top_{mode}"
    lines = [
        "/* Generated fixed-bank P14-B DAG; class windows are Slothy inputs. */",
        "#ifdef __APPLE__",
        f"#define {name} _{name}",
        "#endif",
        ".text", ".p2align 4", f".global {name}", f"{name}:",
        " stp x29,x30,[sp,#-112]!", " mov x29,sp", " stp x19,x20,[sp,#16]",
        " stp d8,d9,[sp,#32]", " stp d10,d11,[sp,#48]",
        " stp d12,d13,[sp,#64]", " stp d14,d15,[sp,#80]",
        " mov x19,x0", " mov x20,x1", f" bl {top}",
        " add x0,x19,#648", " add x1,x20,#864", f" bl {top}",
    ]
    lines += [f" movi v{i}.16b,#0" for i in range(32)]
    lines += [
        " ldp d8,d9,[sp,#32]", " ldp d10,d11,[sp,#48]",
        " ldp d12,d13,[sp,#64]", " ldp d14,d15,[sp,#80]",
        " ldp x19,x20,[sp,#16]", " ldp x29,x30,[sp],#112", " ret",
        ".p2align 4", f"{top}:",
        f" adr x2,p14_indices_{mode}", f" adr x3,p14_pack_index_{mode}",
        " ldr q16,[x3]", " mov w8,#3457", " dup v14.8h,w8",
    ]
    if mode == "full":
        lines += [" mov w8,#9", " dup v15.8h,w8"]
    lines += [" mov x5,x0", " add x6,x0,#216", " add x7,x0,#432"]
    previous: list[int] | None = None
    for class_index, sources in enumerate(path):
        slots = states[class_index]
        lines.append(f"p14_{mode}_class_{class_index}_start:")
        for slot, source_q in enumerate(slots):
            if previous is None or previous[slot] != source_q:
                lines.append(f" ldr q{slot},[x1,#{16 * source_q}]")
        for output_q in sorted(classes[sources]):
            lines += [
                f" ldr q8,[x2,#{32 * output_q}]",
                f" ldr q9,[x2,#{32 * output_q + 16}]",
                " tbl v10.16b,{v0.16b-v3.16b},v8.16b",
                " tbl v11.16b,{v4.16b-v7.16b},v9.16b",
                " orr v11.16b,v10.16b,v11.16b",
            ]
            if mode == "full":
                lines += [
                    " sqrdmulh v12.8h,v11.8h,v15.8h",
                    " mls v11.8h,v12.8h,v14.8h",
                ]
            lines += [
                " sshr v12.8h,v11.8h,#15",
                " and v12.16b,v12.16b,v14.16b",
                " add v11.8h,v11.8h,v12.8h",
                " uzp1 v12.8h,v11.8h,v11.8h",
                " uzp2 v13.8h,v11.8h,v11.8h",
                " shl v10.8h,v13.8h,#12",
                " orr v12.16b,v12.16b,v10.16b",
                " ushr v13.8h,v13.8h,#4",
                " tbl v11.16b,{v12.16b,v13.16b},v16.16b",
            ]
            base = ("x5", "x6", "x7")[output_q // 18]
            offset = 12 * (output_q % 18)
            lines += [
                f" stur d11,[{base},#{offset}]",
                " umov w9,v11.s[2]",
                f" stur w9,[{base},#{offset + 8}]",
            ]
        lines.append(f"p14_{mode}_class_{class_index}_end:")
        previous = slots
    lines += [" ret", ".p2align 4", f"p14_pack_index_{mode}:",
              " .byte 0,1,16,2,3,18,4,5,20,6,7,22,255,255,255,255",
              ".p2align 4", f"p14_indices_{mode}:"]
    for output in indices:
        lines.append(" .byte " + ",".join(map(str, output[0])))
        lines.append(" .byte " + ",".join(map(str, output[1])))
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    forward = exact_map()
    path, classes = class_path(forward[:432])
    states = build_slots(path)
    indices, _ = make_indices(forward[:432], path, classes, states)
    BUILD.mkdir(exist_ok=True)
    (BUILD / "p14_tables.h").write_text(emit_header(forward, indices))
    (BUILD / "p14_tobytes_full.c").write_text(emit_source("full", path, classes, states))
    (BUILD / "p14_tobytes_small.c").write_text(emit_source("small", path, classes, states))
    (BUILD / "p14_tobytes_public.S").write_text(emit_public())
    (BUILD / "p14_tobytes_full.S").write_text(
        emit_asm("full", path, classes, states, indices))
    (BUILD / "p14_tobytes_small.S").write_text(
        emit_asm("small", path, classes, states, indices))
    (BUILD / "schedule.txt").write_text(
        "classes=15\nclass_sizes=" + str(sorted(map(len, classes.values()))) +
        "\nsource_q_loads_per_top=64\nretained_overlap=56\n"
    )
    print("p14_generated classes=15 source_q_loads_per_top=64 outputs=54")


if __name__ == "__main__":
    main()
