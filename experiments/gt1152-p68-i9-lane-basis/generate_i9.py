#!/usr/bin/env python3
"""P68: rebuild packed_i9 in the (component, half) lane basis.

One call per t instead of per (top, component, block):
  input   9 Q at [x2 + j*256]      (was j*128, four calls sharing a t-block)
  output  9 Q at [x0 + s*256]      (was 16 half-stores + 8 lane-scatters)

The output transpose network disappears: each result register already holds
the eight independent problems (c,h) in its lanes, which is exactly what
invntt16_asm wants to read as one contiguous run of sixteen Q.

Stores are emitted at each output register's LAST DEFINITION, not at the
position the old store occupied -- generate_tail.py documents why: the
scheduler reuses these registers immediately after the transposes consumed
them, so a store left at the old site reads a clobbered value.
"""
import re, sys

SRC = "../gt1152-p10-kem/inverse9.S"
DST = "inverse9_lane.S"

# packed_i9 output register -> radix-9 output index s (probe_i9.S tagging run)
SMAP = {'v24':0, 'v31':1, 'v9':2, 'v14':3, 'v22':4, 'v11':5, 'v20':6, 'v19':7, 'v28':8}

lines = open(SRC).read().splitlines()
head_end = next(i for i,l in enumerate(lines) if 'packed_i9_slothy_start' in l) + 1
tail_start = next(i for i,l in enumerate(lines) if re.match(r'\s*ret\b', l))
head, body, tail = lines[:head_end], lines[head_end:tail_start], lines[tail_start:]

def op(l):
    m = re.match(r'\s*([a-z][a-z0-9.]*)\s', l)
    return m.group(1) if m else ''

# ---- 1. drop the output transpose network, its stores and its addressing ----
DROP_ADDR = re.compile(r'\s*(add\s+x(16|12|4)\s*,|mov\s+x14\s*,\s*#16)')
kept = []
for l in body:
    o = op(l)
    if o.startswith('trn'):                     continue   # 16 output transposes
    if o == 'str' and '[x0' in l or o == 'str' and '[x16' in l: continue
    if o == 'st1' and ('[x12' in l or '[x4' in l or '[x1]' in l or '[x1,' in l
                       or re.search(r'\[x1\]|\[x1\s*,|\[x12|\[x4\b', l)):  continue
    if DROP_ADDR.match(l):                      continue
    kept.append(l)

# ---- 2. input loads: Good-Thomas row stride 128 -> 256 bytes ----
def restride(l):
    m = re.match(r'(\s*ldr\s+q\d+,\s*\[x2(?:,\s*#(\d+))?\])(.*)$', l)
    if not m: return l
    off = int(m.group(2) or 0)
    assert off % 128 == 0 and off // 128 < 9, l
    return f"        ldr {re.search(r'q\d+', l).group(0)}, [x2, #{off//128*256}]{m.group(3)}"
kept = [restride(l) for l in kept]

# ---- 3. emit one str q at each output register's last definition ----
DEF = re.compile(r'\s*[a-z][a-z0-9.]*\s+(v\d+)\.')
last = {}
for i, l in enumerate(kept):
    m = DEF.match(l)
    if not m: continue
    r = m.group(1)
    if op(l) in ('str', 'st1', 'cmp', 'umov'):  continue   # not a define
    last[r] = i

missing = [r for r in SMAP if r not in last]
assert not missing, f"no definition found for {missing}"

out, pending = [], {}
for r, s in SMAP.items(): pending.setdefault(last[r], []).append((r, s))
for i, l in enumerate(kept):
    out.append(l)
    for r, s in sorted(pending.get(i, []), key=lambda p: p[1]):
        out.append(f"        str q{r[1:]}, [x0, #{s*256}]          // s={s}")

hdr = ["/* NTRU+1152 inverse9 in the (component, half) lane basis; generated by",
       " * generate_i9.py (P68).  One call per t.  The output transpose network",
       " * and its 24 split stores are replaced by nine str q at stride 256; the",
       " * input row stride doubles to 256 because the rebase (P65) already put",
       " * the four components and both halves in the eight lanes.",
       " * x1 is no longer used: s=8 is an ordinary output, not a tail scatter.",
       " */"]
open(DST,'w').write("\n".join(hdr + head[len([h for h in head if h.startswith('/*') or h.startswith(' *')]):] + out + tail) + "\n")

print(f"  {SRC}: {len(body)} body instructions")
print(f"  {DST}: {len(out)} body instructions   ({len(out)-len(body):+d})")
print(f"  dropped {len(body)-len(kept)} (16 trn + 24 stores + addressing), added 9 str q")
print("  store sites (last definition of each output register):")
for r, s in sorted(SMAP.items(), key=lambda p: p[1]):
    print(f"    s={s}  {r:>4}  after line {last[r]}: {kept[last[r]].strip()}")
