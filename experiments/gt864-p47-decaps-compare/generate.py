#!/usr/bin/env python3
"""Derive the P47 compare kernel mechanically from exact promoted P46."""
from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
SOURCE = ROOT / "ntruplus-GT-Production/Additional_Implementation/aarch64/NTRU+864/gt864_p18_tobytes_full.S"
OUT = HERE / "candidate-compare.sym.S"

D_STORE = re.compile(r"^(\s*)stur d(\d+), \[(x[567]), #(\d+)\](\s*//.*)?$")
W_STORE = re.compile(r"^(\s*)stur w9, \[(x[567]), #(\d+)\](\s*//.*)?$")


def generate() -> tuple[str, int, int]:
    text = SOURCE.read_text()
    text = text.replace("Generated by P23 generate.py; do not edit.",
                        "P47 derived mechanically from promoted P46; regenerate with experiments/gt864-p47-decaps-compare/generate.py.")
    text = text.replace("gt864_p18_tobytes_full_asm", "gt864_p47_decaps_compare_asm")
    text = text.replace("p23_top_full", "p47_top_compare")
    text = text.replace("p23_full_group3_", "p47_compare_group3_")
    text = text.replace("p23_pack_index_full", "p47_pack_index_full")

    old = """ mov x19,x0
 mov x20,x1
 bl p47_top_compare
 add x0,x19,#648
 add x1,x20,#864
 bl p47_top_compare
"""
    new = """ mov x19,x0
 mov x20,x1
 bl p47_top_compare
 add x2,x19,#648
 mov x19,x0
 mov x0,x2
 add x1,x20,#864
 bl p47_top_compare
 orr x0,x0,x19
 cmp x0,#0
 cset w0,ne
"""
    if old not in text:
        raise RuntimeError("wrapper pattern not found")
    text = text.replace(old, new, 1)
    text = text.replace(" dup v28.8h,w8\n mov x5,x0", " dup v28.8h,w8\n mov x8,#0\n mov x5,x0", 1)

    lines: list[str] = []
    d_count = 0
    w_count = 0
    for line in text.splitlines():
        # Slothy schedule comments deliberately retain the original store DAG;
        # only executable lines are transformed.
        match = D_STORE.match(line)
        if match:
            indent, vector, base, offset, _ = match.groups()
            lines.extend([
                # x9 may already hold this record's high D because P46 is free
                # to order MOV-high before STUR-low.  x0 is dead after x5-x7
                # capture the expected-byte bases, so use it for low D.
                f"{indent}mov x0, v{vector}.d[0]",
                f"{indent}ldur x2, [{base}, #{offset}]",
                f"{indent}eor x0, x0, x2",
                f"{indent}orr x8, x8, x0",
            ])
            d_count += 1
            continue
        match = W_STORE.match(line)
        if match:
            indent, base, offset, _ = match.groups()
            lines.extend([
                f"{indent}ldur w2, [{base}, #{offset}]",
                f"{indent}eor w9, w9, w2",
                f"{indent}orr x8, x8, x9",
            ])
            w_count += 1
            continue
        if line == "p47_top_compare_slothy_end:":
            lines.append(line)
            continue
        if line == " ret" and lines and lines[-1] == "p47_top_compare_slothy_end:":
            lines.extend([" mov x0,x8", " ret"])
            continue
        lines.append(line)

    if (d_count, w_count) != (54, 54):
        raise RuntimeError(f"expected 54 D and 54 W stores per top, saw {(d_count, w_count)}")
    generated = "\n".join(lines) + "\n"
    if re.search(r"(?m)^\s*stur [dw]", generated):
        raise RuntimeError("candidate still has executable byte stores")
    return generated, d_count, w_count


def main() -> None:
    text, d_count, w_count = generate()
    OUT.write_text(text)
    print(f"generated {OUT}: compared {d_count} D plus {w_count} W records/top")


if __name__ == "__main__":
    main()
