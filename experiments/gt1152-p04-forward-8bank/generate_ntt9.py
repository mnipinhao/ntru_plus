"""Emit NTRU+1152's ntt9.S from NTRU+864's.

The 9x16 Good-Thomas core .Lntt_one_bank and all four twiddle tables are copied
byte-identically; only the bank driver is regenerated.  That is sound because
the tables are selected by the alpha/beta half alone and never by component, and
because the leaf ordering is fixed by the core, not by the component count --
both established in gt1152-p03-gt-layout.

Changes: 6 banks -> 8, tail base 1536 -> 2048, and the output store addressing
    864 : top*864  + component*16 + row*96  + halfcol*48
    1152: top*1152 + component*16 + row*128 + halfcol*64
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GT864 = HERE.parents[1] / "ntruplus-GT-Production/Additional_Implementation/aarch64/NTRU+864"
SRC = GT864 / "ntt9.S"

# Output register order produced by .Lntt_one_bank, read off any 864 bank block:
# nine rows at halfcol 0, then nine rows at halfcol 1.
ROW_REGS_HALF0 = ["q31", "q1", "q9", "q26", "q20", "q24", "q30", "q29", "q22"]
ROW_REGS_HALF1 = ["q19", "q21", "q23", "q8", "q10", "q12", "q6", "q27", "q0"]


def extract_core(text):
    """Everything from .Lntt_one_bank to the end, minus the exported single-bank
    entry, which is an 864 test hook with a bank-contiguous store layout."""
    start = text.index(".Lntt_one_bank:")
    single = text.index(".global ntt_one_bank")
    common = text.index(".Lntt_common:")
    body = text[start:single].rstrip()
    tables = text[common:]
    return body, tables


def emit_bank(bank, top, component):
    base = top * 1152 + component * 16
    out = [f"    // top={top}, component={component}, bank={bank}"]
    out.append(f"    add x0, x7, #{256 * bank}")
    out.append("    add x1, x7, #2048")
    out.append(f"    add x1, x1, #{32 * bank}")
    out.append(f"    adr x2, .Lntt16_top{top}")
    out.append(f"    adr x3, .Lntt9_top{top}")
    out.append("    bl .Lntt_one_bank")
    for halfcol, regs in ((0, ROW_REGS_HALF0), (1, ROW_REGS_HALF1)):
        for row, reg in enumerate(regs):
            off = base + row * 128 + halfcol * 64
            out.append(f"    str {reg}, [x6, #{off}]")
    return "\n".join(out)


def main():
    text = SRC.read_text()
    body, tables = extract_core(text)

    banks = []
    for bank in range(8):
        banks.append(emit_bank(bank, bank // 4, bank % 4))

    parts = [
        "/* NTRU+1152 Forward Pass-2: eight-bank driver over the NTRU+864",
        " * 9x16 Good-Thomas core.",
        " *",
        " * Generated by generate_ntt9.py; do not edit.",
        f" * Core and tables copied verbatim from {SRC.relative_to(HERE.parents[1])}.",
        " * Only the bank count, the tail base and the store addressing differ.",
        " */",
        ".text",
        ".p2align 2",
        ".global ntt9_asm",
        ".global _ntt9_asm",
        "ntt9_asm:",
        "_ntt9_asm:",
        "    mov x6, x0",
        "    mov x7, x1",
        "    mov x16, x30",
        "    mov x4, #16",
        "    adr x5, .Lntt_common",
        "    ldp q14, q15, [x5], #32",
        "    ldr q13, [x5]",
        "",
        "\n\n".join(banks),
        "",
        "    mov x30, x16",
        "    ret",
        "",
        body,
        "",
        tables.rstrip(),
        "",
        "#if defined(__ELF__)",
        '.section .note.GNU-stack,"",%progbits',
        "#endif",
        "",
    ]
    dst = HERE / "ntt9.S"
    dst.write_text("\n".join(parts))

    # Hard gate: the copied core must be byte-identical to 864's.
    src_body, src_tables = extract_core(SRC.read_text())
    got = dst.read_text()
    assert src_body in got, "core body was altered"
    assert src_tables.rstrip() in got, "twiddle tables were altered"

    stores = len(re.findall(r"^\s+str q", "\n\n".join(banks), re.M))
    print(f"wrote {dst.name}: 8 banks, {stores} stores "
          f"({stores * 8} int16 = {stores * 16} bytes)")
    print("core .Lntt_one_bank and .Lntt9_top{0,1}/.Lntt16_top{0,1} copied verbatim")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
