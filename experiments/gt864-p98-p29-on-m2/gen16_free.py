#!/usr/bin/env python3
"""NTRU+864 invntt16_asm dumping a free layout: sixteen STR Q per call.

Every group's final register was measured to carry its four outputs in both
halves -- the last step is an eight-lane reduction x.lo + x.hi written as
ADD v, v, EXT(v), which is symmetric.  So two groups' registers merge with one
ZIP1 .2D of their low halves, into the later of the two so no register is
needed, and leave as one STR Q.

128 UMOV + 128 STRH per call become 16 ZIP1 + 16 STR Q.  The layout is not
natural order; the pairing is emitted as a table for the repack to consume.
"""
import json, re, sys
from pathlib import Path
SRC, DST, MAP = (Path(a) for a in sys.argv[1:4])
body = [l.split("//")[0].rstrip() for l in SRC.read_text().splitlines()]
UMOV = re.compile(r"^\s*umov\s+w(\d+),\s*v(\d+)\.h\[(\d+)\]\s*$")
STRH = re.compile(r"^\s*strh\s+w(\d+),\s*\[x0(?:,\s*#(\d+))?\]\s*$")
DEFV = r"^\s*(?!str|st[1-4]|umov)[a-z][a-z0-9_.]*\s+(?:v{0}\.|q{0}\b)"

held, groups = {}, {}
for i, l in enumerate(body):
    if (m := UMOV.match(l)): held[m.group(1)] = (m.group(2), i); continue
    if not (m := STRH.match(l)): continue
    v, at = held.pop(m.group(1))
    k, r = divmod((int(m.group(2) or 0) // 2), 27)
    assert r % 3 == 0, f"unexpected output stride at {l}"
    vv, first, last = groups.get(k, (v, at, at))
    assert vv == v, f"group {k} extracted from more than one register"
    groups[k] = (v, min(first, at), max(last, at))
assert not held and set(groups) == set(range(32))

def live(vreg, frm, to):                       # not redefined in (frm, to]
    pat = re.compile(DEFV.format(vreg))
    return not any(pat.match(body[j]) for j in range(frm + 1, to + 1))

# Feasible pairs: the earlier register must survive to the later extraction,
# and the two must be different registers.  Greedy on the shortest span keeps
# the extension of live ranges small.
feasible = []
for a in groups:
    for b in groups:
        va, _, la = groups[a]; vb, _, lb = groups[b]
        if la >= lb or va == vb: continue
        if live(va, la, lb): feasible.append((lb - la, a, b))
feasible.sort()
pairs, used = [], set()
for _, a, b in feasible:
    if a in used or b in used: continue
    pairs.append((a, b)); used |= {a, b}
if len(pairs) != 16:
    raise SystemExit(f"only {len(pairs)} of 16 pairs are feasible; "
                     f"unmatched groups {sorted(set(groups) - used)}")

emit = {groups[b][2]: (p, groups[a][0], groups[b][0]) for p, (a, b) in enumerate(pairs)}
out = []
for i, l in enumerate(body):
    if i in emit:
        p, va, vb = emit[i]
        out.append(f"        zip1 v{vb}.2D, v{va}.2D, v{vb}.2D")
        out.append(f"        str  q{vb}, [x0, #{16 * p}]")
        continue
    if UMOV.match(l) or STRH.match(l): continue
    out.append(l)

DST.write_text(
    "/* NTRU+864 invntt16_asm, free output layout, generated by gen16_free.py;\n"
    " * do not edit.  Pair p occupies halfwords 8p..8p+7 of the call's block:\n"
    " * lanes 0-3 are the first group of the pair, lanes 4-7 the second.\n"
    " */\n" + "\n".join(out) + "\n")
MAP.write_text(json.dumps(pairs))
n0 = len([l for l in body if re.match(r"^\s+[a-z]", l)])
n1 = len([l for l in out  if re.match(r"^\s+[a-z]", l)])
print(f"  {DST.name}: {n1} 條 (原 {n0}), store 128 -> 16")
print(f"  配對: {pairs[:4]} ...")
