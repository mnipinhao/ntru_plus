#!/usr/bin/env python3
"""Emit the lane-proved byte-shuffle masks used by D3 ASM0."""

from __future__ import annotations

import argparse
import json
import pathlib


def emit_vector(lines: list[str], label: str, values: list[int]) -> None:
    assert len(values) == 32
    lines.extend([".p2align 5", f"{label}:", ".byte " + ", ".join(str(x) for x in values)])


def mask(source: list[tuple[int, int]], desired: list[tuple[int, int]]) -> list[int]:
    index = {owner: i for i, owner in enumerate(source)}
    result = []
    for owner in desired:
        if owner in index:
            i = index[owner]
            result.extend((2 * i, 2 * i + 1))
        else:
            result.extend((128, 128))
    return result


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--gate", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    gate = json.loads(args.gate.read_text())
    lines = ["# Generated by generate_d3_vpmaddwd_asm_masks.py; do not edit.", ".section .rodata"]

    halves = [[(q, j) for q in range(16) for j in range(3)][i:i + 8]
              for i in range(0, 48, 8)]
    p_carriers = [(0, 3), (1, 4), (2, 5)]
    for j in range(3):
        desired = [(q, j) for q in range(16)]
        low, high = desired[:8], desired[8:]
        merged = [None] * 16
        for carrier_index, (lo_half, hi_half) in enumerate(p_carriers):
            lo_mask = mask(halves[lo_half], low)
            hi_mask = mask(halves[hi_half], high)
            emit_vector(lines, f"d3_p_j{j}_c{carrier_index}", lo_mask + hi_mask)
            for lane, owner in enumerate(low + high):
                source = halves[lo_half] if lane < 8 else halves[hi_half]
                if owner in source:
                    assert merged[lane] is None
                    merged[lane] = owner
        assert merged == desired

    schedules = gate["joint_pair_routing"]["constructive_schedule"]
    for operand in ("a", "b"):
        for target in schedules[operand]["targets"]:
            band = "lo" if target["band"] == "q00_07" else "hi"
            for carrier_index, carrier in enumerate(target["carriers"]):
                values = carrier["low_vpshufb_mask"] + carrier["high_vpshufb_mask"]
                emit_vector(lines, f"d3_pair_{operand}_{target['sum']}_{band}_c{carrier_index}", values)

    emit_vector(lines, "d3_q_words", sum(([3457 & 255, 3457 >> 8] for _ in range(16)), []))
    emit_vector(lines, "d3_qinv_words", sum(([12929 & 255, 12929 >> 8] for _ in range(16)), []))
    q_even_words = [3457 if i % 2 == 0 else 0 for i in range(16)]
    emit_vector(lines, "d3_q_even_words", sum(([x & 255, x >> 8] for x in q_even_words), []))
    lines.append('.section .note.GNU-stack,"",@progbits')
    encoded = "\n".join(lines) + "\n"
    if args.check:
        assert args.output.read_text() == encoded, f"stale generated file: {args.output}"
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(encoded)
    print(f"D3 ASM masks: 9 P masks + 24 pair masks -> {args.output}")


if __name__ == "__main__":
    main()
