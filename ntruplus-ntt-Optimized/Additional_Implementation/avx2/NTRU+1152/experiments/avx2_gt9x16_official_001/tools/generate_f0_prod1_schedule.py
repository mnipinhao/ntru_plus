#!/usr/bin/env python3
"""Generate the production-shaped F0 direct-load and transient-store schedule."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path


P_ORDER = [0, 3, 6, 1, 4, 7, 8, 2, 5]
Q_ORDER = [0, 8, 4, 12, 2, 10, 6, 14, 1, 9, 5, 13, 3, 11, 7, 15]
FIRST_GROUPS = [([0, 3, 6], [0, 3, 6]),
                ([1, 4, 7], [1, 4, 7]),
                ([8, 2, 5], [2, 5, 8])]
SECOND_GROUPS = [([0, 1, 2], ["one", "one"]),
                 ([3, 4, 5], ["rho", "rhoinv"]),
                 ([6, 7, 8], ["rhoinv", "rho"])]
ROUTE_MASK = [0, 1, 4, 5, 8, 9, 12, 13,
              2, 3, 6, 7, 10, 11, 14, 15]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def signed16(value: int) -> int:
    value &= 0xffff
    return value - 0x10000 if value >= 0x8000 else value


def parse_i16_array(text: str, name: str) -> list[int]:
    match = re.search(rf"{re.escape(name)}\[144\]\s*=\s*\{{(.*?)\}};", text, re.S)
    if not match:
        raise SystemExit(f"missing generated table: {name}")
    values = [int(x) for x in re.findall(r"-?\d+", match.group(1))]
    if len(values) != 144:
        raise SystemExit(f"{name}: expected 144 values, found {len(values)}")
    return values


def output_vector(branch: int, row: int, pair: int, stream: int) -> int:
    return (((branch * 9 + row) * 2 + pair) * 2) + stream


def compact_one_load(load: list[str], pair: int) -> list[str]:
    # vpshufd $0x88/$0xdd followed by vpermq $0xd8; only the compact low
    # 128-bit half is consumed by the subsequent vperm2i128.
    coefficient_base = 2 * pair
    return [load[4 * component + coefficient_base + stream]
            for component in range(4) for stream in range(2)]


def simulate_route(pair: int) -> tuple[list[str], list[str]]:
    loads = [[f"component{4 * block + component}.coefficient{coefficient}"
              for component in range(4) for coefficient in range(4)]
             for block in range(4)]
    compact = [compact_one_load(load, pair) for load in loads]
    combined = [compact[0] + compact[1], compact[2] + compact[3]]
    # ROUTE_MASK is byte-valued and acts independently on each 128-bit half.
    word_order = [0, 2, 4, 6, 1, 3, 5, 7]
    shuffled = []
    for vector in combined:
        shuffled.append([vector[base + index]
                         for base in (0, 8) for index in word_order])
    # vpunpck{l,h}qdq combines the selected qword from the two vectors in
    # each 128-bit half; vpermq $0xd8 then restores component order.
    qwords = [[vector[index:index + 4] for index in range(0, 16, 4)]
              for vector in shuffled]
    stream0_q = [qwords[0][0], qwords[1][0], qwords[0][2], qwords[1][2]]
    stream1_q = [qwords[0][1], qwords[1][1], qwords[0][3], qwords[1][3]]
    order = [0, 2, 1, 3]
    stream0 = sum((stream0_q[index] for index in order), [])
    stream1 = sum((stream1_q[index] for index in order), [])
    return stream0, stream1


def emit_constants(twists: list[list[int]]) -> str:
    lines = [
        "/* Generated by tools/generate_f0_prod1_schedule.py. */",
        ".section .rodata",
        ".p2align 5",
        ".Lf0_prod1_route_mask:",
        "  .byte " + ",".join(map(str, ROUTE_MASK * 2)),
    ]
    for branch in range(2):
        for row in range(9):
            source_h = (5 * row) % 9
            values = twists[branch][16 * source_h:16 * (source_h + 1)]
            qinv = [signed16(value * 12929) for value in values]
            lines.extend([
                ".p2align 5",
                f".Lf0_prod1_b{branch}_r{row}_twist:",
                "  .short " + ",".join(map(str, values)),
                ".p2align 5",
                f".Lf0_prod1_b{branch}_r{row}_twist_qinv:",
                "  .short " + ",".join(map(str, qinv)),
            ])
    return "\n".join(lines) + "\n"


def write(path: Path, text: str, check: bool) -> None:
    if check:
        if not path.is_file() or path.read_text() != text:
            raise SystemExit(f"generated file is stale: {path}")
    else:
        path.write_text(text)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tables", type=Path, required=True)
    parser.add_argument("--map", type=Path, required=True)
    parser.add_argument("--prod0-contract", type=Path, required=True)
    parser.add_argument("--paper-range", type=Path, required=True)
    parser.add_argument("--ma2-range", type=Path, required=True)
    parser.add_argument("--ntt9-macro", type=Path, required=True)
    parser.add_argument("--ntt16-macro", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--asm-constants", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    table_text = args.tables.read_text()
    mapping = json.loads(args.map.read_text())
    prod0 = json.loads(args.prod0_contract.read_text())
    paper_range = json.loads(args.paper_range.read_text())
    ma2_range = json.loads(args.ma2_range.read_text())
    ntt9 = args.ntt9_macro.read_text()
    ntt16 = args.ntt16_macro.read_text()

    frozen = mapping["frozen_semantic_contract"]
    if frozen["physical_p_order"] != P_ORDER or frozen["physical_q_order"] != Q_ORDER:
        raise SystemExit("frozen F0 physical order changed")
    if frozen["transform_scale"] != 4 or frozen["montgomery_r_exponent"] != 0:
        raise SystemExit("frozen F0 scale changed")
    if "PAPER_R2_CACHED_STREAM" not in ntt9 or "PAPER_D1_BODY" not in ntt16:
        raise SystemExit("selected F-R3D1 arithmetic macro disappeared")
    if not ma2_range["all_preoperations_signed_i16"]:
        raise SystemExit("MA2 no longer proves all preoperations signed-i16 safe")

    twists = [parse_i16_array(table_text, f"ntruplus1152_exp001_twist_branch{b}")
              for b in range(2)]
    route_proofs = []
    for pair in range(2):
        actual = simulate_route(pair)
        expected = tuple([
            f"component{component}.coefficient{2 * pair + stream}"
            for component in range(16)] for stream in range(2))
        route_proofs.append({
            "terminal_pair": pair,
            "vpshufd_imm": "0x88" if pair == 0 else "0xdd",
            "stream0": actual[0],
            "stream1": actual[1],
            "expected_exact": actual == expected,
        })
    if not all(proof["expected_exact"] for proof in route_proofs):
        raise SystemExit("AVX2 direct-load route does not produce expected streams")

    destination_for_input = {
        source: destination
        for sources, destinations in FIRST_GROUPS
        for source, destination in zip(sources, destinations)
    }
    load_maps = []
    slots = set()
    for branch in range(2):
        for pair in range(2):
            for input_row in range(9):
                source_h = (5 * input_row) % 9
                destination_row = destination_for_input[input_row]
                vectors = [output_vector(branch, destination_row, pair, stream)
                           for stream in range(2)]
                slots.update(vectors)
                load_maps.append({
                    "branch": branch,
                    "terminal_pair": pair,
                    "coefficient_streams": [2 * pair, 2 * pair + 1],
                    "input_gt_row": input_row,
                    "source_h_row": source_h,
                    "split_base_i16": branch * 576 + source_h * 64,
                    "aligned_load_offsets_i16": [0, 16, 32, 48],
                    "pre_twist": {
                        "zeta_label": f".Lf0_prod1_b{branch}_r{input_row}_twist",
                        "qinv_label": f".Lf0_prod1_b{branch}_r{input_row}_twist_qinv",
                    },
                    "r2_first_destination_row": destination_row,
                    "transient_f0_vectors": vectors,
                    "transient_f0_byte_offsets": [32 * vector for vector in vectors],
                })
    if slots != set(range(72)):
        raise SystemExit("transient F0 slots are not complete and unique")

    broad_input = paper_range["ntt9_input_range"]
    actual_coeff = prod0["input_roles"]["F0_R"]["coefficient_range"]
    broad_coeff = [-3, 4]
    if not (broad_coeff[0] <= actual_coeff[0] <= actual_coeff[1] <= broad_coeff[1]):
        raise SystemExit("actual coefficient producer is not inside proven KEM-small domain")
    if not paper_range["proof"]["all_recorded_intervals_fit_signed16"]:
        raise SystemExit("paper path range proof is no longer signed-i16 safe")

    document = {
        "schema": "gt-f0-prod1-schedule/v1",
        "checkpoint": "F0-PROD1-SCHED",
        "parameter": 1152,
        "frozen_contract": {
            "physical_p_order": P_ORDER,
            "physical_q_order": Q_ORDER,
            "transform_scale": 4,
            "montgomery_r_exponent": 0,
            "standalone_scale_pass": False,
        },
        "boundary": {
            "top_split_arithmetic": "unchanged existing small-input split",
            "top_split_materialization_bytes": 2304,
            "actual_input_alignment_bytes": 32,
            "split_row_alignment_bytes": 32,
            "official_abi_crossings": 0,
            "scalar_adapter_calls": 0,
            "coefficient_adapter_bytes": 0,
            "pair_input_bytes": 0,
            "pair_output_bytes": 0,
            "internal_vzeroupper": 0,
        },
        "direct_load_route": {
            "load_maps": load_maps,
            "load_map_count": len(load_maps),
            "loads_per_map": 4,
            "load_opcode": "vmovdqa",
            "instructions_per_map": {
                "vpshufd": 4, "vpermq": 6, "vperm2i128": 2,
                "vpshufb": 2, "vpunpcklqdq": 1, "vpunpckhqdq": 1,
                "routing_total": 16,
            },
            "route_mask": ROUTE_MASK,
            "route_proofs": route_proofs,
        },
        "arithmetic_schedule": {
            "reuse": "exact F-R3D1 PAPER_R2_CACHED_STREAM plus PAPER_D1_BODY arithmetic/order",
            "r2_first": [{"input_rows": source, "output_rows": destination}
                         for source, destination in FIRST_GROUPS],
            "r2_second": [{"rows": rows, "pre_twists": pre_twists}
                          for rows, pre_twists in SECOND_GROUPS],
            "d1": {"adjacent_physical_row_pairs": [[0, 1], [2, 3], [4, 5], [6, 7]],
                   "tail_row": 8},
            "r2_first_writes_transient_f0": True,
            "r2_second_and_d1_overwrite_in_place": True,
            "final_materialized_vectors": 72,
        },
        "range_proof": {
            "actual_coefficient_domain": actual_coeff,
            "existing_proven_domain": broad_coeff,
            "domain_subset": True,
            "existing_pre_twist_bound": broad_input,
            "unchanged_arithmetic_schedule": True,
            "all_intermediate_ranges_signed_i16": True,
            "ma2_all_preoperations_signed_i16": True,
            "extra_reductions": 0,
        },
        "register_and_stack_plan": {
            "producer_realization": "P1-H leaf helpers first; P1-I full inline retained as placement variant",
            "formation_peak_ymm": 13,
            "r2_cached_peak_ymm": 15,
            "d1_peak_ymm": 11,
            "spill_target": 0,
            "only_live_array": "top_split",
            "required_stack_bytes": 2304,
            "stack_frame_target_max_bytes": 2432,
            "callee_saved_gpr_plan": ["rbx", "r12", "r13", "r14", "r15"],
            "leaf_entry_alignment_bytes": 32,
            "constant_alignment_bytes": 32,
        },
        "decision": {
            "schedule_complete": True,
            "authorized_next": "F0-PROD1-ASM P1-H",
            "assembly_implemented": False,
            "kem_benchmark_authorized": False,
            "reason": "producer assembly must pass differential, ABI, range, and structural audit first",
        },
        "source_sha256": {key: sha256(path) for key, path in {
            "tables": args.tables, "map": args.map,
            "prod0_contract": args.prod0_contract, "paper_range": args.paper_range,
            "ma2_range": args.ma2_range, "ntt9_macro": args.ntt9_macro,
            "ntt16_macro": args.ntt16_macro,
        }.items()},
    }
    write(args.output, json.dumps(document, indent=2, sort_keys=True) + "\n", args.check)
    write(args.asm_constants, emit_constants(twists), args.check)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
