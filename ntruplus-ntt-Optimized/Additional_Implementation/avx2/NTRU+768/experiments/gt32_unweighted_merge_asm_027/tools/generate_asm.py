#!/usr/bin/env python3
"""Generate the executable counterexample for the 026 claimed schedule.

The emitted candidate is intentionally not benchmark-eligible.  The exact
candidate/current conjugation proof is generated by prove_exact_conjugation.py;
the assembly here makes the old propagation error observable in a native test.
"""

from __future__ import annotations

import itertools
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "avx2_gt16_quadratic_official_001"
HEADER = SOURCE / "generated" / "quadratic-constants.h"
Q = 3457
QINV = 12929
R = (1 << 16) % Q
RINV = pow(R, -1, Q)
HIGH = {2, 3, 6, 7, 10, 11, 14, 15}
BRV3 = (0, 4, 2, 6, 1, 5, 3, 7)
CAGE = 32768
PLUS = [
    0,1,2,3,0,1,2,3, 8,9,10,11,8,9,10,11,
    0,1,2,3,0,1,2,3, 8,9,10,11,8,9,10,11,
]
MINUS = [
    4,5,6,7,4,5,6,7, 12,13,14,15,12,13,
    14,15,4,5,6,7,4,5,6,7,12,13,14,15,12,13,14,15,
]


def center(value: int) -> int:
    value %= Q
    return value - Q if value > Q // 2 else value


def s16(value: int) -> int:
    value &= 0xFFFF
    return value - 65536 if value & 0x8000 else value


def inv(value: int) -> int:
    return pow(value % Q, -1, Q)


def mont(standard: int) -> int:
    return center(standard * R)


def qinv_constant(montgomery: int) -> int:
    return s16(montgomery * QINV)


def extract(text: str, pattern: str, count: int) -> list[int]:
    match = re.search(pattern + r".*?= \{(.*?)\n\};", text, re.S)
    if not match:
        raise RuntimeError(pattern)
    values = [int(value) for value in re.findall(r"-?\d+", match.group(1))]
    if len(values) != count:
        raise RuntimeError(f"{pattern}: {len(values)} != {count}")
    return values


def normalize_signs(raw: tuple[int, int, int], target: tuple[int, int, int]) -> tuple[int, int, int]:
    for signs in ((1,) + tail for tail in itertools.product((1, -1), repeat=2)):
        signed = tuple(raw[index] * signs[index] % Q for index in range(3))
        base = signed[0]
        normalized = tuple(value * inv(base) % Q for value in signed)
        if normalized == target:
            return signs
    raise RuntimeError((raw, target))


def emit_words(name: str, rows: list[list[int]]) -> str:
    lines = [".p2align 5", f"{name}:"]
    for row in rows:
        if len(row) != 16:
            raise RuntimeError((name, len(row)))
        lines.append("    .short " + ", ".join(str(s16(value)) for value in row))
    return "\n".join(lines)


def emit_bytes(name: str, rows: list[list[int]]) -> str:
    lines = [".p2align 5", f"{name}:"]
    for row in rows:
        if len(row) != 32:
            raise RuntimeError((name, len(row)))
        lines.append("    .byte " + ", ".join(str(value) for value in row))
    return "\n".join(lines)


def mont_lines(register: int, temporary: int, mont_label: str, qinv_label: str, offset: int) -> list[str]:
    return [
        f"    vpmullw {qinv_label}+{offset}(%rip), %ymm{register}, %ymm{temporary}",
        f"    vpmulhw {mont_label}+{offset}(%rip), %ymm{register}, %ymm{register}",
        f"    vpmulhw %ymm15, %ymm{temporary}, %ymm{temporary}",
        f"    vpsubw %ymm{temporary}, %ymm{register}, %ymm{register}",
    ]


def center_lines(register: int, temporary: int, iterations: int) -> list[str]:
    lines = []
    for _ in range(iterations):
        lines += [
            f"    vpcmpgtw %ymm14, %ymm{register}, %ymm{temporary}",
            f"    vpand %ymm15, %ymm{temporary}, %ymm{temporary}",
            f"    vpsubw %ymm{temporary}, %ymm{register}, %ymm{register}",
            f"    vpcmpgtw %ymm{register}, %ymm13, %ymm{temporary}",
            f"    vpand %ymm15, %ymm{temporary}, %ymm{temporary}",
            f"    vpaddw %ymm{temporary}, %ymm{register}, %ymm{register}",
        ]
    return lines


def merge_current(register: int, source_offset: int, vector: int) -> list[str]:
    plus, minus, total, difference, temporary = (2, 3, 4, 5, 6) if register == 0 else (2, 3, 7, 8, 6)
    lines = [
        f"    vmovdqu {source_offset}(%rsi), %ymm{register}",
        f"    vpshufb .Lplus(%rip), %ymm{register}, %ymm{plus}",
        f"    vpshufb .Lminus(%rip), %ymm{register}, %ymm{minus}",
        f"    vpaddw %ymm{minus}, %ymm{plus}, %ymm{total}",
        f"    vpsubw %ymm{minus}, %ymm{plus}, %ymm{difference}",
    ]
    lines += mont_lines(difference, temporary, ".Lmerge_mont", ".Lmerge_qinv", vector * 32)
    lines += [f"    vpblendw $0xcc, %ymm{difference}, %ymm{total}, %ymm{register}"]
    return lines


def merge_candidate(register: int, source_offset: int, k3: int) -> list[str]:
    plus, minus, total, difference = (2, 3, 4, 5) if register == 0 else (2, 3, 7, 8)
    mask_offset = k3 * 32
    return [
        f"    vmovdqu {source_offset}(%rsi), %ymm{register}",
        f"    vpshufb .Lcplus+{mask_offset}(%rip), %ymm{register}, %ymm{plus}",
        f"    vpshufb .Lcminus+{mask_offset}(%rip), %ymm{register}, %ymm{minus}",
        f"    vpaddw %ymm{minus}, %ymm{plus}, %ymm{total}",
        f"    vpsubw %ymm{minus}, %ymm{plus}, %ymm{difference}",
        f"    vpblendw $0xcc, %ymm{difference}, %ymm{total}, %ymm{register}",
    ]


def function_prologue(name: str) -> list[str]:
    return [
        "    .p2align 6",
        f"    .globl {name}",
        f"    .type {name},@function",
        f"{name}:",
        f".Lstart_{name}:",
        "    vmovdqa .Lnegcenter(%rip), %ymm13",
        "    vmovdqa .Lcenter(%rip), %ymm14",
        "    vmovdqa .Lq(%rip), %ymm15",
    ]


def function_epilogue(name: str) -> list[str]:
    return [
        "    vzeroupper",
        "    ret",
        f"    .fill {CAGE}-(.-.Lstart_{name}),1,0x90",
        f"    .size {name},.-{name}",
    ]


def generate_body(kind: str, metadata: dict) -> list[str]:
    repaired = kind == "repaired"
    candidate = kind != "control"
    name = f"qbm_inverse_{kind}_rows_asm"
    lines = function_prologue(name)

    candidate_stage1_edge = 0
    for k3 in range(3):
        base = 16 * k3
        for position, k16 in enumerate(BRV3):
            low = base + k16
            high = low + 8
            if candidate:
                lines += merge_candidate(0, low * 32, k3)
                lines += merge_candidate(1, high * 32, k3)
                lines += mont_lines(1, 6, ".Lc_s2_mont", ".Lc_s2_qinv", candidate_stage1_edge * 32)
                candidate_stage1_edge += 1
            else:
                lines += merge_current(0, low * 32, low)
                lines += merge_current(1, high * 32, high)
            lines += [
                "    vpaddw %ymm1, %ymm0, %ymm2",
                "    vpsubw %ymm1, %ymm0, %ymm3",
            ]
            lines += center_lines(2, 9, 2)
            lines += center_lines(3, 9, 2)
            lines += [
                f"    vmovdqu %ymm2, {(base + 2 * position) * 32}(%rdi)",
                f"    vmovdqu %ymm3, {(base + 2 * position + 1) * 32}(%rdi)",
            ]

    current_edge = 0
    candidate_edge = 0
    twiddle_offset = 0
    for length in (4, 8, 16):
        half = length // 2
        for k3 in range(3):
            base = 16 * k3
            for start in range(0, 16, length):
                for index in range(half):
                    low = base + start + index
                    high = low + half
                    lines += [
                        f"    vmovdqu {low * 32}(%rdi), %ymm0",
                        f"    vmovdqu {high * 32}(%rdi), %ymm1",
                    ]
                    if candidate:
                        lines += mont_lines(1, 4, ".Lc_ntt_mont", ".Lc_ntt_qinv", candidate_edge * 32)
                        candidate_edge += 1
                    elif index != 0:
                        lines += mont_lines(1, 4, ".Lcontrol_ntt_mont", ".Lcontrol_ntt_qinv", current_edge * 32)
                        current_edge += 1
                    lines += [
                        "    vpaddw %ymm1, %ymm0, %ymm2",
                        "    vpsubw %ymm1, %ymm0, %ymm3",
                    ]
                    if length == 8:
                        lines += center_lines(2, 4, 1)
                        lines += center_lines(3, 4, 1)
                    lines += [
                        f"    vmovdqu %ymm2, {low * 32}(%rdi)",
                        f"    vmovdqu %ymm3, {high * 32}(%rdi)",
                    ]
        twiddle_offset += half

    for i16 in range(16):
        lines += [
            f"    vmovdqu {i16 * 32}(%rdi), %ymm0",
            f"    vmovdqu {(16 + i16) * 32}(%rdi), %ymm1",
            f"    vmovdqu {(32 + i16) * 32}(%rdi), %ymm2",
            "    vpsubw %ymm1, %ymm2, %ymm3",
        ]
        lines += mont_lines(3, 4, ".Lomega_mont", ".Lomega_qinv", 0)
        lines += [
            "    vpaddw %ymm1, %ymm0, %ymm5",
            "    vpaddw %ymm2, %ymm5, %ymm5",
            "    vpsubw %ymm1, %ymm0, %ymm6",
            "    vpaddw %ymm3, %ymm6, %ymm6",
            "    vpsubw %ymm2, %ymm0, %ymm7",
            "    vpsubw %ymm3, %ymm7, %ymm7",
        ]
        post_label = ".Lc_post" if candidate else ".Lpost"
        post_qinv = ".Lc_post_qinv" if candidate else ".Lpost_qinv"
        for output, register in enumerate((5, 6, 7)):
            offset = (3 * i16 + output) * 32
            lines += mont_lines(register, 4, post_label, post_qinv, offset)
        if repaired:
            lines += [
                "    vpblendw $0xcc, %ymm7, %ymm5, %ymm0",
                "    vpblendw $0xcc, %ymm5, %ymm6, %ymm1",
                "    vpblendw $0xcc, %ymm6, %ymm7, %ymm2",
                f"    vmovdqu %ymm0, {i16 * 32}(%rdi)",
                f"    vmovdqu %ymm1, {(16 + i16) * 32}(%rdi)",
                f"    vmovdqu %ymm2, {(32 + i16) * 32}(%rdi)",
            ]
        else:
            lines += [
                f"    vmovdqu %ymm5, {i16 * 32}(%rdi)",
                f"    vmovdqu %ymm6, {(16 + i16) * 32}(%rdi)",
                f"    vmovdqu %ymm7, {(32 + i16) * 32}(%rdi)",
            ]
    lines += function_epilogue(name)
    metadata[name] = {
        "candidate": candidate,
        "terminal_repaired": repaired,
        "stage1_montgomery_chains": candidate_stage1_edge if candidate else 48,
        "ntt16_montgomery_chains": candidate_edge if candidate else current_edge,
        "dft3_montgomery_chains": 16,
        "postweight_montgomery_chains": 48,
        "terminal_blends": 48 if repaired else 0,
    }
    return lines


def main() -> None:
    text = HEADER.read_text()
    merge_mont_flat = extract(text, r"round4c_merge_mont\[48\]\[16\]", 768)
    merge_qinv_flat = extract(text, r"round4c_merge_qinv\[48\]\[16\]", 768)
    inv_mont = extract(text, r"round4c_inv16_twiddle_mont\[14\]", 14)
    inv_qinv = extract(text, r"round4c_inv16_twiddle_qinv\[14\]", 14)
    post_mont_flat = extract(text, r"round4c_inv48_postweight_mont\[48\]\[16\]", 768)
    post_qinv_flat = extract(text, r"round4c_inv48_postweight_qinv\[48\]\[16\]", 768)
    omega_mont = int(re.search(r"round4c_inv3_omega_mont = (-?\d+);", text).group(1))
    omega_qinv = int(re.search(r"round4c_inv3_omega_qinv = (-?\d+);", text).group(1))

    merge_mont = [merge_mont_flat[16*i:16*i+16] for i in range(48)]
    merge_qinv = [merge_qinv_flat[16*i:16*i+16] for i in range(48)]
    weight = [[center(value * RINV) for value in row] for row in merge_mont]
    post_mont = [post_mont_flat[16*i:16*i+16] for i in range(48)]
    post_qinv = [post_qinv_flat[16*i:16*i+16] for i in range(48)]

    # First propagate alpha=+1 to identify the final k3 character and choose
    # one free sign vector per k3 batch that normalizes all high lanes to the
    # same nontrivial character.
    unsigned_scale = [[weight[v][j] if j in HIGH else 1 for j in range(16)] for v in range(48)]
    provenance = [[v for _ in range(16)] for v in range(48)]
    scale = unsigned_scale
    after = [[0]*16 for _ in range(48)]
    after_prov = [[0]*16 for _ in range(48)]
    for k3 in range(3):
        for position, k16 in enumerate(BRV3):
            low = 16*k3+k16
            for destination in (16*k3+2*position, 16*k3+2*position+1):
                after[destination] = scale[low][:]
                after_prov[destination] = provenance[low][:]
    scale, provenance = after, after_prov
    for length in (4,8,16):
        half=length//2; after=[row[:] for row in scale]; after_prov=[row[:] for row in provenance]
        for k3 in range(3):
            for start in range(0,16,length):
                for index in range(half):
                    low=16*k3+start+index; high=low+half
                    after[low]=scale[low][:]; after[high]=scale[low][:]
                    after_prov[low]=provenance[low][:]; after_prov[high]=provenance[low][:]
        scale, provenance=after,after_prov
    assert {provenance[16*k][0] for k in range(3)} == {0,16,32}
    roots = sorted(value for value in range(1,Q) if pow(value,3,Q)==1 and value != 1)
    target = (1, roots[1], roots[0])
    alpha = [[1]*16 for _ in range(3)]
    for lane in range(16):
        raw=tuple(scale[16*k][lane]%Q for k in range(3))
        if lane in HIGH:
            signs=normalize_signs(raw,target)
            for k3 in range(3): alpha[k3][lane]=signs[k3]

    # Apply the batch sign to every vector so it is free in three reusable
    # shuffle-mask pairs and cancels inside each NTT16 batch ratio.
    scale=[[weight[v][j]*alpha[v//16][j] if j in HIGH else 1 for j in range(16)] for v in range(48)]
    cplus=[]; cminus=[]
    for k3 in range(3):
        p=PLUS[:];m=MINUS[:]
        for lane in HIGH:
            if alpha[k3][lane] == -1:
                p[2*lane:2*lane+2],m[2*lane:2*lane+2]=m[2*lane:2*lane+2],p[2*lane:2*lane+2]
        cplus.append(p);cminus.append(m)

    s2_standard=[]
    after=[[0]*16 for _ in range(48)]
    for k3 in range(3):
        for position,k16 in enumerate(BRV3):
            low=16*k3+k16;high=low+8
            ratio=[center(scale[high][j]*inv(scale[low][j])) for j in range(16)]
            s2_standard.append(ratio)
            for destination in (16*k3+2*position,16*k3+2*position+1):after[destination]=scale[low][:]
    scale=after
    c_ntt_standard=[]; control_ntt_mont=[];control_ntt_qinv=[]
    offset=0
    for length in (4,8,16):
        half=length//2;after=[row[:] for row in scale]
        for k3 in range(3):
            for start in range(0,16,length):
                for index in range(half):
                    low=16*k3+start+index;high=low+half
                    tw=1 if index==0 else center(inv_mont[offset+index]*RINV)
                    modified=[center(tw*scale[high][j]*inv(scale[low][j])) for j in range(16)]
                    c_ntt_standard.append(modified)
                    if index!=0:
                        control_ntt_mont.append([inv_mont[offset+index]]*16)
                        control_ntt_qinv.append([inv_qinv[offset+index]]*16)
                    after[low]=scale[low][:];after[high]=scale[low][:]
        scale=after;offset+=half

    # Verify the normalized terminal scale classes.
    for lane in range(16):
        raw=tuple(scale[16*k][lane]%Q for k in range(3)); base=raw[0]
        normalized=tuple(value*inv(base)%Q for value in raw)
        assert normalized == (target if lane in HIGH else (1,1,1))

    permutation=(2,0,1)
    inverse_permutation=[permutation.index(source) for source in range(3)]
    post_standard = [[center(value * RINV) for value in row] for row in post_mont]
    c_post_mont=[];c_post_qinv=[]
    for i16 in range(16):
        for source_index in range(3):
            row=[]
            for lane in range(16):
                destination=source_index if lane not in HIGH else inverse_permutation[source_index]
                common_scale = scale[i16][lane]
                row.append(mont(center(
                    post_standard[16*destination+i16][lane] * inv(common_scale)
                )))
            c_post_mont.append(row)
            c_post_qinv.append([qinv_constant(value) for value in row])

    rows = []
    rows.append("#define CAGE_BYTES 32768")
    rows.append(".text")
    metadata={}
    bodies={kind:generate_body(kind,metadata) for kind in ("control","heterogeneous","repaired")}
    rows.append("#ifdef REVERSED")
    rows += bodies["repaired"]+bodies["heterogeneous"]+bodies["control"]
    rows.append("#else")
    rows += bodies["control"]+bodies["heterogeneous"]+bodies["repaired"]
    rows.append("#endif")
    rows += [".section .rodata", ".p2align 5"]
    rows += [emit_words(".Lq", [[Q]*16]),emit_words(".Lcenter", [[Q//2]*16]),emit_words(".Lnegcenter", [[-(Q//2)]*16])]
    rows += [emit_bytes(".Lplus", [PLUS]),emit_bytes(".Lminus", [MINUS]),emit_bytes(".Lcplus", cplus),emit_bytes(".Lcminus", cminus)]
    rows += [emit_words(".Lmerge_mont",merge_mont),emit_words(".Lmerge_qinv",merge_qinv)]
    s2_mont=[[mont(x) for x in row] for row in s2_standard]
    rows += [emit_words(".Lc_s2_mont",s2_mont),emit_words(".Lc_s2_qinv",[[qinv_constant(x) for x in row] for row in s2_mont])]
    c_ntt_mont=[[mont(x) for x in row] for row in c_ntt_standard]
    rows += [emit_words(".Lc_ntt_mont",c_ntt_mont),emit_words(".Lc_ntt_qinv",[[qinv_constant(x) for x in row] for row in c_ntt_mont])]
    rows += [emit_words(".Lcontrol_ntt_mont",control_ntt_mont),emit_words(".Lcontrol_ntt_qinv",control_ntt_qinv)]
    rows += [emit_words(".Lomega_mont",[[omega_mont]*16]),emit_words(".Lomega_qinv",[[omega_qinv]*16])]
    # DFT loop indexing is i16-major/output-minor, unlike the source table.
    post_loop_mont=[];post_loop_qinv=[]
    for i16 in range(16):
        for output in range(3):
            post_loop_mont.append(post_mont[16*output+i16])
            post_loop_qinv.append(post_qinv[16*output+i16])
    rows += [emit_words(".Lpost",post_loop_mont),emit_words(".Lpost_qinv",post_loop_qinv),emit_words(".Lc_post",c_post_mont),emit_words(".Lc_post_qinv",c_post_qinv)]
    rows.append('.section .note.GNU-stack,"",@progbits')
    (ROOT/"generated"/"merge_basis_asm.S").write_text("\n".join(rows)+"\n")

    depth={"control_max_montgomery_depth":6,"candidate_max_montgomery_depth":6}
    result={
        "experiment":"GT32-UNWEIGHTED-MERGE-ASM-027",
        "semantic_valid":False,
        "benchmark_eligible":False,
        "purpose":"executable counterexample to the 026 absolute-scale propagation",
        "cage_bytes":CAGE,
        "functions":metadata,
        "alpha_signs_by_k3":alpha,
        "terminal_permutation":{"sum_lanes":[0,1,2],"difference_lanes":list(permutation)},
        "max_montgomery_depth":depth,
        "constants":{"candidate_stage1_vectors":len(s2_mont),"candidate_ntt16_vectors":len(c_ntt_mont),"control_ntt16_vectors":len(control_ntt_mont)},
    }
    (ROOT/"generated"/"asm_metadata.json").write_text(json.dumps(result,indent=2,sort_keys=True)+"\n")
    print(ROOT/"generated"/"merge_basis_asm.S")


if __name__ == "__main__":
    main()
