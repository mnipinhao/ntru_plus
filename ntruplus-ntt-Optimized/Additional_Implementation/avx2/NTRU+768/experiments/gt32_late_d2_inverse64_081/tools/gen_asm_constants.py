#!/usr/bin/env python3
"""Generate fixed tile-0 constants for the executable inverse64 gate."""
from __future__ import annotations

import json
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
ROOT = Path(__file__).resolve().parents[1]
ORACLE = json.loads((ROOT / "generated/inverse64_endpoint.json").read_text())
W64 = ORACLE["omega64"]
MU0 = ORACLE["tiles"][0]["mu0"]
PHYS_TO_CYCLIC = ORACLE["tiles"][0]["physical_to_inverse64_index"]


def centered(x: int) -> int:
    x %= Q
    return x - Q if x > Q // 2 else x


def s16(x: int) -> int:
    x &= 0xffff
    return x - 0x10000 if x >= 0x8000 else x


def mont(x: int) -> int:
    return centered(x * R)


def qinv(x: int) -> int:
    return s16(x * QINV)


def row(value: int) -> list[int]:
    return [value] * 16


def emit_rows(lines: list[str], label: str, rows: list[list[int]]) -> None:
    lines += [".p2align 5", f"{label}:"]
    for values in rows:
        assert len(values) == 16
        lines.append("\t.short " + ",".join(map(str, values)))


def inv_rows(length: int) -> list[list[int]]:
    distance = length // 2
    rows = []
    for g in range(4):
        rows.append([mont(pow(W64, (-((16 * g + lane) % distance)
                                      * (64 // length)) % 64, Q))
                     for lane in range(16)])
    return rows


def pack_pair(a: list[int], b: list[int], distance: int) -> list[int]:
    if distance == 8:
        return a[8:16] + b[8:16]
    if distance == 4:
        return a[4:8] + b[4:8] + a[12:16] + b[12:16]
    if distance == 2:
        return (a[2:4] + a[6:8] + b[2:4] + b[6:8]
                + a[10:12] + a[14:16] + b[10:12] + b[14:16])
    raise ValueError(distance)


lines = ["/* Generated by tools/gen_asm_constants.py; do not hand-edit. */"]
for label, value in (("q", Q), ("qinv_scalar", QINV), ("low16", 0xffff),
                     ("qpair", Q)):
    if label == "low16":
        vals = [s16(0xffff if i % 2 == 0 else 0) for i in range(16)]
    elif label == "qpair":
        vals = [Q if i % 2 == 0 else 0 for i in range(16)]
    else:
        vals = row(value)
    emit_rows(lines, f".Ld2_{label}", [vals])

mu = [mont(MU0 * pow(W64, PHYS_TO_CYCLIC[physical], Q))
      for physical in range(32)]
emit_rows(lines, ".Ld2_mu", [mu[:16], mu[16:]])
emit_rows(lines, ".Ld2_mu_qinv", [[qinv(x) for x in mu[:16]],
                                    [qinv(x) for x in mu[16:]]])
emit_rows(lines, ".Ld2_neg_mu", [[centered(-x) for x in mu[:16]],
                                  [centered(-x) for x in mu[16:]]])
emit_rows(lines, ".Ld2_neg_mu_qinv", [[qinv(centered(-x)) for x in mu[:16]],
                                       [qinv(centered(-x)) for x in mu[16:]]])

for length in (4, 8, 16):
    rows = inv_rows(length)
    d = length // 2
    packed = [pack_pair(rows[0], rows[1], d), pack_pair(rows[2], rows[3], d)]
    emit_rows(lines, f".Ld2_inv_l{length}_factor", packed)
    emit_rows(lines, f".Ld2_inv_l{length}_qinv",
              [[qinv(x) for x in values] for values in packed])
for length in (32, 64):
    rows = inv_rows(length)
    if length == 32:
        selected = [rows[1], rows[3]]
    else:
        selected = [rows[2], rows[3]]
    emit_rows(lines, f".Ld2_inv_l{length}_factor", selected)
    emit_rows(lines, f".Ld2_inv_l{length}_qinv",
              [[qinv(x) for x in values] for values in selected])

inv32 = mont(pow(32, -1, Q))
inv64 = pow(64, -1, Q)
odd = mont(inv64 * pow(MU0, -1, Q) % Q)
even = mont(inv64)
emit_rows(lines, ".Ld2_norm32_factor", [row(inv32)])
emit_rows(lines, ".Ld2_norm32_qinv", [row(qinv(inv32))])
alt = [even if i % 2 == 0 else odd for i in range(16)]
emit_rows(lines, ".Ld2_norm64_factor", [alt])
emit_rows(lines, ".Ld2_norm64_qinv", [[qinv(x) for x in alt]])

def mask(parity: int) -> list[int]:
    out = []
    for half in range(2):
        for i in range(4):
            word = 2 * i + parity
            out += [2 * word, 2 * word + 1]
        out += [0x80] * 8
    return out

for parity, name in ((0, "even"), (1, "odd")):
    values = mask(parity)
    lines += [".p2align 5", f".Ld2_{name}_mask:",
              "\t.byte " + ",".join(map(str, values))]

# Generic but exact physical-Q -> cyclic-Q shuffle masks.  Each source 128-bit
# half is broadcast into both halves before vpshufb, so one mask constructs two
# eight-word destination halves at once.
cyclic_to_phys = [PHYS_TO_CYCLIC.index(p) for p in range(32)]
def bitreverse5(x: int) -> int:
    return int(f"{x:05b}"[::-1], 2)
for outvec in range(2):
    for source_half in range(4):
        values = []
        for out_half in range(2):
            for lane in range(8):
                # Inverse DIT consumes bit-reversed frequency order.
                cyclic = bitreverse5(16 * outvec + 8 * out_half + lane)
                physical = cyclic_to_phys[cyclic]
                if physical // 8 == source_half:
                    local = physical & 7
                    values += [2 * local, 2 * local + 1]
                else:
                    values += [0x80, 0x80]
        lines += [".p2align 5", f".Ld2_perm_o{outvec}_s{source_half}:",
                  "\t.byte " + ",".join(map(str, values))]

(ROOT / "generated/inverse64_constants.inc").write_text("\n".join(lines) + "\n")
print(json.dumps({"mu0": MU0, "physical_to_cyclic": PHYS_TO_CYCLIC,
                  "inv32_mont": inv32,
                  "inv64_even_mont": even, "inv64_odd_mont": odd}, indent=2))
