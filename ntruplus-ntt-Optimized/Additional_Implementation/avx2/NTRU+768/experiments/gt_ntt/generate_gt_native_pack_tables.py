#!/usr/bin/env python3
"""Generate the GTN16-to-production quartic-slot permutation."""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

from generate_gt_soa_tables import centered, make_native_table


Q = 3457
PRODUCTION_BATCHES = 12
LANES = 16


def read_zetas(path: Path) -> list[int]:
    text = path.read_text()
    match = re.search(
        r"const\s+int16_t\s+zetas\[816\].*?=\s*\{(.*?)\};",
        text,
        flags=re.DOTALL,
    )
    if match is None:
        raise ValueError(f"could not locate zetas[816] in {path}")
    values = [int(value) for value in re.findall(r"-?\d+", match.group(1))]
    if len(values) != 816:
        raise ValueError(f"expected 816 zetas in {path}, found {len(values)}")
    return values


def production_lambdas(zetas: list[int]) -> list[int]:
    result = []
    for production_batch in range(PRODUCTION_BATCHES):
        group = production_batch // 2
        sign = production_batch & 1
        for lane in range(LANES):
            value = zetas[624 + 32 * group + 16 + lane]
            result.append(centered(-value if sign else value))
    return result


def derive_map(zetas: list[int]) -> tuple[list[int], list[int]]:
    production = production_lambdas(zetas)
    native = [value for row in make_native_table() for value in row]

    if len(set(production)) != PRODUCTION_BATCHES * LANES:
        raise ValueError("production lambda slots are not unique")
    if len(set(native)) != PRODUCTION_BATCHES * LANES:
        raise ValueError("native lambda slots are not unique")
    if set(production) != set(native):
        raise ValueError("production/native lambda multisets differ")

    native_slot = {value: index for index, value in enumerate(native)}
    production_to_native = [native_slot[value] for value in production]
    native_to_production = [0] * (PRODUCTION_BATCHES * LANES)
    for production_index, native_index in enumerate(production_to_native):
        native_to_production[native_index] = production_index

    assert sorted(production_to_native) == list(range(192))
    assert sorted(native_to_production) == list(range(192))
    for production_index, native_index in enumerate(production_to_native):
        assert native_to_production[native_index] == production_index
    return production_to_native, native_to_production


def format_array(name: str, values: list[int]) -> str:
    lines = [
        f"const uint8_t {name}[GT_NATIVE_QUARTIC_SLOTS] = {{",
    ]
    for offset in range(0, len(values), 16):
        row = ", ".join(f"{value:3d}" for value in values[offset : offset + 16])
        lines.append(f"\t{row},")
    lines.append("};")
    return "\n".join(lines)


def render_c(zetas: list[int]) -> str:
    production_to_native, native_to_production = derive_map(zetas)
    return "\n".join(
        [
            "/* Generated by generate_gt_native_pack_tables.py; do not edit. */",
            format_array(
                "gt_production_to_native_quartic", production_to_native
            ),
            "",
            format_array(
                "gt_native_to_production_quartic", native_to_production
            ),
            "",
        ]
    )


def native_pack_asm_groups(
    production_to_native: list[int],
) -> tuple[list[list[tuple[int, tuple[int, ...], tuple[int, ...]]]],
           list[tuple[int, ...]]]:
    groups = []
    masks = []

    for production_group in range(6):
        chunks = []
        for lane_base in range(0, LANES, 4):
            signs = []
            for sign in range(2):
                production_batch = 2 * production_group + sign
                native_slots = [
                    production_to_native[
                        LANES * production_batch + lane_base + lane
                    ]
                    for lane in range(4)
                ]
                native_batches = {slot // LANES for slot in native_slots}
                native_halves = {(slot % LANES) // 8 for slot in native_slots}
                if len(native_batches) != 1 or len(native_halves) != 1:
                    raise ValueError(
                        "WIRE12 four-lane chunk does not share one native XMM"
                    )
                signs.append(
                    (
                        native_slots[0] // LANES,
                        (native_slots[0] % LANES) // 8,
                        tuple(slot % 8 for slot in native_slots),
                    )
                )

            if signs[0][:2] != signs[1][:2]:
                raise ValueError(
                    "WIRE12 sign pair does not share one native XMM"
                )
            native_batch, native_half = signs[0][:2]
            offset = 128 * native_batch + 16 * native_half
            lane_masks = (signs[0][2], signs[1][2])
            for lane_mask in lane_masks:
                if lane_mask not in masks:
                    masks.append(lane_mask)
            chunks.append((offset, lane_masks[0], lane_masks[1]))
        groups.append(chunks)

    if len(masks) != 8:
        raise ValueError(f"expected 8 native pack lane masks, found {len(masks)}")
    return groups, masks


def render_asm(zetas: list[int]) -> str:
    production_to_native, _ = derive_map(zetas)
    groups, _ = native_pack_asm_groups(production_to_native)
    dual_masks = []
    paired_dual_masks = []
    lines = [
        "/* Generated by generate_gt_native_pack_tables.py; do not edit. */",
    ]

    for chunks in groups:
        source_positions = {}
        for chunk_index, (offset, sign0_mask, sign1_mask) in enumerate(chunks):
            source_positions[(offset // 128, (offset % 128) // 16)] = (
                chunk_index,
                sign0_mask,
                sign1_mask,
            )
        source_batches = {source[0] for source in source_positions}
        paired_order = []
        for low_chunk, high_chunk in ((3, 0), (2, 1)):
            matches = [
                native_batch
                for native_batch in source_batches
                if (
                    (native_batch, 0) in source_positions
                    and (native_batch, 1) in source_positions
                    and source_positions[(native_batch, 0)][0] == low_chunk
                    and source_positions[(native_batch, 1)][0] == high_chunk
                )
            ]
            if len(matches) == 1:
                paired_order.append(matches[0])
        if len(source_batches) == 2 and len(paired_order) == 2:
            arguments = []
            for native_batch in paired_order:
                low = source_positions[(native_batch, 0)]
                high = source_positions[(native_batch, 1)]
                arguments.append(str(128 * native_batch))
                paired_dual_mask = (
                    (low[1], low[2]),
                    (high[1], high[2]),
                )
                if paired_dual_mask not in paired_dual_masks:
                    paired_dual_masks.append(paired_dual_mask)
                arguments.append(
                    ".Lgt_native_pack_pair_dual_mask_"
                    f"{paired_dual_masks.index(paired_dual_mask)}"
                )
            lines.append(
                "\tGT_NATIVE_PACK_GROUP_PAIRED " + ", ".join(arguments)
            )
            continue

        arguments = []
        for offset, sign0_mask, sign1_mask in chunks:
            dual_mask = (sign0_mask, sign1_mask)
            if dual_mask not in dual_masks:
                dual_masks.append(dual_mask)
            arguments.extend(
                [
                    str(offset),
                    ".Lgt_native_pack_dual_mask_"
                    f"{dual_masks.index(dual_mask)}",
                ]
            )
        lines.append("\tGT_NATIVE_PACK_GROUP " + ", ".join(arguments))

    lines.extend(
        [
            "",
            "\t.pushsection .rodata",
            "\t.p2align 5",
            ".Lgt_native_pack_q:",
            "\t.short " + ", ".join(["3457"] * 16),
            ".Lgt_native_pack_v:",
            "\t.short " + ", ".join(["19412"] * 16),
            ".Lgt_native_pack_center10:",
            "\t.short " + ", ".join(["10"] * 16),
        ]
    )
    for index, dual_mask in enumerate(dual_masks):
        byte_mask = [
            byte
            for lane_mask in dual_mask
            for lane in lane_mask
            for byte in (2 * lane, 2 * lane + 1)
        ]
        lines.extend(
            [
                f".Lgt_native_pack_dual_mask_{index}:",
                "\t.byte " + ", ".join(str(value) for value in byte_mask),
            ]
        )
    for index, paired_dual_mask in enumerate(paired_dual_masks):
        byte_mask = [
            byte
            for dual_mask in paired_dual_mask
            for lane_mask in dual_mask
            for lane in lane_mask
            for byte in (2 * lane, 2 * lane + 1)
        ]
        lines.extend(
            [
                f".Lgt_native_pack_pair_dual_mask_{index}:",
                "\t.byte " + ", ".join(str(value) for value in byte_mask),
            ]
        )
    lines.extend(["\t.popsection", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--consts",
        type=Path,
        default=Path("../../consts.c"),
        help="production AVX2 consts.c containing zetas[816]",
    )
    parser.add_argument("--check", type=Path)
    parser.add_argument("--check-asm", type=Path)
    parser.add_argument(
        "--emit",
        choices=("c", "asm"),
        default="c",
        help="generated format when not checking a file",
    )
    args = parser.parse_args()

    if args.check is not None and args.check_asm is not None:
        parser.error("--check and --check-asm are mutually exclusive")
    zetas = read_zetas(args.consts)
    generated = render_asm(zetas) if (
        args.check_asm is not None or args.emit == "asm"
    ) else render_c(zetas)
    check_path = args.check_asm if args.check_asm is not None else args.check
    if check_path is None:
        sys.stdout.write(generated)
        return 0
    try:
        actual = check_path.read_text()
    except FileNotFoundError:
        print(f"missing generated file: {check_path}", file=sys.stderr)
        return 1
    if actual != generated:
        print(
            f"stale generated native pack table: {check_path}",
            file=sys.stderr,
        )
        return 1
    print(f"native-pack-table-check=passed file={check_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
