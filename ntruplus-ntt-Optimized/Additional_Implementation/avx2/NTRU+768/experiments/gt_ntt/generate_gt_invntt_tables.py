#!/usr/bin/env python3
"""Generate fixed-factor tables for the AVX2 GT SoA inverse prototype."""

import argparse
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
OMEGA96 = 675
BRANCH_SCALE = (2, 22)


def centered(value: int) -> int:
    value %= Q
    if value > Q // 2:
        value -= Q
    return value


def signed16(value: int) -> int:
    value &= 0xFFFF
    if value >= 0x8000:
        value -= 0x10000
    return value


def factor_qinv(value: int) -> int:
    return signed16(value * QINV)


def inverse_omega32(power: int) -> int:
    omega32 = pow(OMEGA96, 3, Q)
    return centered(pow(omega32, -power, Q) * R)


def repeated_halves(values: list[int]) -> list[int]:
    if len(values) != 8:
        raise ValueError("one AVX2 half must contain eight int16 values")
    return values + values


def make_twiddles() -> list[list[int]]:
    # len=4 and len=8 duplicate each low/high butterfly factor so vpshufb
    # can form both outputs before one fixed-factor Montgomery multiply.
    len4_half = [inverse_omega32(x) for x in (0, 8, 0, 8, 0, 8, 0, 8)]
    len8_half = [inverse_omega32(x) for x in (0, 4, 8, 12, 0, 4, 8, 12)]
    len16_half = [inverse_omega32(x) for x in range(0, 16, 2)]
    len32_lo_half = [inverse_omega32(x) for x in range(8)]
    len32_hi_half = [inverse_omega32(x) for x in range(8, 16)]
    return [
        repeated_halves(len4_half),
        repeated_halves(len8_half),
        repeated_halves(len16_half),
        repeated_halves(len32_lo_half),
        repeated_halves(len32_hi_half),
    ]


def make_untwist() -> list[list[int]]:
    table = []
    for n3 in range(3):
        for group in range(4):
            row = []
            for branch in range(2):
                for lane in range(8):
                    n32 = 8 * group + lane
                    n = (64 * n3 + 33 * n32) % 96
                    row.append(centered(pow(BRANCH_SCALE[branch], n, Q) * R))
            table.append(row)
    return table


def make_output_blocks() -> list[list[int]]:
    return [
        [
            (64 * n3 + 33 * (8 * group + lane)) % 96
            for lane in range(8)
        ]
        for n3 in range(3)
        for group in range(4)
    ]


def format_vector_table(
    name: str, table: list[list[int]], *, external: bool = False
) -> str:
    storage = "" if external else "static "
    lines = [
        f"{storage}const int16_t {name}[{len(table)}][16]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for row in table:
        values = ", ".join(f"{value:6d}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def format_index_table(
    name: str, table: list[list[int]], *, external: bool = False
) -> str:
    storage = "" if external else "static "
    lines = [f"{storage}const uint8_t {name}[{len(table)}][8] = {{"]
    for row in table:
        values = ", ".join(f"{value:2d}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def render() -> str:
    twiddles = make_twiddles()
    untwist = make_untwist()
    return "\n".join(
        [
            "/* Generated by generate_gt_invntt_tables.py; do not hand-edit. */",
            format_vector_table("gt_intt_twiddle", twiddles),
            "",
            format_vector_table(
                "gt_intt_twiddle_qinv",
                [[factor_qinv(value) for value in row] for row in twiddles],
            ),
            "",
            format_vector_table("gt_inv_untwist", untwist, external=True),
            "",
            format_vector_table(
                "gt_inv_untwist_qinv",
                [[factor_qinv(value) for value in row] for row in untwist],
                external=True,
            ),
            "",
            format_index_table(
                "gt_inv_output_block", make_output_blocks(), external=True
            ),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", type=Path, help="fail if FILE is stale")
    args = parser.parse_args()
    generated = render()

    if args.check is None:
        print(generated, end="")
        return 0
    if args.check.read_text() != generated:
        print(f"stale generated table: {args.check}")
        return 1
    print(f"table-check=passed file={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
