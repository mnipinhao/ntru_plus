#!/usr/bin/env python3
"""Generate packed mapping and twist tables for the AVX2 GT frontend."""

import argparse
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
BRANCH_SCALE = (2, 22)
ZETA_TOP = -1033

# Multiplication by 33 modulo 96 turns Q -> Q+3 into a three-quartic-block
# displacement.  Pair the resulting length-32 cycle so 47 of the 48 GT rows
# can be gathered by one 32-byte load plus vpermq; only (30,1), n3=1 wraps.
WIDE_PAIRS = [
    (0, 3), (6, 9), (12, 15), (18, 21),
    (24, 27), (30, 1), (4, 7), (10, 13),
    (16, 19), (22, 25), (28, 31), (2, 5),
    (8, 11), (14, 17), (20, 23), (26, 29),
]


def centered(value: int) -> int:
    value %= Q
    if value > Q // 2:
        value -= Q
    return value


def signed16(value: int) -> int:
    value &= 0xFFFF
    if value >= 0x8000:
        value -= 0x10000
    return value


def input_index(n3: int, q_index: int) -> int:
    return (64 * n3 + 33 * q_index) % 96


def twist(branch: int, index: int) -> int:
    return centered(pow(BRANCH_SCALE[branch], -index, Q) * R)


def montgomery_product(left: int, right: int) -> int:
    """Multiply two Montgomery-form constants, returning Montgomery form."""
    return centered(left * right * pow(R, -1, Q))


def input_offsets(pairs: list[tuple[int, int]]) -> list[list[int]]:
    return [
        [
            8 * input_index(n3, q_index)
            for n3 in range(3)
            for q_index in pair
        ]
        for pair in pairs
    ]


def packed_twists(pairs: list[tuple[int, int]]) -> list[list[list[int]]]:
    table = []
    for pair_indices in pairs:
        pair = []
        for n3 in range(3):
            factors = []
            for q_index in pair_indices:
                index = input_index(n3, q_index)
                factors.extend([twist(0, index)] * 4)
                factors.extend([twist(1, index)] * 4)
            # The assembly issues the low product before the high product.
            pair.append([signed16(value * QINV) for value in factors] + factors)
        table.append(pair)
    return table


def packed_fused_split_twists(
        pairs: list[tuple[int, int]]) -> list[list[list[int]]]:
    """Factors for t_b * (low + zeta_b * high), b in {0,1}."""
    one_minus_zeta = centered(R - ZETA_TOP)
    table = []
    for pair_indices in pairs:
        pair = []
        for n3 in range(3):
            low_factors = []
            high_factors = []
            for q_index in pair_indices:
                index = input_index(n3, q_index)
                low0 = twist(0, index)
                low1 = twist(1, index)
                high0 = montgomery_product(low0, ZETA_TOP)
                high1 = montgomery_product(low1, one_minus_zeta)
                low_factors.extend([low0] * 4)
                low_factors.extend([low1] * 4)
                high_factors.extend([high0] * 4)
                high_factors.extend([high1] * 4)
            pair.append(
                [signed16(value * QINV) for value in low_factors]
                + low_factors
                + [signed16(value * QINV) for value in high_factors]
                + high_factors
            )
        table.append(pair)
    return table


def format_offsets(name: str, table: list[list[int]]) -> str:
    lines = [
        f"const uint16_t {name}[16][6]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for row in table:
        values = ", ".join(f"{value:3d}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def format_twists(name: str, table: list[list[list[int]]]) -> str:
    width = len(table[0][0])
    lines = [
        f"const int16_t {name}[16][3][{width}]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for pair in table:
        lines.append("\t{")
        for row in pair:
            values = ", ".join(f"{value:6d}" for value in row)
            lines.append(f"\t\t{{ {values} }},")
        lines.append("\t},")
    lines.append("};")
    return "\n".join(lines)


def render_fixed_offset_asm() -> str:
    adjacent_pairs = [(q_index, q_index + 1) for q_index in range(0, 32, 2)]
    offsets = input_offsets(adjacent_pairs)
    lines = [
        "/* Generated by generate_gt_frontend_tables.py; do not hand-edit. */",
        "/* Pair-specific public CRT displacements for the high-first path. */",
        ".macro FRONTEND_HIGH_FIRST_FIXED_BODY",
        "\tleaq gt_frontend_twist_qinv_factor(%rip), %r8",
        "\tvmovdqa .Lfront_zeta_top(%rip), %ymm13",
        "\tvmovdqa .Lfront_zeta_top_qinv(%rip), %ymm14",
        "\tvmovdqa .Lfront_q(%rip), %ymm15",
        "\txorl %r9d, %r9d",
        "",
        "\t/* Pair 0 prologue. */",
        "\tFRONTEND_LOADS_FIXED " + ", ".join(str(value) for value in offsets[0]),
        "\tFRONTEND_TOP_MONT",
        ".p2align 5",
    ]
    for pair_index, pair_offsets in enumerate(offsets[1:], start=1):
        values = ", ".join(str(value) for value in pair_offsets)
        lines.append(f"\t/* Current pair {pair_index - 1} preloads pair {pair_index}. */")
        lines.append(f"\tFRONTEND_HIGH_FIRST_FIXED_PIPELINED_PAIR {values}")
    lines.extend(
        [
            "\t/* Pair 15 is the store-only epilogue. */",
            "\tFRONTEND_HIGH_FIRST_FINAL_PAIR",
            ".endm",
            "",
        ]
    )

    wide_offsets = input_offsets(WIDE_PAIRS)
    lines.extend(
        [
            "/* Q/Q+3 wide-load order; fixed stores restore canonical Q order. */",
            ".macro FRONTEND_WIDE_HIGH_FIRST_BODY",
            "\tleaq gt_frontend_wide_twist_qinv_factor(%rip), %r8",
            "\tvmovdqa .Lfront_zeta_top(%rip), %ymm13",
            "\tvmovdqa .Lfront_zeta_top_qinv(%rip), %ymm14",
            "\tvmovdqa .Lfront_q(%rip), %ymm15",
            "",
            "\t/* Pair 0 prologue. */",
            "\tFRONTEND_LOADS_WIDE_FIXED "
            + ", ".join(str(value) for value in wide_offsets[0][::2]),
            "\tFRONTEND_TOP_MONT",
            ".p2align 5",
        ]
    )
    for pair_index, pair_offsets in enumerate(wide_offsets[1:], start=1):
        current_q0, current_q1 = WIDE_PAIRS[pair_index - 1]
        next_q0, next_q1 = WIDE_PAIRS[pair_index]
        if pair_index == 5:
            # Pair (30,1), n3=1 is the only Q/Q+3 row that crosses index 95.
            args = [
                current_q0, current_q1,
                pair_offsets[0], pair_offsets[2], pair_offsets[3],
                pair_offsets[4],
            ]
            macro = "FRONTEND_WIDE_HIGH_FIRST_PIPELINED_PAIR_WRAP1"
        else:
            assert all(pair_offsets[2 * n3 + 1]
                       == pair_offsets[2 * n3] + 24
                       for n3 in range(3))
            args = [current_q0, current_q1]
            args.extend(pair_offsets[2 * n3] for n3 in range(3))
            macro = "FRONTEND_WIDE_HIGH_FIRST_PIPELINED_PAIR"
        lines.append(
            f"\t/* Current ({current_q0},{current_q1}) preloads "
            f"({next_q0},{next_q1}). */")
        lines.append(f"\t{macro} " + ", ".join(str(value) for value in args))
    final_q0, final_q1 = WIDE_PAIRS[-1]
    lines.extend(
        [
            f"\tFRONTEND_WIDE_HIGH_FIRST_FINAL_PAIR {final_q0}, {final_q1}",
            ".endm",
            "",
            "/* Wide duplicated loads + fused split/twist without checkpoint. */",
            ".macro FRONTEND_WIDE_FUSED_DELAYED_BODY",
            "\tleaq gt_frontend_wide_fused_split_twist_qinv_factor(%rip), %r8",
            "\tvmovdqa .Lfront_q(%rip), %ymm15",
            "",
            "\t/* Pair 0 prologue. */",
            "\tFRONTEND_LOADS_WIDE_FIXED "
            + ", ".join(str(value) for value in wide_offsets[0][::2]),
            ".p2align 5",
        ]
    )
    for pair_index, pair_offsets in enumerate(wide_offsets[1:], start=1):
        current_q0, current_q1 = WIDE_PAIRS[pair_index - 1]
        next_q0, next_q1 = WIDE_PAIRS[pair_index]
        if pair_index == 5:
            args = [
                current_q0, current_q1,
                pair_offsets[0], pair_offsets[2], pair_offsets[3],
                pair_offsets[4],
            ]
            macro = "FRONTEND_WIDE_FUSED_PIPELINED_PAIR_WRAP1"
        else:
            args = [current_q0, current_q1]
            args.extend(pair_offsets[2 * n3] for n3 in range(3))
            macro = "FRONTEND_WIDE_FUSED_PIPELINED_PAIR"
        lines.append(
            f"\t/* Current ({current_q0},{current_q1}) preloads "
            f"({next_q0},{next_q1}). */")
        lines.append(f"\t{macro} " + ", ".join(str(value) for value in args))
    lines.extend(
        [
            f"\tFRONTEND_WIDE_FUSED_FINAL_PAIR {final_q0}, {final_q1}",
            ".endm",
            "",
            "/* Move next n3=0 fused chains into the current DFT3 tail. */",
            ".macro FRONTEND_WIDE_FUSED_PARTIAL_N0_BODY",
            "\tleaq gt_frontend_wide_fused_split_twist_qinv_factor(%rip), %r8",
            "\tvmovdqa .Lfront_q(%rip), %ymm15",
            "",
            "\t/* Pair 0 prologue is the only full fused producer. */",
            "\tFRONTEND_LOADS_WIDE_FIXED "
            + ", ".join(str(value) for value in wide_offsets[0][::2]),
            "\tFRONTEND_FUSED_SPLIT_TWIST_DUPLICATED_NOCENTER",
            ".p2align 5",
        ]
    )
    for pair_index, pair_offsets in enumerate(wide_offsets[1:], start=1):
        current_q0, current_q1 = WIDE_PAIRS[pair_index - 1]
        next_q0, next_q1 = WIDE_PAIRS[pair_index]
        if pair_index == 5:
            args = [
                current_q0, current_q1,
                pair_offsets[0], pair_offsets[2], pair_offsets[3],
                pair_offsets[4],
            ]
            macro = "FRONTEND_WIDE_FUSED_PARTIAL_N0_PIPELINED_PAIR_WRAP1"
        else:
            args = [current_q0, current_q1]
            args.extend(pair_offsets[2 * n3] for n3 in range(3))
            macro = "FRONTEND_WIDE_FUSED_PARTIAL_N0_PIPELINED_PAIR"
        lines.append(
            f"\t/* Current ({current_q0},{current_q1}) fuses next "
            f"({next_q0},{next_q1}) n3=0. */")
        lines.append(f"\t{macro} " + ", ".join(str(value) for value in args))
    lines.extend(
        [
            f"\tFRONTEND_WIDE_FUSED_PARTIAL_N0_FINAL_PAIR "
            f"{final_q0}, {final_q1}",
            ".endm",
            "",
        ]
    )
    return "\n".join(lines)


def render() -> str:
    adjacent_pairs = [(q_index, q_index + 1) for q_index in range(0, 32, 2)]
    stripe_pairs = [
        pair
        for q_index in range(8)
        for pair in ((q_index, q_index + 16),
                     (q_index + 8, q_index + 24))
    ]

    return "\n".join(
        [
            "/* Generated by generate_gt_frontend_tables.py; do not hand-edit. */",
            format_offsets("gt_frontend_input_byte_offset",
                           input_offsets(adjacent_pairs)),
            "",
            format_twists("gt_frontend_twist_qinv_factor",
                          packed_twists(adjacent_pairs)),
            "",
            "/* Fused split+twist order: low*qinv, low, high*qinv, high. */",
            format_twists("gt_frontend_fused_split_twist_qinv_factor",
                          packed_fused_split_twists(adjacent_pairs)),
            "",
            "/* Q/Q+3 order used by the 32-byte wide-load candidates. */",
            format_twists("gt_frontend_wide_twist_qinv_factor",
                          packed_twists(WIDE_PAIRS)),
            "",
            "/* Wide fused order: low*qinv, low, high*qinv, high. */",
            format_twists("gt_frontend_wide_fused_split_twist_qinv_factor",
                          packed_fused_split_twists(WIDE_PAIRS)),
            "",
            "/* Stripe order: (q,q+16), (q+8,q+24), q=0..7. */",
            format_offsets("gt_frontend_stripe_input_byte_offset",
                           input_offsets(stripe_pairs)),
            "",
            format_twists("gt_frontend_stripe_twist_qinv_factor",
                          packed_twists(stripe_pairs)),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", type=Path, help="fail if FILE is stale")
    parser.add_argument("--output", type=Path, help="write generated table to FILE")
    parser.add_argument("--check-asm", type=Path,
                        help="fail if generated ASM include FILE is stale")
    parser.add_argument("--asm-output", type=Path,
                        help="write fixed-offset ASM include to FILE")
    args = parser.parse_args()
    generated = render()
    generated_asm = render_fixed_offset_asm()

    selected = [args.check, args.output, args.check_asm, args.asm_output]
    if sum(value is not None for value in selected) > 1:
        parser.error("output/check options are mutually exclusive")
    if args.output is not None:
        args.output.write_text(generated)
        print(f"table-generated file={args.output}")
        return 0
    if args.asm_output is not None:
        args.asm_output.write_text(generated_asm)
        print(f"asm-generated file={args.asm_output}")
        return 0
    if args.check_asm is not None:
        if args.check_asm.read_text() != generated_asm:
            print(f"stale generated ASM include: {args.check_asm}")
            return 1
        print(f"asm-check=passed file={args.check_asm}")
        return 0
    if args.check is None:
        print(generated, end="")
        return 0
    if args.check.read_text() != generated:
        print(f"stale generated table: {args.check}")
        return 1
    print(f"table-check=passed file={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
