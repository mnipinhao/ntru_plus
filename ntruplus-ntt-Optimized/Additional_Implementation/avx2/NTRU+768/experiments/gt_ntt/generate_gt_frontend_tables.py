#!/usr/bin/env python3
"""Generate packed mapping and twist tables for the AVX2 GT frontend."""

import argparse
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
BRANCH_SCALE = (2, 22)


def centered(value: int) -> int:
    value %= Q
    if value > Q // 2:
        value -= Q
    return value


def signed16(value: int) -> int:
    value &= 0xFFFF
    if value >= 0x8000:
        value -= 0x10000
    return value


def input_index(n3: int, q_index: int) -> int:
    return (64 * n3 + 33 * q_index) % 96


def twist(branch: int, index: int) -> int:
    return centered(pow(BRANCH_SCALE[branch], -index, Q) * R)


def input_offsets() -> list[list[int]]:
    return [
        [
            8 * input_index(n3, q_index + parity)
            for n3 in range(3)
            for parity in range(2)
        ]
        for q_index in range(0, 32, 2)
    ]


def packed_twists() -> list[list[list[int]]]:
    table = []
    for q_index in range(0, 32, 2):
        pair = []
        for n3 in range(3):
            factors = []
            for parity in range(2):
                index = input_index(n3, q_index + parity)
                factors.extend([twist(0, index)] * 4)
                factors.extend([twist(1, index)] * 4)
            # The assembly issues the low product before the high product.
            pair.append([signed16(value * QINV) for value in factors] + factors)
        table.append(pair)
    return table


def format_offsets(table: list[list[int]]) -> str:
    lines = [
        "const uint16_t gt_frontend_input_byte_offset[16][6]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for row in table:
        values = ", ".join(f"{value:3d}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def format_twists(table: list[list[list[int]]]) -> str:
    lines = [
        "const int16_t gt_frontend_twist_qinv_factor[16][3][32]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for pair in table:
        lines.append("\t{")
        for row in pair:
            values = ", ".join(f"{value:6d}" for value in row)
            lines.append(f"\t\t{{ {values} }},")
        lines.append("\t},")
    lines.append("};")
    return "\n".join(lines)


def render() -> str:
    return "\n".join(
        [
            "/* Generated by generate_gt_frontend_tables.py; do not hand-edit. */",
            format_offsets(input_offsets()),
            "",
            format_twists(packed_twists()),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", type=Path, help="fail if FILE is stale")
    args = parser.parse_args()
    generated = render()

    if args.check is None:
        print(generated, end="")
        return 0
    if args.check.read_text() != generated:
        print(f"stale generated table: {args.check}")
        return 1
    print(f"table-check=passed file={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
