#!/usr/bin/env python3
"""Generate packed mapping and twist tables for the AVX2 GT frontend."""

import argparse
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
BRANCH_SCALE = (2, 22)


def centered(value: int) -> int:
    value %= Q
    if value > Q // 2:
        value -= Q
    return value


def signed16(value: int) -> int:
    value &= 0xFFFF
    if value >= 0x8000:
        value -= 0x10000
    return value


def input_index(n3: int, q_index: int) -> int:
    return (64 * n3 + 33 * q_index) % 96


def twist(branch: int, index: int) -> int:
    return centered(pow(BRANCH_SCALE[branch], -index, Q) * R)


def input_offsets(pairs: list[tuple[int, int]]) -> list[list[int]]:
    return [
        [
            8 * input_index(n3, q_index)
            for n3 in range(3)
            for q_index in pair
        ]
        for pair in pairs
    ]


def packed_twists(pairs: list[tuple[int, int]]) -> list[list[list[int]]]:
    table = []
    for pair_indices in pairs:
        pair = []
        for n3 in range(3):
            factors = []
            for q_index in pair_indices:
                index = input_index(n3, q_index)
                factors.extend([twist(0, index)] * 4)
                factors.extend([twist(1, index)] * 4)
            # The assembly issues the low product before the high product.
            pair.append([signed16(value * QINV) for value in factors] + factors)
        table.append(pair)
    return table


def format_offsets(name: str, table: list[list[int]]) -> str:
    lines = [
        f"const uint16_t {name}[16][6]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for row in table:
        values = ", ".join(f"{value:3d}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def format_twists(name: str, table: list[list[list[int]]]) -> str:
    lines = [
        f"const int16_t {name}[16][3][32]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for pair in table:
        lines.append("\t{")
        for row in pair:
            values = ", ".join(f"{value:6d}" for value in row)
            lines.append(f"\t\t{{ {values} }},")
        lines.append("\t},")
    lines.append("};")
    return "\n".join(lines)


def render() -> str:
    adjacent_pairs = [(q_index, q_index + 1) for q_index in range(0, 32, 2)]
    stripe_pairs = [
        pair
        for q_index in range(8)
        for pair in ((q_index, q_index + 16),
                     (q_index + 8, q_index + 24))
    ]

    return "\n".join(
        [
            "/* Generated by generate_gt_frontend_tables.py; do not hand-edit. */",
            format_offsets("gt_frontend_input_byte_offset",
                           input_offsets(adjacent_pairs)),
            "",
            format_twists("gt_frontend_twist_qinv_factor",
                          packed_twists(adjacent_pairs)),
            "",
            "/* Stripe order: (q,q+16), (q+8,q+24), q=0..7. */",
            format_offsets("gt_frontend_stripe_input_byte_offset",
                           input_offsets(stripe_pairs)),
            "",
            format_twists("gt_frontend_stripe_twist_qinv_factor",
                          packed_twists(stripe_pairs)),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", type=Path, help="fail if FILE is stale")
    parser.add_argument("--output", type=Path, help="write generated table to FILE")
    args = parser.parse_args()
    generated = render()

    if args.check is not None and args.output is not None:
        parser.error("--check and --output are mutually exclusive")
    if args.output is not None:
        args.output.write_text(generated)
        print(f"table-generated file={args.output}")
        return 0
    if args.check is None:
        print(generated, end="")
        return 0
    if args.check.read_text() != generated:
        print(f"stale generated table: {args.check}")
        return 1
    print(f"table-check=passed file={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
