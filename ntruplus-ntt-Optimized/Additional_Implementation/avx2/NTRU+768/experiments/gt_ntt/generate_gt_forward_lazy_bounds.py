#!/usr/bin/env python3
"""Generate and check the delayed-center Forward terminal range contract."""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import sys


Q = 3457
M = Q - 1
MONT_SIGNED_HALF = 1 << 15
CENTER_FACTOR = 10
CENTER_ROUND = 1 << 14


def center_image(bound: int) -> tuple[int, int]:
    image = [
        value - ((value * CENTER_FACTOR + CENTER_ROUND) // (1 << 15)) * Q
        for value in range(-bound, bound + 1)
    ]
    return min(image), max(image)


def derive() -> dict[str, int | tuple[int, int]]:
    # The wide fused frontend has three independently bounded DFT3 rows.
    row0_dft3 = 6 * M
    row12_dft3 = 5 * M

    row0_stage3 = row0_dft3 + 3 * M
    row12_stage3 = row12_dft3 + 3 * M
    row0_center = center_image(row0_stage3)
    row12_center = center_image(row12_stage3)

    # Stage 4 and Stage 5 each add/subtract one Montgomery-reduced high arm.
    row0_terminal = max(abs(row0_center[0]), abs(row0_center[1])) + 2 * M
    row12_terminal = max(abs(row12_center[0]), abs(row12_center[1])) + 2 * M

    montgomery_limit = Q * MONT_SIGNED_HALF
    square_safe_bound = math.isqrt(montgomery_limit - 1)

    result: dict[str, int | tuple[int, int]] = {
        "row0_dft3": row0_dft3,
        "row12_dft3": row12_dft3,
        "row0_stage3": row0_stage3,
        "row12_stage3": row12_stage3,
        "row0_center": row0_center,
        "row12_center": row12_center,
        "row01_terminal": max(row0_terminal, row12_terminal),
        "row2_terminal": row12_terminal,
        "l3_envelope": 3 * M,
        "montgomery_limit": montgomery_limit,
        "square_safe_bound": square_safe_bound,
    }

    assert row0_stage3 * 1728 < montgomery_limit
    assert row12_stage3 * 1728 < montgomery_limit
    assert row0_terminal < 3 * M
    assert row12_terminal < 3 * M
    assert (3 * M) ** 2 < montgomery_limit
    assert row0_terminal**2 < montgomery_limit
    assert row12_terminal**2 < montgomery_limit
    return result


def render_header(values: dict[str, int | tuple[int, int]]) -> str:
    return f"""\
/* Generated by generate_gt_forward_lazy_bounds.py; do not edit. */
#ifndef NTRUPLUS_GT_FORWARD_LAZY_BOUNDS_H
#define NTRUPLUS_GT_FORWARD_LAZY_BOUNDS_H

#define GT_FORWARD_LAZY_ROW01_BOUND {values["row01_terminal"]}
#define GT_FORWARD_LAZY_ROW2_BOUND {values["row2_terminal"]}
#define GT_FORWARD_LAZY_L3_BOUND {values["l3_envelope"]}
#define GT_BASEINV_MONT_SQUARE_SAFE_BOUND {values["square_safe_bound"]}

#define GT_FORWARD_LAZY_BATCH_BOUND(batch) \\
\t((batch) < 8U ? GT_FORWARD_LAZY_ROW01_BOUND : \\
\t GT_FORWARD_LAZY_ROW2_BOUND)

#endif
"""


def render_contract(values: dict[str, int | tuple[int, int]]) -> str:
    row0_center = values["row0_center"]
    row12_center = values["row12_center"]
    assert isinstance(row0_center, tuple)
    assert isinstance(row12_center, tuple)

    lines = [
        "# Generated by generate_gt_forward_lazy_bounds.py; do not edit.",
        "contract: ntruplus768_gt_forward_lazy_terminal_bounds",
        "status: benchmark_only_default_off",
        "",
        "arithmetic:",
        f"  q: {Q}",
        f"  q_minus_1: {M}",
        "  lane: signed_int16",
        f"  montgomery_unknown_product_limit: {values['montgomery_limit']}",
        f"  montgomery_square_safe_absolute_bound: {values['square_safe_bound']}",
        f"  gtn_l3_envelope: {values['l3_envelope']}",
        "",
        "recurrence:",
        "  wide_fused_frontend:",
        f"    row0_dft3_absolute_bound: {values['row0_dft3']}",
        f"    row1_row2_dft3_absolute_bound: {values['row12_dft3']}",
        "  after_three_radix2_stages:",
        f"    row0_absolute_bound: {values['row0_stage3']}",
        f"    row1_row2_absolute_bound: {values['row12_stage3']}",
        "  delayed_center10_exact_image:",
        f"    row0: [{row0_center[0]}, {row0_center[1]}]",
        f"    row1_row2: [{row12_center[0]}, {row12_center[1]}]",
        "  after_stage4_and_stage5:",
        f"    row0_absolute_bound: {values['row01_terminal']}",
        f"    row1_row2_absolute_bound: {values['row2_terminal']}",
        "",
        "baseinv:",
        "  normalization_vectors_required_for_forward_output: 0",
        f"  row01_max_square: {int(values['row01_terminal']) ** 2}",
        f"  row2_max_square: {int(values['row2_terminal']) ** 2}",
        "  initial_unknown_products_montgomery_safe: true",
        "  direct_consumer_format: GTN-L3",
        "",
        "vector_slot_semantics:",
        "  vector: 4*batch+coefficient",
        "  word_offset: 16*vector",
        "  next_consumer: baseinv_same_batch_and_coefficient",
        "  row01_lane: (Q_mod_8)+8*k3",
        "  row2_lane: (Q_mod_8)+8*floor(Q/16)",
        "",
        "vector_groups:",
    ]

    lines.extend(
        [
            "  - vectors: ["
            + ", ".join(str(vector) for vector in range(32))
            + "]",
            "    batches: [0, 7]",
            "    coefficients: [0, 3]",
            "    row_family: row01",
            f"    absolute_bound: {values['row01_terminal']}",
            "    direct_baseinv_square_safe: true",
            "  - vectors: ["
            + ", ".join(str(vector) for vector in range(32, 48))
            + "]",
            "    batches: [8, 11]",
            "    coefficients: [0, 3]",
            "    row_family: row2",
            f"    absolute_bound: {values['row2_terminal']}",
            "    direct_baseinv_square_safe: true",
        ]
    )
    lines.extend(
        [
            "",
            "constant_time:",
            "  normalization_mask: all_zero_public_constant",
            "  coefficient_dependent_control_flow: false",
            "  coefficient_dependent_addresses: false",
            "",
        ]
    )
    return "\n".join(lines)


def check_file(path: Path, expected: str) -> bool:
    try:
        actual = path.read_text()
    except FileNotFoundError:
        print(f"missing generated file: {path}", file=sys.stderr)
        return False
    if actual != expected:
        print(
            f"stale generated file: {path}; regenerate with this script",
            file=sys.stderr,
        )
        return False
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check-header", type=Path)
    parser.add_argument("--check-contract", type=Path)
    parser.add_argument(
        "--emit", choices=("header", "contract"), default="contract"
    )
    args = parser.parse_args()
    values = derive()
    header = render_header(values)
    contract = render_contract(values)

    ok = True
    if args.check_header is not None:
        ok &= check_file(args.check_header, header)
    if args.check_contract is not None:
        ok &= check_file(args.check_contract, contract)
    if args.check_header is not None or args.check_contract is not None:
        return 0 if ok else 1

    sys.stdout.write(header if args.emit == "header" else contract)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
