#!/usr/bin/env python3
"""Generate AVX2 GT SoA/native lambda and lambda*qinv tables."""

import argparse
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
OMEGA96 = 675
BRANCH_SCALE = (2, 22)


def centered(value: int) -> int:
    value %= Q
    if value > Q // 2:
        value -= Q
    return value


def signed16(value: int) -> int:
    value &= 0xFFFF
    if value >= 0x8000:
        value -= 0x10000
    return value


def bitreverse5(value: int) -> int:
    result = 0
    for _ in range(5):
        result = (result << 1) | (value & 1)
        value >>= 1
    return result


def lambda_montgomery(k3: int, q_index: int, branch: int) -> int:
    logical = (32 * k3 + 3 * bitreverse5(q_index)) % 96
    normal = pow(OMEGA96, logical, Q) * pow(BRANCH_SCALE[branch], -1, Q)
    return centered(normal * R)


def make_table() -> list[list[int]]:
    table = []
    for batch in range(12):
        k3 = batch // 4
        q_base = 8 * (batch % 4)
        row = []
        for branch in range(2):
            for lane in range(8):
                row.append(lambda_montgomery(k3, q_base + lane, branch))
        table.append(row)
    return table


def make_native_table() -> list[list[int]]:
    """Return lambdas in the fused Stage345 native output lane order."""
    table = []

    # row0/1: batch=(2*g+branch), lane=(Q%8)+8*k3, k3 in {0,1}.
    for g in range(4):
        for branch in range(2):
            row = []
            for k3 in range(2):
                for lane in range(8):
                    row.append(lambda_montgomery(k3, 8 * g + lane, branch))
            table.append(row)

    # row2: batch=8+(2*g+branch), lane=(Q%8)+8*(Q//16), k3=2.
    for g in range(2):
        for branch in range(2):
            row = []
            for q_half in range(2):
                for lane in range(8):
                    q_index = 16 * q_half + 8 * g + lane
                    row.append(lambda_montgomery(2, q_index, branch))
            table.append(row)

    return table


def format_table(name: str, table: list[list[int]]) -> str:
    lines = [
        f"const int16_t {name}[GT_SOA_BATCHES][GT_SOA_LANES]",
        "\t__attribute__((aligned(32))) = {",
    ]
    for row in table:
        values = ", ".join(f"{value:6d}" for value in row)
        lines.append(f"\t{{ {values} }},")
    lines.append("};")
    return "\n".join(lines)


def render() -> str:
    lambdas = make_table()
    native_lambdas = make_native_table()
    lambda_qinv = [
        [signed16(value * QINV) for value in row]
        for row in lambdas
    ]
    native_lambda_qinv = [
        [signed16(value * QINV) for value in row]
        for row in native_lambdas
    ]
    return "\n".join(
        [
            "/* Generated by generate_gt_soa_tables.py; do not hand-edit. */",
            format_table("gt_soa_lambda", lambdas),
            "",
            format_table("gt_soa_lambda_qinv", lambda_qinv),
            "",
            format_table("gt_native_lambda", native_lambdas),
            "",
            format_table("gt_native_lambda_qinv", native_lambda_qinv),
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", type=Path, help="fail if FILE is stale")
    args = parser.parse_args()
    generated = render()

    if args.check is None:
        print(generated, end="")
        return 0
    if args.check.read_text() != generated:
        print(f"stale generated table: {args.check}")
        return 1
    print(f"table-check=passed file={args.check}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
