#!/usr/bin/env python3
"""Generate fixed (branch=0,k3=0) HWA16/TILE4 island constants."""

from __future__ import annotations

import json
import itertools
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929
OMEGA96 = 675
OMEGA32 = pow(OMEGA96, 3, Q)
BRANCH_SCALE = (2, 22)
BRANCH = 0
K3 = 0
ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "generated"


def centered(x: int) -> int:
    x %= Q
    return x - Q if x > Q // 2 else x


def signed16(x: int) -> int:
    x &= 0xFFFF
    return x - 0x10000 if x >= 0x8000 else x


def bitreverse(x: int, bits: int) -> int:
    y = 0
    for _ in range(bits):
        y = (y << 1) | (x & 1)
        x >>= 1
    return y


def mont_root(power: int) -> int:
    return centered(pow(OMEGA32, power % 32, Q) * R)


def factor_qinv(factor: int) -> int:
    return signed16(factor * QINV)


def forward_power(stage: int, group: int) -> int:
    if stage == 1:
        return 0
    return bitreverse(group >> (6 - stage), stage - 1) << (5 - stage)


def lambda_mont(q_index: int) -> int:
    logical = (32 * K3 + 3 * bitreverse(q_index, 5)) % 96
    normal = pow(OMEGA96, logical, Q) * pow(BRANCH_SCALE[BRANCH], -1, Q)
    return centered(normal * R)


def lane_mask(distance: int, high: bool) -> list[int]:
    out = []
    for lane in range(16):
        source = (lane & ~distance) | (distance if high else 0)
        # vpshufb indexes within each 128-bit lane.  d<=4 never crosses it.
        local = source & 7
        out.extend((2 * local, 2 * local + 1))
    return out


def hwa_forward(stage: int) -> list[list[int]]:
    distance = 32 >> stage
    records = []
    for c in range(4):
        for g in range(2):
            row = []
            for lane in range(16):
                q_index = 16 * g + lane
                group = (q_index // (2 * distance)) * (2 * distance)
                row.append(mont_root(forward_power(stage, group)))
            records.append(row)
    return records


def hwa_inverse(length: int) -> list[list[int]]:
    distance = length // 2
    records = []
    for c in range(4):
        for g in range(2):
            row = []
            for lane in range(16):
                q_index = 16 * g + lane
                j = q_index % distance
                row.append(mont_root((-j * (32 // length)) % 32))
            records.append(row)
    return records


def emit_rows(lines: list[str], label: str, rows: list[list[int]]) -> None:
    lines += [".p2align 5", f"{label}:"]
    for row in rows:
        lines.append("\t.short " + ",".join(str(v) for v in row))


def emit_bytes(lines: list[str], label: str, row: list[int]) -> None:
    assert len(row) == 32
    lines += [".p2align 5", f"{label}:",
              "\t.byte " + ",".join(str(v) for v in row)]


def pack_pair_rows(rows: list[list[int]], distance: int) -> list[list[int]]:
    """Constants in the physical low/high stream made by V2 pair routing."""
    packed = []
    for first in range(0, 8, 2):
        a, b = rows[first], rows[first + 1]
        if distance == 8:
            row = a[8:16] + b[8:16]
        elif distance == 4:
            row = a[4:8] + b[4:8] + a[12:16] + b[12:16]
        elif distance == 2:
            row = (a[2:4] + a[6:8] + b[2:4] + b[6:8]
                   + a[10:12] + a[14:16] + b[10:12] + b[14:16])
        else:
            raise ValueError(distance)
        assert len(row) == 16
        packed.append(row)
    return packed


def emit_asm() -> None:
    lines = ["/* Generated by tools/generate.py; do not hand-edit. */"]
    qrow = [[Q] * 16]
    emit_rows(lines, ".Lhwa_q", qrow)
    emit_rows(lines, ".Lhwa_center10", [[10] * 16])
    for stage in range(2, 6):
        rows = hwa_forward(stage)
        emit_rows(lines, f".Lhwa_fwd_s{stage}_factor", rows)
        emit_rows(lines, f".Lhwa_fwd_s{stage}_qinv",
                  [[factor_qinv(v) for v in row] for row in rows])
        distance = 32 >> stage
        if distance >= 2:
            pairs = pack_pair_rows(rows, distance)
            emit_rows(lines, f".Lhwa_fwd_s{stage}_pair_factor", pairs)
            emit_rows(lines, f".Lhwa_fwd_s{stage}_pair_qinv",
                      [[factor_qinv(v) for v in row] for row in pairs])
    for length, ordinal in ((4, 1), (8, 2), (16, 3), (32, 4)):
        rows = hwa_inverse(length)
        distance = length // 2
        emit_rows(lines, f".Lhwa_inv_s{ordinal}_factor", rows)
        emit_rows(lines, f".Lhwa_inv_s{ordinal}_qinv",
                  [[factor_qinv(v) for v in row] for row in rows])
        if distance < 16:
            pairs = pack_pair_rows(rows, distance)
            emit_rows(lines, f".Lhwa_inv_s{ordinal}_pair_factor", pairs)
            emit_rows(lines, f".Lhwa_inv_s{ordinal}_pair_qinv",
                      [[factor_qinv(v) for v in row] for row in pairs])
        else:
            cross = [rows[2 * c + 1] for c in range(4)]
            emit_rows(lines, ".Lhwa_inv_s4_cross_factor", cross)
            emit_rows(lines, ".Lhwa_inv_s4_cross_qinv",
                      [[factor_qinv(v) for v in row] for row in cross])
    for distance in (4, 2, 1):
        emit_bytes(lines, f".Lhwa_d{distance}_lowmask", lane_mask(distance, False))
        emit_bytes(lines, f".Lhwa_d{distance}_highmask", lane_mask(distance, True))

    natural = [[lambda_mont(16 * g + lane) for lane in range(16)]
               for g in range(2)]
    q_order = [0, 4, 8, 12, 1, 5, 9, 13, 2, 6, 10, 14, 3, 7, 11, 15]
    control = [[lambda_mont(16 * g + q) for q in q_order] for g in range(2)]
    emit_rows(lines, ".Lhwa_bm_lambda", natural)
    emit_rows(lines, ".Lhwa_bm_lambda_qinv",
              [[factor_qinv(v) for v in row] for row in natural])
    emit_rows(lines, ".Lctl_bm_lambda", control)
    emit_rows(lines, ".Lctl_bm_lambda_qinv",
              [[factor_qinv(v) for v in row] for row in control])
    (GEN / "hwa16_constants.inc").write_text("\n".join(lines) + "\n")


def emit_manifest() -> None:
    manifest = {
        "experiment": "GT32-HWA16-ISLAND-061",
        "fixed_island": {"branch": BRANCH, "k3": K3, "quartic_leaves": 32},
        "q": Q,
        "r_mod_q": centered(R),
        "qinv": QINV,
        "mapping": "H[c][g][lane]=A[branch][k3][16*g+lane][c]",
        "stage_distances": {"forward": [16, 8, 4, 2, 1],
                            "inverse": [1, 2, 4, 8, 16]},
        "extra_reductions": 0,
        "control": "current TILE4 pair Forward/B3-late-c3center/pair Inverse",
    }
    (GEN / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")


DIMENSIONS = ("ymm", "half", "qword", "dword", "word")
V3_SELECTED = {
    # End-point swap only.
    "m40a": (0, 3, 2, 1, 4),
    # Complete bit reversal.
    "m40b": (0, 1, 2, 3, 4),
    # Move q2 to the cross-128 dimension and q3 to qword.
    "m40c": (0, 2, 3, 1, 4),
}


def physical_q(bits_by_dimension: tuple[int, ...], g: int, lane: int) -> int:
    physical_bits = (g, (lane >> 3) & 1, (lane >> 2) & 1,
                     (lane >> 1) & 1, lane & 1)
    q_index = 0
    for physical, logical_bit in zip(physical_bits, bits_by_dimension):
        q_index |= physical << logical_bit
    return q_index


def v3_rows(bits: tuple[int, ...], inverse_length: int | None,
            forward_stage: int | None) -> list[list[int]]:
    rows = []
    for c in range(4):
        for g in range(2):
            row = []
            for lane in range(16):
                q_index = physical_q(bits, g, lane)
                if forward_stage is not None:
                    distance = 32 >> forward_stage
                    group = (q_index // (2 * distance)) * (2 * distance)
                    power = forward_power(forward_stage, group)
                else:
                    assert inverse_length is not None
                    distance = inverse_length // 2
                    j = q_index % distance
                    power = (-j * (32 // inverse_length)) % 32
                row.append(mont_root(power))
            rows.append(row)
    return rows


def logical_dimension(bits: tuple[int, ...], logical_bit: int) -> str:
    return DIMENSIONS[bits.index(logical_bit)]


def emit_v3() -> None:
    lines = ["/* Generated V3 physical-Q tables; do not hand-edit. */"]
    survey = []
    for bits in itertools.permutations(range(5)):
        bit_dimension = {f"q{bit}": logical_dimension(bits, bit)
                         for bit in range(5)}
        # Routing count is invariant (0+16+16+16+24=72).  This proxy ranks
        # where the weighted 2F+I Montgomery work lands, not expected cycles.
        word_bit = bits[4]
        ymm_bit = bits[0]
        weighted_word_mont = (0 if word_bit == 4 else 2) + (0 if word_bit == 0 else 1)
        weighted_ymm_mont = (0 if ymm_bit == 4 else 2) + (0 if ymm_bit == 0 else 1)
        survey.append({
            "bits_by_dimension": dict(zip(DIMENSIONS, bits)),
            "bit_dimension": bit_dimension,
            "route_instructions_per_transform": 72,
            "weighted_word_mont": weighted_word_mont,
            "weighted_ymm_mont": weighted_ymm_mont,
            "selected": next((name for name, value in V3_SELECTED.items()
                              if value == bits), None),
        })
    survey.sort(key=lambda row: (row["weighted_word_mont"],
                                 -row["weighted_ymm_mont"],
                                 tuple(row["bits_by_dimension"].values())))

    for name, bits in V3_SELECTED.items():
        for stage in range(2, 6):
            rows = v3_rows(bits, None, stage)
            dimension = logical_dimension(bits, 5 - stage)
            if dimension == "ymm":
                material = [rows[2 * c + 1] for c in range(4)]
            elif dimension == "half":
                material = pack_pair_rows(rows, 8)
            elif dimension == "qword":
                material = pack_pair_rows(rows, 4)
            elif dimension == "dword":
                material = pack_pair_rows(rows, 2)
            else:
                material = rows
            emit_rows(lines, f".Lv3_{name}_fwd_s{stage}_factor", material)
            emit_rows(lines, f".Lv3_{name}_fwd_s{stage}_qinv",
                      [[factor_qinv(v) for v in row] for row in material])
        for length, ordinal in ((4, 1), (8, 2), (16, 3), (32, 4)):
            rows = v3_rows(bits, length, None)
            dimension = logical_dimension(bits, ordinal)  # q1,q2,q3,q4
            if dimension == "ymm":
                material = [rows[2 * c + 1] for c in range(4)]
            elif dimension == "half":
                material = pack_pair_rows(rows, 8)
            elif dimension == "qword":
                material = pack_pair_rows(rows, 4)
            elif dimension == "dword":
                material = pack_pair_rows(rows, 2)
            else:
                material = rows
            emit_rows(lines, f".Lv3_{name}_inv_s{ordinal}_factor", material)
            emit_rows(lines, f".Lv3_{name}_inv_s{ordinal}_qinv",
                      [[factor_qinv(v) for v in row] for row in material])
        lambdas = [[lambda_mont(physical_q(bits, g, lane)) for lane in range(16)]
                   for g in range(2)]
        emit_rows(lines, f".Lv3_{name}_lambda", lambdas)
        emit_rows(lines, f".Lv3_{name}_lambda_qinv",
                  [[factor_qinv(v) for v in row] for row in lambdas])

    (GEN / "v3_constants.inc").write_text("\n".join(lines) + "\n")
    (GEN / "v3_mapping_survey.json").write_text(json.dumps({
        "count": len(survey),
        "dimensions": DIMENSIONS,
        "selected": {name: dict(zip(DIMENSIONS, bits))
                     for name, bits in V3_SELECTED.items()},
        "note": "static routing ties; selection spans middle-bit scheduling",
        "candidates": survey,
    }, indent=2) + "\n")


if __name__ == "__main__":
    GEN.mkdir(exist_ok=True)
    emit_asm()
    emit_manifest()
    emit_v3()
