#!/usr/bin/env python3
"""Generate Y2 terminal constants that consume an R^-1 Official product."""

import argparse
import json
from pathlib import Path

Q = 3457
R = (1 << 16) % Q
QINV = 12929


def signed16(value: int) -> int:
    value &= 0xffff
    return value - 0x10000 if value >= 0x8000 else value


def centered(value: int) -> int:
    value %= Q
    return value - Q if value > Q // 2 else value


def render(source: Path) -> str:
    metadata = json.loads(source.read_text())
    lines = ["/* Generated by generate_rminus1_terminal.py; do not edit. */",
             ".p2align 5", ".Lterminal_offsets:"]
    for record in metadata["records"]:
        lines.append("\t.long " + ", ".join(str(x) for x in record["output_offsets"]))
    lines.extend([".p2align 5", ".Lterminal_direct_tables:"])
    for record in metadata["records"]:
        for value_key in ("direct_p_lanes", "direct_q_lanes"):
            values = [centered(int(x) * R) for x in record[value_key]]
            qinvs = [signed16(x * QINV) for x in values]
            lines.append("\t.short " + ", ".join(str(x) for x in values))
            lines.append("\t.short " + ", ".join(str(x) for x in qinvs))
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", type=Path)
    args = parser.parse_args()
    generated = render(args.source)
    if args.output:
        args.output.write_text(generated)
    elif args.check:
        if args.check.read_text() != generated:
            raise SystemExit(f"stale: {args.check}")
        print(f"rminus1-terminal-check=passed file={args.check}")
    else:
        print(generated, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
