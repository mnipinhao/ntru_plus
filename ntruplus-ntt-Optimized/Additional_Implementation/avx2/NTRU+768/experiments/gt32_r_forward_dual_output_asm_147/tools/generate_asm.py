#!/usr/bin/env python3
from pathlib import Path
import re

HERE = Path(__file__).resolve()
EXP = HERE.parents[1]
ROOT = HERE.parents[3]
OUT = EXP / "generated" / "dual_output.s"


def macro(text: str, name: str) -> str:
    m = re.search(rf"^\s*\.macro\s+{re.escape(name)}\b.*?^\s*\.endm\s*$", text,
                  re.MULTILINE | re.DOTALL)
    if not m:
        raise RuntimeError(name)
    return m.group(0)


def section_for_label(text: str, label: str) -> str:
    pos = text.index(label + ":")
    start = text.rfind(" .section ", 0, pos)
    end = text.find(" .section ", pos)
    if start < 0 or end < 0:
        raise RuntimeError(label)
    return text[start:end]


def process_half(regs: tuple[int, int, int, int], moff: int, pattern: int,
                 woff: int, safe: int) -> str:
    a, b, c, d = regs
    return f"""
 /* Match GT103_STORE_QL2 memory order: v0,v2,v1,v3. */
 GT147_Q_ONLY ymm{a},ymm{c},ymm{b},ymm{d}
 GT147_PATTERN {pattern},{woff},{safe}
 GT147_TO_M ymm{a},ymm{b},ymm{c},ymm{d},{moff}
"""


def handler(tile: int, low: tuple[int, int, int], high: tuple[int, int, int]) -> str:
    lp, lo, ls = low
    hp, ho, hs = high
    return f""".Lgt147_tile{tile}:
{process_half((0,1,2,3), 0, lp, lo, ls)}
{process_half((4,5,6,7), 128, hp, ho, hs)}
 jmp .Lgt147_next
"""


def main() -> None:
    ntt = (ROOT / "ntt_m.s").read_text()
    macros = "\n".join(macro(ntt, name) for name in (
        "FR_MONT_CROSS4", "FR_RAW_CROSS4", "FR_MONT_HALF_PAIR",
        "FR_MONT_QWORD_PACKED"))
    constants = "\n".join(section_for_label(ntt, label) for label in (
        ".Lfr_q", ".Ltile4_fwd_s2_qinv", ".Ltile4_fwd_s2_factor",
        ".Ltile4_fwd_s3_qinv", ".Ltile4_fwd_s3_factor",
        ".Ltile4_fwd_s4_pair_qinv", ".Ltile4_fwd_s4_pair_factor",
        ".Ltile4_fwd_s5_pair_qinv", ".Ltile4_fwd_s5_pair_factor"))

    # pattern: 0=[11,10,8,9], 1=[8,9,10,11], 2=[10,11,9,8],
    #          3=[9,8,11,10], 4=[10,11,9,8] with different immediates.
    # Linear tile execution needs exact final stores at six group boundaries.
    handlers = "".join((
        handler(0, (0, 0, 0), (0, 96, 0)),
        handler(1, (2, 1056, 1), (1, 960, 1)),
        handler(2, (3, 384, 0), (3, 480, 0)),
        handler(3, (0, 768, 0), (0, 864, 1)),
        handler(4, (2, 288, 1), (1, 192, 1)),
        handler(5, (3, 672, 1), (4, 576, 1)),
    ))

    source = f"""/* Generated by tools/generate_asm.py. */
.text
{macros}

.macro GT147_Q_ONLY a,b,c,d
 vpunpcklqdq %\\c, %\\a, %ymm8
 vpunpckhqdq %\\c, %\\a, %ymm9
 vpunpcklqdq %\\d, %\\b, %ymm10
 vpunpckhqdq %\\d, %\\b, %ymm11
.endm

.macro GT147_STORE src,tmp,offset,safe
 vmovdqu %xmm\\src, \\offset(%rdx)
 vextracti128 $1, %ymm\\src, %xmm\\tmp
.if \\safe
 vmovq %xmm\\tmp, \\offset+12(%rdx)
 vpextrd $2, %xmm\\tmp, \\offset+20(%rdx)
.else
 vmovdqu %xmm\\tmp, \\offset+12(%rdx)
.endif
.endm

.macro GT147_QUAD a,ap,ao,asafe,b,bp,bo,bsafe,c,cp,co,csafe,d,dp,do,dsafe
 /* S5 is complete, so ymm12/13/15 no longer hold live NTT constants.
    Four temporaries expose the four independent packet chains to OoO. */
 vpmulhrsw .Lgt147_v(%rip), %ymm\\a, %ymm12
 vpmulhrsw .Lgt147_v(%rip), %ymm\\b, %ymm13
 vpmulhrsw .Lgt147_v(%rip), %ymm\\c, %ymm14
 vpmulhrsw .Lgt147_v(%rip), %ymm\\d, %ymm15
 vpmullw .Lfr_q(%rip), %ymm12, %ymm12
 vpmullw .Lfr_q(%rip), %ymm13, %ymm13
 vpmullw .Lfr_q(%rip), %ymm14, %ymm14
 vpmullw .Lfr_q(%rip), %ymm15, %ymm15
 vpsubw %ymm12, %ymm\\a, %ymm\\a
 vpsubw %ymm13, %ymm\\b, %ymm\\b
 vpsubw %ymm14, %ymm\\c, %ymm\\c
 vpsubw %ymm15, %ymm\\d, %ymm\\d
 vpermq $\\ap, %ymm\\a, %ymm\\a
 vpermq $\\bp, %ymm\\b, %ymm\\b
 vpermq $\\cp, %ymm\\c, %ymm\\c
 vpermq $\\dp, %ymm\\d, %ymm\\d
 vpsraw $15, %ymm\\a, %ymm12
 vpsraw $15, %ymm\\b, %ymm13
 vpsraw $15, %ymm\\c, %ymm14
 vpsraw $15, %ymm\\d, %ymm15
 vpand .Lfr_q(%rip), %ymm12, %ymm12
 vpand .Lfr_q(%rip), %ymm13, %ymm13
 vpand .Lfr_q(%rip), %ymm14, %ymm14
 vpand .Lfr_q(%rip), %ymm15, %ymm15
 vpaddw %ymm12, %ymm\\a, %ymm\\a
 vpaddw %ymm13, %ymm\\b, %ymm\\b
 vpaddw %ymm14, %ymm\\c, %ymm\\c
 vpaddw %ymm15, %ymm\\d, %ymm\\d
 vpmaddwd .Lgt147_pair_factor(%rip), %ymm\\a, %ymm\\a
 vpmaddwd .Lgt147_pair_factor(%rip), %ymm\\b, %ymm\\b
 vpmaddwd .Lgt147_pair_factor(%rip), %ymm\\c, %ymm\\c
 vpmaddwd .Lgt147_pair_factor(%rip), %ymm\\d, %ymm\\d
 vpshufb .Lgt147_pack_mask(%rip), %ymm\\a, %ymm\\a
 vpshufb .Lgt147_pack_mask(%rip), %ymm\\b, %ymm\\b
 vpshufb .Lgt147_pack_mask(%rip), %ymm\\c, %ymm\\c
 vpshufb .Lgt147_pack_mask(%rip), %ymm\\d, %ymm\\d
 GT147_STORE \\a,12,\\ao,\\asafe
 GT147_STORE \\b,13,\\bo,\\bsafe
 GT147_STORE \\c,14,\\co,\\csafe
 GT147_STORE \\d,15,\\do,\\dsafe
.endm

.macro GT147_PATTERN pattern,base,safe
.if \\pattern == 0
 GT147_QUAD 11,177,\\base+0,0, 10,75,\\base+24,0, 8,75,\\base+48,0, 9,75,\\base+72,\\safe
.elseif \\pattern == 1
 GT147_QUAD 8,228,\\base+0,0, 9,228,\\base+24,0, 10,228,\\base+48,0, 11,228,\\base+72,\\safe
.elseif \\pattern == 2
 GT147_QUAD 10,228,\\base+0,0, 11,228,\\base+24,0, 9,228,\\base+48,0, 8,30,\\base+72,\\safe
.elseif \\pattern == 3
 GT147_QUAD 9,30,\\base+0,0, 8,177,\\base+24,0, 11,30,\\base+48,0, 10,177,\\base+72,\\safe
.else
 GT147_QUAD 10,30,\\base+0,0, 11,30,\\base+24,0, 9,30,\\base+48,0, 8,177,\\base+72,\\safe
.endif
.endm

.macro GT147_TO_M a,b,c,d,outoff
 vpshufb .Lfr_plane_pshufb(%rip), %\\a, %\\a
 vpshufb .Lfr_plane_pshufb(%rip), %\\b, %\\b
 vpshufb .Lfr_plane_pshufb(%rip), %\\c, %\\c
 vpshufb .Lfr_plane_pshufb(%rip), %\\d, %\\d
 vpunpckldq %\\c, %\\a, %ymm8
 vpunpckhdq %\\c, %\\a, %ymm9
 vpunpckldq %\\d, %\\b, %ymm10
 vpunpckhdq %\\d, %\\b, %ymm11
 vpunpcklqdq %ymm10, %ymm8, %\\a
 vpunpckhqdq %ymm10, %ymm8, %\\b
 vpunpcklqdq %ymm11, %ymm9, %\\c
 vpunpckhqdq %ymm11, %ymm9, %\\d
 vmovdqu %\\a, \\outoff+0(%rdi)
 vmovdqu %\\b, \\outoff+32(%rdi)
 vmovdqu %\\c, \\outoff+64(%rdi)
 vmovdqu %\\d, \\outoff+96(%rdi)
.endm

.section .text.gt147_dual_output,"ax",@progbits
.p2align 5
.globl gt147_ntt_m_wire_avx2
.type gt147_ntt_m_wire_avx2,@function
gt147_ntt_m_wire_avx2:
 xorl %ecx, %ecx
.p2align 5
.Lgt147_core:
 vmovdqa .Lfr_q(%rip), %ymm15
 vmovdqu 0(%rsi), %ymm0
 vmovdqu 32(%rsi), %ymm1
 vmovdqu 64(%rsi), %ymm2
 vmovdqu 96(%rsi), %ymm3
 vmovdqu 128(%rsi), %ymm4
 vmovdqu 160(%rsi), %ymm5
 vmovdqu 192(%rsi), %ymm6
 vmovdqu 224(%rsi), %ymm7
 FR_RAW_CROSS4 %ymm0,%ymm4,%ymm1,%ymm5,%ymm2,%ymm6,%ymm3,%ymm7
 FR_MONT_CROSS4 %ymm0,%ymm2,%ymm1,%ymm3,%ymm4,%ymm6,%ymm5,%ymm7, .Ltile4_fwd_s2_qinv,.Ltile4_fwd_s2_factor
 FR_MONT_CROSS4 %ymm0,%ymm1,%ymm2,%ymm3,%ymm4,%ymm5,%ymm6,%ymm7, .Ltile4_fwd_s3_qinv,.Ltile4_fwd_s3_factor
 FR_MONT_HALF_PAIR %ymm0,%ymm1,0
 FR_MONT_HALF_PAIR %ymm2,%ymm3,32
 FR_MONT_QWORD_PACKED %ymm0,%ymm1,0
 FR_MONT_HALF_PAIR %ymm4,%ymm5,64
 FR_MONT_QWORD_PACKED %ymm2,%ymm3,32
 FR_MONT_HALF_PAIR %ymm6,%ymm7,96
 FR_MONT_QWORD_PACKED %ymm4,%ymm5,64
 FR_MONT_QWORD_PACKED %ymm6,%ymm7,96
 leaq .Lgt147_handlers(%rip), %rax
 movslq (%rax,%rcx,4), %r8
 addq %rax, %r8
 jmp *%r8

{handlers}
.Lgt147_next:
 addq $256, %rsi
 addq $256, %rdi
 incl %ecx
 cmpl $6, %ecx
 jne .Lgt147_core
 vzeroupper
 ret
.size gt147_ntt_m_wire_avx2,.-gt147_ntt_m_wire_avx2

.section .rodata.gt147,"a",@progbits
.p2align 5
.Lgt147_handlers:
 .long .Lgt147_tile0-.Lgt147_handlers
 .long .Lgt147_tile1-.Lgt147_handlers
 .long .Lgt147_tile2-.Lgt147_handlers
 .long .Lgt147_tile3-.Lgt147_handlers
 .long .Lgt147_tile4-.Lgt147_handlers
 .long .Lgt147_tile5-.Lgt147_handlers
.p2align 5
.Lgt147_v:
 .rept 16
 .short 9
 .endr
.Lgt147_pair_factor:
 .rept 8
 .short 1,4096
 .endr
.Lgt147_pack_mask:
 .byte 0,1,2,4,5,6,8,9,10,12,13,14,128,128,128,128
 .byte 0,1,2,4,5,6,8,9,10,12,13,14,128,128,128,128

{constants}
.section .note.GNU-stack,"",@progbits
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(source)
    print(f"generated {OUT}")


if __name__ == "__main__":
    main()
