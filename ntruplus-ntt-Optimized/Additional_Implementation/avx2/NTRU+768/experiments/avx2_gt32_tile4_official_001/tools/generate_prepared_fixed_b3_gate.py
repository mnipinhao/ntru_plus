#!/usr/bin/env python3
"""Generate the bounded PREPARED-FIXED-B3 static/range gate.

The fixed operand is expanded at prepare time into four dot-product rows per
quartic output.  Each row is stored as four YMM packets matching the low/high
vpunpckwd geometry used by the existing persistent-SoA REDC16 probe.
"""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INC = ROOT / "generated/tile4_basemul_constants.inc"
OUT_JSON = ROOT / "generated/tile4_prepared_fixed_b3_gate.json"
OUT_H = ROOT / "generated/tile4_prepared_fixed_b3_lambda.h"

Q = 3457
R = 1 << 16
HALF_Q = (Q - 1) // 2
BLOCKS = 12
LANES = 16


def center(value: int) -> int:
    value %= Q
    if value > HALF_Q:
        value -= Q
    return value


def parse_lambda() -> list[int]:
    text = INC.read_text()
    match = re.search(
        r"\.Ltile4_bm_lambda:\n(?P<body>.*?)\n\.p2align 5\n"
        r"\.Ltile4_bm_lambda_qinv:",
        text,
        re.S,
    )
    if match is None:
        raise RuntimeError("cannot locate .Ltile4_bm_lambda")
    values = [int(x) for x in re.findall(r"-?\d+", match.group("body"))]
    assert len(values) == BLOCKS * LANES
    assert max(abs(x) for x in values) <= HALF_Q
    return values


def emit_header(values: list[int]) -> None:
    lines = [
        "/* Generated by tools/generate_prepared_fixed_b3_gate.py. */",
        "#ifndef GT32_TILE4_PREPARED_FIXED_B3_LAMBDA_H",
        "#define GT32_TILE4_PREPARED_FIXED_B3_LAMBDA_H",
        "#include <stdint.h>",
        "static const int16_t gt32_tile4_prepared_fixed_b3_lambda[192] = {",
    ]
    for block in range(BLOCKS):
        row = values[block * LANES : (block + 1) * LANES]
        lines.append("\t" + ", ".join(str(x) for x in row) + ",")
    lines += ["};", "#endif", ""]
    OUT_H.write_text("\n".join(lines))


def main() -> None:
    lambdas = parse_lambda()
    emit_header(lambdas)

    # Prepared coefficients and lambda-weighted coefficients are centered
    # before the optional e=1 scaling.  Scaling by R is a residue relabel and
    # therefore preserves the centered [-1728,1728] bound.
    fixed_bound = HALF_Q
    dynamic_bounds = {
        "encap_r": 10788,
        "decap_c_minus_mhat": 12699,
        "decap_ciphertext_c": Q - 1,
    }
    dot_bounds = {
        name: 4 * fixed_bound * bound
        for name, bound in dynamic_bounds.items()
    }
    assert max(dot_bounds.values()) < 2**31
    redc16_bounds = {
        name: (bound + 65535) // 65536 + (Q - 1)
        for name, bound in dot_bounds.items()
    }
    encap_post_add_bound = redc16_bounds["encap_r"] + 10788
    assert encap_post_add_bound < 32768

    # The measured existing SoA-dot symbol has 178 instructions.  Preparing
    # the fixed matrix removes four fixed-plane loads, three four-instruction
    # lambda chains, and sixteen low/high pair unpacks.
    fixed_body_estimate = 178 - 4 - 12 - 16
    fixed_symbol = 153
    controls = {
        "scale_B3_e_minus1": 127,
        "general_B3_e0": 154,
    }
    report = {
        "experiment": "PREPARED-FIXED-B3-001",
        "fixed_matrix": {
            "blocks": BLOCKS,
            "output_rows_per_block": 4,
            "ymm_packets_per_row": 4,
            "bytes_per_fixed_operand": BLOCKS * 4 * 4 * 32,
            "row_formula": [
                ["a0", "lambda*a3", "lambda*a2", "lambda*a1"],
                ["a1", "a0", "lambda*a3", "lambda*a2"],
                ["a2", "a1", "a0", "lambda*a3"],
                ["a3", "a2", "a1", "a0"],
            ],
        },
        "range": {
            "fixed_centered_bound": fixed_bound,
            "dynamic_bounds": dynamic_bounds,
            "exact_int32_dot_bounds": dot_bounds,
            "conservative_REDC16_representative_bounds": redc16_bounds,
            "encap_post_add_bound": encap_post_add_bound,
            "int32_safe": True,
            "signed_int16_safe_through_H1": True,
        },
        "scale_contracts": {
            "fixed_e0_dynamic_e0_REDC16": "output_e_minus1",
            "fixed_e1_dynamic_e0_REDC16": "output_e0",
        },
        "static_instruction_filter": {
            "existing_SoA_dot_REDC16": 178,
            "prepared_arithmetic_body_estimate": fixed_body_estimate,
            "prepared_fixed_estimate": fixed_symbol,
            "removed": {
                "fixed_plane_loads": 4,
                "runtime_lambda_chains": 12,
                "fixed_pair_unpacks": 16,
            },
            "controls": controls,
            "delta_vs_scale": fixed_symbol - controls["scale_B3_e_minus1"],
            "delta_vs_general": fixed_symbol - controls["general_B3_e0"],
        },
        "decision": {
            "fixed_f_scale_edge": "static-stop-as-primary; retain attribution control",
            "fixed_h_hinv_general_edge": "emit-bounded-assembly-probe",
            "reason": [
                "scale edge retains the old SoA dword-compaction debt and is 26 static instructions larger",
                "general edge uses e=1 prepared rows and deletes the complete runtime R2 finalizer",
                "emitted general probe is one static instruction smaller than the current general B3 symbol",
                "the noncentered REDC16 representative is repaid by the already-qualified full-int16 H1 Q24 reducer",
            ],
        },
        "reopen_fixed_f_only_if": [
            "general fixed probe demonstrates unexpectedly cheap dword compaction",
            "caller supplies packed dword pairs",
            "a reducer removes even-word compaction",
        ],
    }
    OUT_JSON.write_text(json.dumps(report, indent=2) + "\n")
    print(OUT_JSON)
    print(OUT_H)


if __name__ == "__main__":
    main()
