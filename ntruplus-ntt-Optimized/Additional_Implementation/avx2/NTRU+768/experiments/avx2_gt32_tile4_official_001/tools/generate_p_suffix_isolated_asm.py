#!/usr/bin/env python3
"""Extract the qualified P-suffix into one self-contained late-link object."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src/tile4_global_physical_asm.S"
CONSTANTS = ROOT / "generated/tile4_global_physical_constants.inc"


def between(text: str, start: str, end: str) -> str:
    begin = text.index(start)
    finish = text.index(end, begin)
    return text[begin:finish]


parser = argparse.ArgumentParser()
parser.add_argument("--pad", type=int, default=0)
parser.add_argument("--output", type=Path,
                    default=ROOT / "src/tile4_p_suffix_isolated_asm.S")
args = parser.parse_args()
if args.pad < 0 or args.pad % 32:
    raise SystemExit("--pad must be a nonnegative multiple of 32")

source = SOURCE.read_text()
body = between(
    source,
    ".globl gt32_progressive_suffix_forward_p_safe_core_asm",
    ".p2align 5\n.globl gt32_progressive_suffix_forward_m_core_asm",
).rstrip()

constants = CONSTANTS.read_text()
p_constants = between(
    constants,
    ".Lgp_forward_suffix_p_s2_qinv:",
    ".Lgp_forward_suffix_m_s2_qinv:",
).rstrip()

encoded = f"""/* Generated by generate_p_suffix_isolated_asm.py. */
.section .text.gt32_keypair_psuffix,"ax",@progbits
.p2align 6
\t.space {args.pad},0x90
{body}

.section .rodata.gt32_keypair_psuffix,"a",@progbits
.p2align 5
.Lgp_q:
\t.rept 16
\t.short 3457
\t.endr
.p2align 5
.Lgp_center10:
\t.rept 16
\t.short 10
\t.endr
.p2align 5
{p_constants}

.section .note.GNU-stack,"",@progbits
"""
args.output.write_text(encoded)
print(args.output)
