#!/usr/bin/env python3
"""Emit the bounded global-physical Forward/inverse core assembly probe."""

from __future__ import annotations

import json
from pathlib import Path

import generate_poly_abi_v2 as abi
import generate_tile4 as gt


ROOT = Path(__file__).resolve().parents[1]
GATE = gt.GENERATED / "tile4_global_physical_layout_gate.json"
PM_SUFFIX_GATE = gt.GENERATED / "tile4_n5_pm_progressive_suffix_survey.json"
CONSTANTS = gt.GENERATED / "tile4_global_physical_constants.inc"
ASM = ROOT / "src/tile4_global_physical_asm.S"


def inverse_mapping(layout: tuple[str, ...]) -> list[int]:
    old_to_new = []
    current = ("c0", "c1", "q0", "q1", "q2", "q3", "q4")
    for semantic in range(128):
        bits = {axis: (semantic >> position) & 1
                for position, axis in enumerate(current)}
        old_to_new.append(sum(bits[axis] << position
                              for position, axis in enumerate(layout)))
    result = [0] * 128
    for semantic, physical in enumerate(old_to_new):
        result[physical] = semantic
    return result


def stage_factor_records(operation: dict[str, object], inverse: bool) \
        -> list[list[int]]:
    layout = tuple(operation["layout"])
    physical_axis = int(operation["physical_axis"])
    stages = abi.current_inverse_edges() if inverse \
        else abi.current_forward_edges()
    edges = stages[int(operation["stage"]) - 1]
    exponent_by_high = {edge["high"]: edge["twiddle_exponent"]
                        for edge in edges}
    physical_to_semantic = inverse_mapping(layout)

    if physical_axis >= 4:
        vector_bit = physical_axis - 4
        pairs = [(vector, vector | (1 << vector_bit))
                 for vector in range(8)
                 if not ((vector >> vector_bit) & 1)]
        records = []
        for _, high_vector in pairs:
            record = []
            for lane in range(16):
                semantic = physical_to_semantic[16 * high_vector + lane]
                q_value = semantic >> 2
                record.append(gt.mont_root(exponent_by_high[q_value]))
            records.append(record)
        assert len(records) == 4
        return records

    assert physical_axis == 3
    records = []
    for left_vector, right_vector in ((0, 1), (2, 3), (4, 5), (6, 7)):
        record = []
        for vector in (left_vector, right_vector):
            for lane in range(8, 16):
                semantic = physical_to_semantic[16 * vector + lane]
                q_value = semantic >> 2
                record.append(gt.mont_root(exponent_by_high[q_value]))
        assert len(record) == 16
        records.append(record)
    return records


def emit_constants(paths: dict[str, dict[str, object]]) -> str:
    lines = ["/* Generated by generate_gt32_global_physical_asm.py. */"]
    for side, path in paths.items():
        inverse = side == "inverse"
        for operation in path["operations"]:
            if operation["operation"] != "NTT32-stage" \
                    or not operation["montgomery"]:
                continue
            stage = int(operation["stage"])
            records = stage_factor_records(operation, inverse)
            for suffix, transform in (("qinv", gt.factor_qinv),
                                      ("factor", lambda value: value)):
                lines.extend([
                    ".p2align 5",
                    f".Lgp_{side}_s{stage}_{suffix}:",
                ])
                for record in records:
                    lines.append("\t.short " + ",".join(
                        str(transform(value)) for value in record))
    return "\n".join(lines) + "\n"


class Emitter:
    def __init__(self, side: str, path: dict[str, object],
                 baseinv_m_safe: bool = False):
        self.side = side
        self.path = path
        self.baseinv_m_safe = baseinv_m_safe
        self.state = tuple(path["start_layout"])
        self.mapping = list(range(8))
        self.lines: list[str] = []

    @staticmethod
    def reg(number: int) -> str:
        return f"%ymm{number}"

    def free(self) -> list[int]:
        return [register for register in range(15)
                if register not in self.mapping]

    def assert_mapping(self) -> None:
        assert len(set(self.mapping)) == 8
        assert all(0 <= register < 15 for register in self.mapping)

    def rename(self, operation: dict[str, object]) -> None:
        left, right = operation["physical_bit_positions"]
        assert left >= 4 and right >= 4
        left -= 4
        right -= 4
        updated = [0] * 8
        for old_vector, register in enumerate(self.mapping):
            low = (old_vector >> left) & 1
            high = (old_vector >> right) & 1
            new_vector = old_vector
            if low != high:
                new_vector ^= (1 << left) | (1 << right)
            updated[new_vector] = register
        self.mapping = updated

    def unpack(self, operation: dict[str, object]) -> None:
        register_bit = int(operation["source_YMM_selector_bit"]) - 4
        unit = int(operation["unit_word_log2"])
        names = ("vpunpcklwd", "vpunpckldq", "vpunpcklqdq")
        high_names = ("vpunpckhwd", "vpunpckhdq", "vpunpckhqdq")
        for low_vector in range(8):
            if (low_vector >> register_bit) & 1:
                continue
            high_vector = low_vector | (1 << register_bit)
            low_register = self.mapping[low_vector]
            high_register = self.mapping[high_vector]
            temporary = self.free()[0]
            self.lines.append(
                f"\t{high_names[unit]} {self.reg(high_register)},"
                f"{self.reg(low_register)},{self.reg(temporary)}")
            self.lines.append(
                f"\t{names[unit]} {self.reg(high_register)},"
                f"{self.reg(low_register)},{self.reg(low_register)}")
            self.mapping[high_vector] = temporary
        self.assert_mapping()

    def half_select(self, operation: dict[str, object]) -> None:
        register_bit = int(operation["physical_bit_positions"][1]) - 4
        for low_vector in range(8):
            if (low_vector >> register_bit) & 1:
                continue
            high_vector = low_vector | (1 << register_bit)
            low_register = self.mapping[low_vector]
            high_register = self.mapping[high_vector]
            temporary = self.free()[0]
            self.lines.append(
                f"\tvperm2i128 $0x31,{self.reg(high_register)},"
                f"{self.reg(low_register)},{self.reg(temporary)}")
            self.lines.append(
                f"\tvperm2i128 $0x20,{self.reg(high_register)},"
                f"{self.reg(low_register)},{self.reg(low_register)}")
            self.mapping[high_vector] = temporary
        self.assert_mapping()

    def transition(self, operation: dict[str, object]) -> None:
        assert tuple(operation["before"]) == self.state
        family = operation["instruction_family"]
        self.lines.append(f"\t/* {family}: {self.state} -> "
                          f"{tuple(operation['after'])} */")
        if family == "YMM-register-rename":
            self.rename(operation)
        elif family.startswith("vpunpck"):
            self.unpack(operation)
        elif family.startswith("vperm2i128"):
            self.half_select(operation)
        else:
            raise AssertionError(f"unemitted selected transition: {family}")
        self.state = tuple(operation["after"])

    def cross(self, operation: dict[str, object]) -> None:
        physical_axis = int(operation["physical_axis"])
        assert physical_axis >= 4
        vector_bit = physical_axis - 4
        pairs = [(vector, vector | (1 << vector_bit))
                 for vector in range(8)
                 if not ((vector >> vector_bit) & 1)]
        temporaries = self.free()[:4]
        assert len(temporaries) == 4
        stage = int(operation["stage"])
        if operation["montgomery"]:
            for index, ((_, high), temporary) in enumerate(
                    zip(pairs, temporaries)):
                self.lines.append(
                    f"\tvpmullw .Lgp_{self.side}_s{stage}_qinv+{32*index}(%rip),"
                    f"{self.reg(self.mapping[high])},{self.reg(temporary)}")
            for index, (_, high) in enumerate(pairs):
                register = self.mapping[high]
                self.lines.append(
                    f"\tvpmulhw .Lgp_{self.side}_s{stage}_factor+{32*index}(%rip),"
                    f"{self.reg(register)},{self.reg(register)}")
            for temporary in temporaries:
                self.lines.append(
                    f"\tvpmulhw %ymm15,{self.reg(temporary)},"
                    f"{self.reg(temporary)}")
            for (_, high), temporary in zip(pairs, temporaries):
                high_register = self.mapping[high]
                self.lines.append(
                    f"\tvpsubw {self.reg(temporary)},{self.reg(high_register)},"
                    f"{self.reg(high_register)}")
        for (low, high), temporary in zip(pairs, temporaries):
            low_register = self.mapping[low]
            high_register = self.mapping[high]
            self.lines.append(
                f"\tvpsubw {self.reg(high_register)},{self.reg(low_register)},"
                f"{self.reg(temporary)}")
        for low, high in pairs:
            low_register = self.mapping[low]
            high_register = self.mapping[high]
            self.lines.append(
                f"\tvpaddw {self.reg(high_register)},{self.reg(low_register)},"
                f"{self.reg(low_register)}")
        for (_, high), temporary in zip(pairs, temporaries):
            self.mapping[high] = temporary
        self.assert_mapping()

    def local_half(self, operation: dict[str, object]) -> None:
        stage = int(operation["stage"])
        assert int(operation["physical_axis"]) == 3
        for index, (left, right) in enumerate(
                ((0, 1), (2, 3), (4, 5), (6, 7))):
            left_register = self.mapping[left]
            right_register = self.mapping[right]
            low, high, temporary = self.free()[:3]
            offset = 32 * index
            self.lines.extend([
                f"\tvperm2i128 $0x20,{self.reg(right_register)},"
                f"{self.reg(left_register)},{self.reg(low)}",
                f"\tvperm2i128 $0x31,{self.reg(right_register)},"
                f"{self.reg(left_register)},{self.reg(high)}",
                f"\tvpmullw .Lgp_{self.side}_s{stage}_qinv+{offset}(%rip),"
                f"{self.reg(high)},{self.reg(temporary)}",
                f"\tvpmulhw .Lgp_{self.side}_s{stage}_factor+{offset}(%rip),"
                f"{self.reg(high)},{self.reg(high)}",
                f"\tvpmulhw %ymm15,{self.reg(temporary)},{self.reg(temporary)}",
                f"\tvpsubw {self.reg(temporary)},{self.reg(high)},{self.reg(high)}",
                f"\tvpsubw {self.reg(high)},{self.reg(low)},{self.reg(temporary)}",
                f"\tvpaddw {self.reg(high)},{self.reg(low)},{self.reg(low)}",
                f"\tvperm2i128 $0x20,{self.reg(temporary)},{self.reg(low)},"
                f"{self.reg(left_register)}",
                f"\tvperm2i128 $0x31,{self.reg(temporary)},{self.reg(low)},"
                f"{self.reg(right_register)}",
            ])

    def stage(self, operation: dict[str, object]) -> None:
        assert tuple(operation["layout"]) == self.state
        self.lines.append(
            f"\t/* {self.side} S{operation['stage']}: "
            f"{operation['logical_axis']} at physical bit "
            f"{operation['physical_axis']} */")
        if operation["shape"] == "cross-YMM-butterfly":
            self.cross(operation)
        elif operation["instruction_family"] == \
                "vperm2i128-half-local-pair":
            self.local_half(operation)
        else:
            raise AssertionError(operation)

    def emit(self) -> list[str]:
        for operation in self.path["operations"]:
            if operation["operation"] == "layout-transition":
                self.transition(operation)
            else:
                self.stage(operation)
                if self.baseinv_m_safe and self.side.startswith("forward") \
                        and int(operation["stage"]) == 1:
                    # Exact value-set proof: physical post-S1 vectors 0 and
                    # 4 are logical Q={0,1,2,3} and Q={16,17,18,19}.  Center
                    # those complete vectors before any layout transition.
                    value0 = self.mapping[0]
                    value4 = self.mapping[4]
                    temporary0, temporary4 = self.free()[:2]
                    self.lines.extend([
                        "\t/* M/BaseInv selective-center: vectors 0 and 4 */",
                        f"\tvpmulhrsw .Lgp_center10(%rip),"
                        f"{self.reg(value0)},{self.reg(temporary0)}",
                        f"\tvpmulhrsw .Lgp_center10(%rip),"
                        f"{self.reg(value4)},{self.reg(temporary4)}",
                        f"\tvpmullw %ymm15,{self.reg(temporary0)},"
                        f"{self.reg(temporary0)}",
                        f"\tvpmullw %ymm15,{self.reg(temporary4)},"
                        f"{self.reg(temporary4)}",
                        f"\tvpsubw {self.reg(temporary0)},{self.reg(value0)},"
                        f"{self.reg(value0)}",
                        f"\tvpsubw {self.reg(temporary4)},{self.reg(value4)},"
                        f"{self.reg(value4)}",
                    ])
        assert self.state == tuple(self.path["finish_layout"])
        return self.lines


def emit_function(name: str, side: str, path: dict[str, object],
                  baseinv_m_safe: bool = False) -> list[str]:
    emitter = Emitter(side, path, baseinv_m_safe)
    body = emitter.emit()
    lines = [
        ".p2align 5",
        f".globl {name}",
        f".type {name},@function",
        f"{name}:",
        "\tvmovdqa .Lgp_q(%rip),%ymm15",
        "\tmovl $6,%ecx",
        ".p2align 5",
        f".L{name}_loop:",
    ]
    for vector in range(8):
        lines.append(f"\tvmovdqu {32*vector}(%rsi),%ymm{vector}")
    lines.extend(body)
    for vector, register in enumerate(emitter.mapping):
        lines.append(f"\tvmovdqu %ymm{register},{32*vector}(%rdi)")
    lines.extend([
        "\taddq $256,%rsi",
        "\taddq $256,%rdi",
        "\tdecl %ecx",
        f"\tjne .L{name}_loop",
        "\tvzeroupper",
        "\tret",
        f".size {name},.-{name}",
    ])
    return lines


def main() -> None:
    gate = json.loads(GATE.read_text())
    assert gate["decision"] == "emit-bounded-assembly-probe"
    candidate = gate["candidates_by_cost_profile"]["balanced"]
    suffix_gate = json.loads(PM_SUFFIX_GATE.read_text())
    assert suffix_gate["decision"] == "emit-bounded-P-M-suffix-probe"
    suffix_cut = next(
        item for item in suffix_gate["profiles"]["balanced"]["cuts"]
        if item["common_through_stage"] == 4)
    paths = {"forward": candidate["forward"],
             "forward_suffix_p": suffix_cut["P_path"],
             "forward_suffix_m": suffix_cut["M_path"],
             "inverse": candidate["inverse"]}
    CONSTANTS.write_text(emit_constants(paths))

    lines = [
        "/* Generated bounded probe; do not hand-edit. */",
        ".text",
        *emit_function("gt32_global_forward_core_asm", "forward",
                       paths["forward"]),
        "",
        *emit_function("gt32_global_forward_baseinv_m_safe_core_asm",
                       "forward", paths["forward"],
                       baseinv_m_safe=True),
        "",
        *emit_function("gt32_progressive_suffix_forward_p_safe_core_asm",
                       "forward_suffix_p", paths["forward_suffix_p"],
                       baseinv_m_safe=True),
        "",
        *emit_function("gt32_progressive_suffix_forward_m_core_asm",
                       "forward_suffix_m", paths["forward_suffix_m"]),
        "",
        *emit_function("gt32_global_inverse_core_asm", "inverse",
                       paths["inverse"]),
        "",
        ".section .rodata",
        ".p2align 5",
        ".Lgp_q:",
        "\t.rept 16",
        "\t.short 3457",
        "\t.endr",
        ".p2align 5",
        ".Lgp_center10:",
        "\t.rept 16",
        "\t.short 10",
        "\t.endr",
        '#include "../generated/tile4_global_physical_constants.inc"',
    ]
    ASM.write_text("\n".join(lines) + "\n")
    print(CONSTANTS)
    print(ASM)


if __name__ == "__main__":
    main()
