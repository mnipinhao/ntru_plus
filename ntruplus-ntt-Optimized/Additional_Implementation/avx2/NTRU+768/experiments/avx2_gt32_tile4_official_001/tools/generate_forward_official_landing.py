#!/usr/bin/env python3
"""Generate the bounded N5 Stage-5 -> Official BM layout landing.

The frozen N5 arithmetic leaves eight packed vectors live per tile.  This
generator symbolically inverts the qualified packed-to-private-SoA network,
then synthesizes Official NTT-output vectors directly from those packed
registers.  It never materializes the private-SoA intermediate.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "generated"


def load_generator():
    path = ROOT / "tools" / "generate_tile4.py"
    spec = importlib.util.spec_from_file_location("tile4_generator", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


G = load_generator()


def unpack(a: list[object], b: list[object], words: int,
           high: bool) -> list[object]:
    result: list[object] = []
    units_per_half = 8 // words
    selected = range(units_per_half // 2, units_per_half) if high \
        else range(units_per_half // 2)
    for half in range(2):
        base = 8 * half
        for unit in selected:
            start = base + words * unit
            result.extend(a[start:start + words])
            result.extend(b[start:start + words])
    assert len(result) == 16
    return result


def packed_symbolic_network() -> list[list[tuple[int, int]]]:
    source = [[(vector, lane) for lane in range(16)] for vector in range(4)]
    order = (0, 4, 1, 5, 2, 6, 3, 7)
    shuffled = [[value[8 * half + lane]
                 for half in range(2) for lane in order]
                for value in source]
    t8 = unpack(shuffled[0], shuffled[2], 2, False)
    t9 = unpack(shuffled[0], shuffled[2], 2, True)
    t10 = unpack(shuffled[1], shuffled[3], 2, False)
    t11 = unpack(shuffled[1], shuffled[3], 2, True)
    return [unpack(t8, t10, 4, False),
            unpack(t8, t10, 4, True),
            unpack(t9, t11, 4, False),
            unpack(t9, t11, 4, True)]


def infer_packed_sources(private_targets: list[list[int]]) -> list[list[int]]:
    symbolic = packed_symbolic_network()
    locations: dict[tuple[int, int], int] = {}
    for output_vector, output in enumerate(symbolic):
        for lane, source_location in enumerate(output):
            locations[source_location] = private_targets[output_vector][lane]
    assert len(locations) == 64
    return [[locations[(vector, lane)] for lane in range(16)]
            for vector in range(4)]


def pair_routes(sources: list[list[int]], target: list[int]):
    location = {value: (vector, lane) for vector, source in enumerate(sources)
                for lane, value in enumerate(source)}
    descriptor = G.half_route_descriptor(location, target)
    pairs = []
    for encoded_low, encoded_high in descriptor["signature"]:
        low = None if encoded_low == (-1, -1) else encoded_low
        high = None if encoded_high == (-1, -1) else encoded_high
        pairs.append((low, high))
    return pairs


def carrier_mask(sources: list[list[int]], target: list[int], low, high):
    carrier: list[int | None] = []
    for source in (low, high):
        if source is None:
            carrier.extend([None] * 8)
        else:
            vector, half = source
            carrier.extend(sources[vector][8 * half:8 * half + 8])
    mask = []
    for lane, wanted in enumerate(target):
        half_base = 8 * (lane // 8)
        candidates = carrier[half_base:half_base + 8]
        if wanted not in candidates:
            mask.extend((0x80, 0x80))
        else:
            source_lane = candidates.index(wanted)
            mask.extend((2 * source_lane, 2 * source_lane + 1))
    assert len(mask) == 32
    return mask


def emit() -> None:
    _, _, records = G.serialized_mappings()
    standard = G.semantic_decoder_targets(records)["soa"]
    by_official = {record["official_word"]: record for record in records}
    official = [[by_official[16 * vector + lane]["tile4_aos_word"]
                 for lane in range(16)] for vector in range(48)]

    tile_targets: dict[int, list[tuple[int, list[int]]]] = {}
    for vector, target in enumerate(official):
        tiles = {value // 128 for value in target}
        assert len(tiles) == 1
        tile_targets.setdefault(tiles.pop(), []).append((vector, target))
    assert all(len(values) == 8 for values in tile_targets.values())

    tile_routes = {}
    total_permutes = 0
    total_masks = 0
    total_ors = 0
    total_stores = 0
    masks: list[list[int]] = []
    assembly: list[str] = [
        "/* Generated by tools/generate_forward_official_landing.py. */",
        "\t.macro FR_PACKED8_TO_OFFICIAL tile",
    ]
    for tile in range(6):
        private_low = standard[8 * tile:8 * tile + 4]
        private_high = standard[8 * tile + 4:8 * tile + 8]
        sources = infer_packed_sources(private_low) + infer_packed_sources(private_high)
        entries = []
        assembly.append(f"\t.if \\tile == {tile}")
        for ordinal, (destination_vector, target) in enumerate(tile_targets[tile]):
            routes = pair_routes(sources, target)
            route_records = []
            for route_index, (low, high) in enumerate(routes):
                mask = carrier_mask(sources, target, low, high)
                mask_id = len(masks)
                masks.append(mask)
                natural = (low is not None and high is not None
                           and low[0] == high[0]
                           and low[1] == 0 and high[1] == 1)
                carrier_reg = None
                immediate = None
                if natural:
                    carrier_reg = low[0]
                else:
                    # The descriptor pads only when one destination half has
                    # fewer sources.  Reuse the real source for the don't-care
                    # half; VPSHUFB zeros it with the generated mask.
                    actual_low = low if low is not None else high
                    actual_high = high if high is not None else low
                    assert actual_low is not None and actual_high is not None
                    low_reg, low_half = actual_low
                    high_reg, high_half = actual_high
                    immediate = low_half | ((2 + high_half) << 4)
                    assembly.append(
                        f"\tvperm2i128 $0x{immediate:02x}, %ymm{high_reg}, "
                        f"%ymm{low_reg}, %ymm8")
                    carrier_reg = 8
                    total_permutes += 1
                output_reg = 9 if route_index == 0 else 10
                assembly.append(
                    f"\tvpshufb .Lfr_official_mask_{mask_id}(%rip), "
                    f"%ymm{carrier_reg}, %ymm{output_reg}")
                total_masks += 1
                if route_index:
                    assembly.append("\tvpor %ymm10, %ymm9, %ymm9")
                    total_ors += 1
                route_records.append({
                    "low_source": None if low is None else list(low),
                    "high_source": None if high is None else list(high),
                    "natural_carrier": natural,
                    "vperm2i128_immediate": immediate,
                    "mask_id": mask_id,
                })
            assembly.append(
                f"\tvmovdqu %ymm9, {32 * destination_vector}(%rdi)")
            total_stores += 1
            entries.append({
                "destination_vector": destination_vector,
                "route_count": len(routes),
                "routes": route_records,
            })
        assembly.append("\t.endif")
        tile_routes[str(tile)] = entries
    assembly.extend(["\t.endm", ""])
    for mask_id, mask in enumerate(masks):
        assembly.append(f".Lfr_official_mask_{mask_id}:")
        assembly.append("\t.byte " + ",".join(str(value) for value in mask))
    assembly.append("")

    assert total_stores == 48
    total_route_instructions = total_permutes + total_masks + total_ors
    selected_private_shuffles = 144
    extra_route_instructions = total_route_instructions - selected_private_shuffles
    assembly_eligible = extra_route_instructions <= 48
    result = {
        "schema": "ntruplus768-gt32-forward-official-landing-v1",
        "experiment": "GT32-POLYMUL-FWD-OFFICIAL-LANDING-001",
        "scope": "N5-stage5-packed-to-Official-NTT-output-layout",
        "correctness_model": {
            "semantic_words": 768,
            "bijection": sorted(value for target in official for value in target)
                         == list(range(768)),
            "private_intermediate_materialized": False,
        },
        "static_cost": {
            "direct_vperm2i128": total_permutes,
            "direct_vpshufb": total_masks,
            "direct_vpor": total_ors,
            "direct_stores": 48,
            "direct_route_instruction_total": total_route_instructions,
            "selected_private_terminal_shuffle_total": selected_private_shuffles,
            "extra_route_instructions_vs_private_terminal": extra_route_instructions,
            "max_routes_per_target": max(
                entry["route_count"] for entries in tile_routes.values()
                for entry in entries),
            "note": "Each Official vector mixes five or six packed source-half routes",
        },
        "gate": {
            "max_extra_core_cycles_per_forward": 15.0,
            "max_extra_static_instructions_per_forward": 48,
            "assembly_eligible": assembly_eligible,
            "decision": "emit-bounded-asm" if assembly_eligible
                        else "static-hard-stop-before-asm",
            "reason": ("route fits bounded landing budget" if assembly_eligible
                       else "five/six-route targets require a large OR/permute network"),
        },
        "tile_routes": tile_routes,
    }
    include = GEN / "tile4_forward_official_landing.inc"
    if assembly_eligible:
        include.write_text("\n".join(assembly))
    elif include.exists():
        include.unlink()
    (GEN / "tile4_forward_official_landing_gate.json").write_text(
        json.dumps(result, indent=2) + "\n")
    print(json.dumps(result["static_cost"], indent=2))


if __name__ == "__main__":
    emit()
