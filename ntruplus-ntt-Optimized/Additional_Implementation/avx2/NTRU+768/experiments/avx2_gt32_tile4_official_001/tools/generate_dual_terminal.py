#!/usr/bin/env python3
"""Generate the T9 dual-consumer terminal constants and mechanical proof."""

import argparse
import hashlib
import json
import re
from pathlib import Path


SOURCE_LABELS = (
    "frontend_wide_twist_qinv",
    "frontend_wide_twist_factor",
    "frontend_omega3_qinv",
    "frontend_omega3_factor",
    "frontend_zeta_top_raw",
)


def extract_shorts(source: str, label: str) -> list[int]:
    marker = f".Ltile4_{label}:"
    start = source.index(marker) + len(marker)
    tail = source[start:]
    matches = [position for position in (
        tail.find("\n.p2align"), tail.find("\n.Ltile4_")) if position >= 0]
    block = tail[:min(matches)] if matches else tail
    values: list[int] = []
    repeat = None
    for raw_line in block.splitlines():
        line = raw_line.strip()
        if line.startswith(".rept"):
            repeat = int(line.split()[1])
        elif line.startswith(".short"):
            row = [int(value) for value in
                   re.findall(r"-?\d+", line[len(".short"):])]
            values.extend(row * (repeat or 1))
            repeat = None
        elif line.startswith(".endr"):
            continue
    return values


def emit_constants(blocks: dict[str, list[int]]) -> str:
    lines = ["/* Generated by tools/generate_dual_terminal.py. */"]
    for name, values in blocks.items():
        lines.extend((".p2align 5", f".Ldual_{name}:"))
        for offset in range(0, len(values), 16):
            row = ",".join(str(value) for value in values[offset:offset + 16])
            lines.append(f"\t.short {row}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--constants-source", type=Path,
                        default=Path("generated/tile4_constants.inc"))
    parser.add_argument("--range-source", type=Path,
                        default=Path("generated/tile4_inverse_tail_range.json"))
    parser.add_argument("--asm-output", type=Path,
                        default=Path("generated/tile4_dual_terminal_constants.inc"))
    parser.add_argument("--proof-output", type=Path,
                        default=Path("generated/tile4_dual_terminal_gate.json"))
    args = parser.parse_args()

    source_bytes = args.constants_source.read_bytes()
    source = source_bytes.decode()
    blocks = {name: extract_shorts(source, name) for name in SOURCE_LABELS}
    expected_lengths = {
        "frontend_wide_twist_qinv": 8 * 6 * 16,
        "frontend_wide_twist_factor": 8 * 6 * 16,
        "frontend_omega3_qinv": 16,
        "frontend_omega3_factor": 16,
        "frontend_zeta_top_raw": 16,
    }
    for name, expected in expected_lengths.items():
        if len(blocks[name]) != expected:
            raise AssertionError(
                f"{name}: got {len(blocks[name])}, expected {expected}")

    ranges = json.loads(args.range_source.read_text())
    three_mont = ranges["three_mont_matrix"]
    if three_mont["relaxed_output_abs_bound"] > 2179:
        raise AssertionError("production T9 centered representative bound changed")

    coefficient_records = []
    n5_records = []
    for group in range(8):
        n5_records.append({
            "group": group,
            "t9_vectors": [
                "a0", "b0", "c0", "a1", "b1", "c1"],
            "coefficient_byte_offsets": [
                32 * group,
                256 + 32 * group,
                512 + 32 * group,
                768 + 32 * group,
                1024 + 32 * group,
                1280 + 32 * group,
            ],
            "n5_frontend_iteration": group,
            "n5_input_loads_eliminated": 6,
        })
        for segment in range(6):
            for lane in range(16):
                coefficient = 128 * segment + 16 * group + lane
                coefficient_records.append({
                    "coefficient": coefficient,
                    "t9_segment": segment,
                    "t9_group": group,
                    "t9_lane": lane,
                    "sidecar_byte": 16 * segment + 2 * group + lane // 8,
                    "sidecar_bit": lane % 8,
                })

    if sorted(record["coefficient"] for record in coefficient_records) \
            != list(range(768)):
        raise AssertionError("dual-terminal coefficient mapping is not bijective")
    if sorted((record["sidecar_byte"], record["sidecar_bit"])
              for record in coefficient_records) \
            != [(byte, bit) for byte in range(96) for bit in range(8)]:
        raise AssertionError("sidecar bit mapping is not bijective")

    asm = emit_constants(blocks)
    args.asm_output.parent.mkdir(parents=True, exist_ok=True)
    args.asm_output.write_text(asm)

    proof = {
        "schema": "ntruplus768-gt32-dual-terminal-v1",
        "experiment": "GT32-C2-DUAL-CONSUMER-TERMINAL-001",
        "contract": {
            "input": "I1 TILE4 AoS, r_exponent=-1",
            "outputs": [
                "N5 wide-frontend output, e=0",
                "canonical SOTP neg[96] and nz[96] bitplanes",
            ],
            "forbidden_output": "coefficient-order ternary m[768]",
            "alias": "all three regions disjoint",
        },
        "proof": {
            "coefficient_mapping_bijective": True,
            "sidecar_mapping_bijective": True,
            "t9_group_is_n5_frontend_iteration": True,
            "t9_raw_abs_bound": three_mont["precenter_output_abs_bound"],
            "t9_centered_abs_bound": three_mont["relaxed_output_abs_bound"],
            "representative_policy":
                "production T9 CENTER is retained in registers before crepmod3",
            "direct_raw_crepmod3_rejected_by_differential": True,
            "output_scale_exponent": 0,
        },
        "assembly_plan": {
            "groups": 8,
            "input_vectors_per_group": 6,
            "n5_frontend_input_loads_removed": 48,
            "persistent_full_m_vector_stores_removed": 48,
            "sidecar_bytes": 192,
            "peak_ymm": 16,
            "spill_required": False,
            "secret_dependent_control_or_address": False,
            "variants": {
                "direct": {
                    "rotating_scratch_bytes": 0,
                    "temporary_vector_stores": 0,
                    "temporary_vector_loads": 0,
                },
                "B2": {
                    "rotating_scratch_bytes": 384,
                    "temporary_vector_stores": 48,
                    "temporary_vector_loads": 48,
                },
                "B4": {
                    "rotating_scratch_bytes": 768,
                    "temporary_vector_stores": 48,
                    "temporary_vector_loads": 48,
                },
            },
        },
        "n5_routes": n5_records,
        "sidecar_routes": coefficient_records,
        "sources": {
            "tile4_constants_sha256": hashlib.sha256(source_bytes).hexdigest(),
            "inverse_tail_range_sha256": hashlib.sha256(
                args.range_source.read_bytes()).hexdigest(),
        },
        "decision": "assembly-eligible-benchmark-only",
    }
    args.proof_output.parent.mkdir(parents=True, exist_ok=True)
    args.proof_output.write_text(json.dumps(proof, indent=2) + "\n")
    print(json.dumps({
        "decision": proof["decision"],
        "n5_loads_removed": 48,
        "persistent_full_m_stores_removed": 48,
        "sidecar_bytes": 192,
    }, indent=2))


if __name__ == "__main__":
    main()
