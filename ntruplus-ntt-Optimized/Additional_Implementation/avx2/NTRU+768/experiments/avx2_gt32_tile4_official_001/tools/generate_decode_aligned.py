#!/usr/bin/env python3
"""Faithful AT&T lowering of the frozen aligned-packet instruction schedule."""
import argparse
import json
from pathlib import Path
from research_decode_wide import EXP,make,allocate
from generate_tile4 import serialized_mappings

def build():
    frozen=json.loads((EXP/'generated/decode_wide_schedule.json').read_text())['aligned_packet']
    p=make('aligned_packet');peak,allocation=allocate(p)
    assert p.ops==frozen['schedule'] and allocation==frozen['allocation'] and p.masks==frozen['masks']
    prefix='ntruplus768_exp_aligned_decode'
    out=['# Generated by generate_decode_aligned.py; experiment only.']
    def start(name):
        out.extend([f'.section .text.{name},"ax",@progbits','.p2align 5',f'.globl {name}',f'.type {name},@function',name+':'])
    def end(name):out.append(f'.size {name},.-{name}')
    start(prefix+'_body')
    instructions=[]
    for a,r in zip(p.ops,allocation):
        op=a['op'];s=[f'%ymm{x}' for x in r['src_YMM']];d=f'%ymm{r["dst_YMM"]}'
        if 'block_begin' in a:out.append(f'# wire block {a["block_begin"]}')
        if op=='constant':line=f'vmovdqa .Laligned_low12(%rip), {d}'
        elif op=='zero':line=f'vpxor {d}, {d}, {d}'
        elif op=='load':line=f'vmovdqu {a["offset"]}(%rsi), {d}'
        elif op=='store':line=f'vmovdqu {s[0]}, {a["offset"]}(%rdi)'
        elif op=='vperm2i128':line=f'{op} ${a["imm"]}, {s[1]}, {s[0]}, {d}'
        elif op=='vpalignr':line=f'{op} ${a["imm"]}, {s[0]}, {s[1]}, {d}'
        elif op=='vpshufb':line=f'{op} .Laligned_mask{a["mask"]}(%rip), {s[0]}, {d}'
        elif op=='vpsrlw':line=f'{op} ${a["imm"]}, {s[0]}, {d}'
        elif op=='vpblendw':line=f'{op} ${a["imm"]}, {s[1]}, {s[0]}, {d}'
        elif op=='vpcmpgtw':line=f'{op} .Laligned_qm1(%rip), {s[0]}, {d}'
        elif op=='vpmovmskb':line=f'{op} {s[0]}, %edx'
        elif op in ('vpand','vpmaxuw') or op.startswith('vpunpck'):line=f'{op} {s[1]}, {s[0]}, {d}'
        else:raise AssertionError(op)
        out.append(line);instructions.append(line)
    out+=['orl %edx, %eax','ret'];end(prefix+'_body')
    start(prefix)
    out+=['xorl %eax, %eax','subq $8, %rsp',f'call {prefix}_body','addq $8, %rsp',
          'testl %eax, %eax','setne %al','movzbl %al, %eax','vzeroupper','ret'];end(prefix)
    start(prefix+'3')
    out+=['movq %rsi, %r9','movq %rdx, %r10','movq %r8, %r11','xorl %eax, %eax',
          'subq $8, %rsp','movq %rcx, %rsi',f'call {prefix}_body',
          'movq %r9, %rdi','movq %r11, %rsi',f'call {prefix}_body',
          'movq %r10, %rdi','leaq 1152(%r11), %rsi',f'call {prefix}_body',
          'addq $8, %rsp','testl %eax, %eax','setne %al','movzbl %al, %eax','vzeroupper','ret'];end(prefix+'3')
    out+=['.section .rodata.aligned_decode,"a",@progbits','.p2align 5','.Laligned_low12:','.short '+','.join(['4095']*16),
          '.p2align 5','.Laligned_qm1:','.short '+','.join(['3456']*16)]
    for i,mask in enumerate(p.masks):out+=['.p2align 5',f'.Laligned_mask{i}:','.byte '+','.join(map(str,mask))]
    out+=['.section .note.GNU-stack,"",@progbits']
    return '\n'.join(out)+'\n',dict(body_instructions=instructions,peak_YMM=peak,
        wrapper_stack_bytes=8,vector_spills=0,body_calls=0,
        triple_low12_initializations=3,control_triple_low12_initializations=1)

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    source,audit=build()
    mapping='static const unsigned wire_to_m[768]={'+','.join(map(str,serialized_mappings()[1]))+'};\n'
    for name,value in [('decode_aligned.S',source),('decode_aligned_mapping.h',mapping),('decode_aligned_lowering.json',json.dumps(audit,indent=2)+'\n')]:
        path=EXP/'generated'/name
        if a.check:assert path.read_text()==value
        else:path.write_text(value)
    print('aligned decoder lowering: PASS')
