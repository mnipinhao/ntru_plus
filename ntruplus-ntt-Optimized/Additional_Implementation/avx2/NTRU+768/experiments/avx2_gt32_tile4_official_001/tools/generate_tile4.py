def center10(value: int) -> int:
    # AVX2 vpmulhrsw(value,10), followed by value - quotient*q.
    quotient = (value * 10 + (1 << 14)) >> 15
    return value - quotient * Q


def center_canonical10(value: int) -> int:
    value = center10(value)
    if value > Q // 2:
        value -= Q
    if value < -(Q // 2):
        value += Q
    return value


