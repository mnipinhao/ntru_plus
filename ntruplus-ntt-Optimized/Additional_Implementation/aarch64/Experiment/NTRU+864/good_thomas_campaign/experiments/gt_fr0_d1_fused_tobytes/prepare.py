#!/usr/bin/env python3
"""Generate the exact P3B5 route tables from the root-derived ABI map."""

from __future__ import annotations

import importlib.util
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = Path(subprocess.check_output(
    ["git", "rev-parse", "--show-toplevel"], text=True).strip())
MAP_SOURCE = HERE.parent / "gt_forward_full_poly_ntt_asm/generate_official_map.py"

spec = importlib.util.spec_from_file_location("gt864_map", MAP_SOURCE)
assert spec is not None and spec.loader is not None
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
mapping, proof = module.build(ROOT)

store_order = [0, 3, 6, 1, 4, 7, 2, 5, 8]


def bytes_for_lanes(lanes: list[int]) -> list[int]:
    return [2 * lane + byte for lane in lanes for byte in (0, 1)]


a_fwd: list[list[int]] = []
for k, official_group in enumerate(store_order):
    source_by_output_lane = [
        mapping[24 * (2 * official_group) + lane] // 24
        for lane in range(8)
    ]
    # W_k positions contain source J0..J7, except J8 occupies position k.
    source_by_w_position = [0 if position == k else 8 - position
                            for position in range(8)]
    a_fwd.append(bytes_for_lanes([
        source_by_w_position.index(source)
        for source in source_by_output_lane
    ]))

prefix = [[65535 if lane < count else 0 for lane in range(8)]
          for count in range(1, 8)]

lines = [
    "/* Generated by prepare.py; do not edit. */",
    f"/* map_sha256={proof['mapping_sha256']} */",
    "#ifndef P3B5_TABLES_H",
    "#define P3B5_TABLES_H",
    "#include <stdint.h>",
    "static const uint16_t p3b5_map[864] __attribute__((aligned(16))) = {",
]
for start in range(0, 864, 12):
    lines.append("    " + ", ".join(map(str, mapping[start:start + 12])) + ",")
lines.append("};")
lines.append("static const uint8_t p3b5_a_fwd[9][16] __attribute__((aligned(16))) = {")
for row in a_fwd:
    lines.append("    {" + ", ".join(map(str, row)) + "},")
lines.append("};")
lines.append("static const uint16_t p3b5_prefix[7][8] __attribute__((aligned(16))) = {")
for row in prefix:
    lines.append("    {" + ", ".join(map(str, row)) + "},")
lines.extend(["};", "#endif", ""])

build = HERE / "build"
build.mkdir(exist_ok=True)
(build / "p3b5_tables.h").write_text("\n".join(lines), encoding="utf-8")
print(proof["mapping_sha256"])
