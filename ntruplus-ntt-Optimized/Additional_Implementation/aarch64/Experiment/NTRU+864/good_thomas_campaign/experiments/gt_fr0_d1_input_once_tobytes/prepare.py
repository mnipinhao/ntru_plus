#!/usr/bin/env python3
"""Generate the exact peak-16 input-once P3B6 ToBytes implementation."""

from __future__ import annotations

import hashlib
import importlib.util
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = Path(subprocess.check_output(
    ["git", "rev-parse", "--show-toplevel"], text=True).strip())
P3A = HERE.parent / "gt_fr0_d1_byte_abi_architecture/analyze_architecture.py"
spec = importlib.util.spec_from_file_location("p3a", P3A)
assert spec is not None and spec.loader is not None
p3a = importlib.util.module_from_spec(spec)
spec.loader.exec_module(p3a)

mapping, _ = p3a.official_map(ROOT)
shuffle2 = [value for start in range(0, 864, 48)
            for value in p3a.shuffle2_block(start)]
forward = [mapping[shuffle2[index]] for index in range(864)]
digest = hashlib.sha256(b"".join(
    value.to_bytes(2, "little") for value in forward)).hexdigest()
assert digest == "087b7193886e9f3e33ac457452642d64ae70ec780a0961d10036c8e5530da270"
assert all(forward[index + 432] == forward[index] + 432
           for index in range(432))

# Each top has 54 input and 54 output q-vectors.  Select the same greedy
# minimum-upper-bound witness used by P3B3, trying every first input.
neighborhoods = [
    {forward[8 * output_q + lane] // 8 for lane in range(8)}
    for output_q in range(54)
]
best: tuple[int, list[int]] | None = None
for first in range(54):
    loaded = {first}
    order = [first]
    active = {q for q, neighborhood in enumerate(neighborhoods)
              if neighborhood & loaded and not neighborhood <= loaded}
    peak = len(active)
    while len(loaded) < 54:
        choices = []
        for next_input in set(range(54)) - loaded:
            following = loaded | {next_input}
            after = {q for q, neighborhood in enumerate(neighborhoods)
                     if neighborhood & following and
                     not neighborhood <= following}
            touched = {q for q, neighborhood in enumerate(neighborhoods)
                       if next_input in neighborhood}
            choices.append((len(after), len(active | touched), next_input,
                            after))
        _, during, next_input, after = min(choices, key=lambda item: item[:3])
        peak = max(peak, during)
        loaded.add(next_input)
        order.append(next_input)
        active = after
    candidate = (peak, order)
    if best is None or candidate[0] < best[0]:
        best = candidate
assert best is not None and best[0] == 16
peak, input_order = best

header = [
    "/* Generated by prepare.py; do not edit. */",
    f"/* composed_map_sha256={digest} */",
    "#ifndef P3B6_TABLES_H",
    "#define P3B6_TABLES_H",
    "#include <stdint.h>",
    "static const uint16_t p3b6_map[864] = {",
]
for start in range(0, 864, 12):
    header.append("    " + ", ".join(map(str, forward[start:start + 12])) + ",")
header.extend(["};", "#endif", ""])

source = [
    "/* Generated by prepare.py; do not edit. */",
    "#include \"input_once_tobytes.h\"",
    "#include <arm_neon.h>",
    "#include <string.h>",
    "static const uint8_t pack_index[16] __attribute__((aligned(16))) =",
    " {0,1,16,2,3,18,4,5,20,6,7,22,255,255,255,255};",
    "static inline int16x8_t normq(int16x8_t x) {",
    " const int16x8_t q=vdupq_n_s16(3457), r=vdupq_n_s16(9);",
    " int16x8_t t=vqrdmulhq_s16(x,r); x=vmlsq_s16(x,t,q);",
    " return vaddq_s16(x,vandq_s16(vshrq_n_s16(x,15),q));",
    "}",
    "static inline void pack8(uint8_t *out,int16x8_t x) {",
    " uint16x8_t u=vreinterpretq_u16_s16(x);",
    " uint16x8_t e=vuzp1q_u16(u,u),o=vuzp2q_u16(u,u);",
    " uint16x8_t lo=vorrq_u16(e,vshlq_n_u16(o,12)),hi=vshrq_n_u16(o,4);",
    " uint8x16x2_t t={{vreinterpretq_u8_u16(lo),vreinterpretq_u8_u16(hi)}};",
    " uint8x16_t b=vqtbl2q_u8(t,vld1q_u8(pack_index));",
    " uint32_t tail=vgetq_lane_u32(vreinterpretq_u32_u8(b),2);",
    " vst1_u8(out,vget_low_u8(b)); memcpy(out+8,&tail,4);",
    "}",
    "__attribute__((noinline)) static void input_once_top(uint8_t *out,const int16_t *in) {",
    " int16x8_t x;",
    " int16x8_t o0,o1,o2,o3,o4,o5,o6,o7,o8,o9,o10,o11,o12,o13,o14,o15;",
]

free_slots = list(range(16))
slot_for_output: dict[int, int] = {}
filled: dict[int, set[int]] = {}
observed_peak = 0
for input_q in input_order:
    source.append(
        f' __asm__ volatile("ldr %q0, [%1]" : "=w"(x) : '
        f'"r"(in+{8 * input_q}) : "memory");')
    edges = []
    for output_q in range(54):
        for output_lane in range(8):
            source_index = forward[8 * output_q + output_lane]
            if source_index // 8 == input_q:
                edges.append((output_q, output_lane, source_index % 8))
    assert len(edges) == 8
    for output_q, output_lane, source_lane in sorted(edges):
        if output_q not in slot_for_output:
            assert free_slots
            slot = free_slots.pop(0)
            slot_for_output[output_q] = slot
            filled[output_q] = set()
            source.append(f" o{slot}=vdupq_n_s16(0);")
        slot = slot_for_output[output_q]
        source.append(
            f" o{slot}=vsetq_lane_s16(vgetq_lane_s16(x,{source_lane}),"
            f"o{slot},{output_lane});")
        filled[output_q].add(output_lane)
        if len(filled[output_q]) == 8:
            source.append(f" pack8(out+{12 * output_q},normq(o{slot}));")
            del slot_for_output[output_q]
            del filled[output_q]
            free_slots.append(slot)
            free_slots.sort()
    # Preserve the proven frontier in generated code: without this public
    # register-state boundary, C compilers hoist later q-loads and extend
    # partial-output lifetimes beyond the schedule being tested.
    active_slots = sorted(slot_for_output.values())
    if active_slots:
        operands = ",".join(f'"w"(o{slot})' for slot in active_slots)
        source.append(f' __asm__ volatile("" : : {operands});')
    observed_peak = max(observed_peak, len(slot_for_output))
assert not slot_for_output and observed_peak <= peak
source.extend([
    "}",
    "void gt864_fr0_input_once_tobytes(uint8_t out[1296],const int16_t fr0[864]) {",
    " input_once_top(out,fr0);",
    " input_once_top(out+648,fr0+432);",
    "}",
    "",
])

build = HERE / "build"
build.mkdir(exist_ok=True)
(build / "p3b6_tables.h").write_text("\n".join(header), encoding="utf-8")
(build / "input_once_tobytes.c").write_text("\n".join(source), encoding="utf-8")
(build / "schedule.txt").write_text(
    f"composed_map_sha256={digest}\npeak={peak}\n"
    f"observed_codegen_peak={observed_peak}\ninput_order={input_order}\n",
    encoding="utf-8")
print(f"{digest} peak={peak} generated_peak={observed_peak}")
