#!/usr/bin/env python3
"""Generate the scratch-integrated P3B6 route plus P3B9 paired pack."""

from __future__ import annotations

import ast
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
P3B6 = HERE.parent / "gt_fr0_d1_input_once_tobytes"


def main() -> None:
    subprocess.check_call(["python3", "prepare.py"], cwd=P3B6,
                          stdout=subprocess.DEVNULL)
    table = (P3B6 / "build/p3b6_tables.h").read_text(encoding="utf-8")
    forward = list(map(int, re.findall(
        r"\b\d+\b", table.split("{", 1)[1].split("}", 1)[0])))[:432]
    schedule = (P3B6 / "build/schedule.txt").read_text(encoding="utf-8")
    order = ast.literal_eval(re.search(r"input_order=(\[.*\])", schedule).group(1))

    source = [
        "/* Generated by prepare.py; do not edit. */",
        '#include "paired_tobytes.h"',
        "#include <arm_neon.h>",
        "static inline int16x8_t normq(int16x8_t x) {",
        " const int16x8_t q=vdupq_n_s16(3457),r=vdupq_n_s16(9);",
        " int16x8_t t=vqrdmulhq_s16(x,r); x=vmlsq_s16(x,t,q);",
        " return vaddq_s16(x,vandq_s16(vshrq_n_s16(x,15),q));",
        "}",
        "static inline void pack16(uint8_t *out,int16x8_t x,int16x8_t y) {",
        " uint16x8_t ux=vreinterpretq_u16_s16(x),uy=vreinterpretq_u16_s16(y);",
        " uint16x8_t ex=vuzp1q_u16(ux,ux),ox=vuzp2q_u16(ux,ux);",
        " uint16x8_t ey=vuzp1q_u16(uy,uy),oy=vuzp2q_u16(uy,uy);",
        " uint16x8_t e=vcombine_u16(vget_low_u16(ex),vget_low_u16(ey));",
        " uint16x8_t o=vcombine_u16(vget_low_u16(ox),vget_low_u16(oy));",
        " uint8x8_t b0=vmovn_u16(e),b2=vshrn_n_u16(o,4);",
        " uint16x8_t mid=vshrq_n_u16(e,8); mid=vsliq_n_u16(mid,o,4);",
        " uint8x8_t b1=vmovn_u16(mid); uint8x8x3_t bytes={{b0,b1,b2}};",
        " vst3_u8(out,bytes);",
        "}",
        "__attribute__((noinline)) static void paired_top(",
        " uint8_t *out,const int16_t *in,int16_t *scratch) {",
        " int16x8_t x,partner;",
        " int16x8_t o0,o1,o2,o3,o4,o5,o6,o7,o8,o9,o10,o11,o12,o13,o14,o15;",
    ]
    free_slots = list(range(16))
    slot_for_output: dict[int, int] = {}
    filled: dict[int, set[int]] = {}
    stored: set[int] = set()
    peak = 0
    scratch_stores = scratch_loads = packs = 0
    for input_q in order:
        source.append(
            f' __asm__ volatile("ldr %q0, [%1]" : "=w"(x) : '
            f'"r"(in+{8 * input_q}) : "memory");')
        completed: list[int] = []
        edges = []
        for output_q in range(54):
            for output_lane in range(8):
                source_index = forward[8 * output_q + output_lane]
                if source_index // 8 == input_q:
                    edges.append((output_q, output_lane, source_index % 8))
        assert len(edges) == 8
        for output_q, output_lane, source_lane in sorted(edges):
            if output_q not in slot_for_output:
                assert free_slots
                slot = free_slots.pop(0)
                slot_for_output[output_q] = slot
                filled[output_q] = set()
                source.append(f" o{slot}=vdupq_n_s16(0);")
            slot = slot_for_output[output_q]
            source.append(
                f" o{slot}=vsetq_lane_s16(vgetq_lane_s16(x,{source_lane}),"
                f"o{slot},{output_lane});")
            filled[output_q].add(output_lane)
            if len(filled[output_q]) == 8:
                completed.append(output_q)
        for output_q in completed:
            slot = slot_for_output.pop(output_q)
            del filled[output_q]
            pair = output_q // 2
            if pair not in stored:
                source.append(
                    f' __asm__ volatile("str %q0, [%1]" : : "w"(o{slot}),'
                    f'"r"(scratch+{8 * pair}) : "memory");')
                stored.add(pair)
                scratch_stores += 1
            else:
                source.append(
                    f' __asm__ volatile("ldr %q0, [%1]" : "=w"(partner) : '
                    f'"r"(scratch+{8 * pair}) : "memory");')
                if output_q & 1:
                    even, odd = "partner", f"o{slot}"
                else:
                    even, odd = f"o{slot}", "partner"
                source.append(
                    f" pack16(out+{24 * pair},normq({even}),normq({odd}));")
                scratch_loads += 1
                packs += 1
            free_slots.append(slot)
            free_slots.sort()
        active = sorted(slot_for_output.values())
        if active:
            operands = ",".join(f'"w"(o{slot})' for slot in active)
            source.append(f' __asm__ volatile("" : : {operands});')
        peak = max(peak, len(active))
    assert not slot_for_output and len(stored) == 27
    assert scratch_stores == scratch_loads == packs == 27 and peak == 16
    source.extend([
        "}",
        "void gt864_fr0_input_once_paired_tobytes(",
        " uint8_t out[1296],const int16_t fr0[864]) {",
        " int16_t scratch[216] __attribute__((aligned(16)));",
        " paired_top(out,fr0,scratch);",
        " paired_top(out+648,fr0+432,scratch);",
        "}",
        "",
    ])
    build = HERE / "build"
    build.mkdir(exist_ok=True)
    (build / "paired_tobytes.c").write_text("\n".join(source), encoding="utf-8")
    (build / "schedule.txt").write_text(
        f"peak_partial_outputs={peak}\nscratch_bytes=432\n"
        f"stores_per_top={scratch_stores}\nloads_per_top={scratch_loads}\n"
        f"packs_per_top={packs}\n", encoding="utf-8")
    print("p3b10_generated peak=16 scratch=432 stores=27 loads=27 packs=27")


if __name__ == "__main__":
    main()
