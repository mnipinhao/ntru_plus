#!/usr/bin/env python3
"""Generate the exact FR-0 -> stock Forward physical-ABI permutation."""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

Q = 3457
N = 864
POINTS = N // 3
R = (1 << 16) % Q
ALPHA = (-722) % Q
BETA = (1 - (-722)) % Q


def signed16(value: int) -> int:
    value &= 0xFFFF
    return value - 0x10000 if value & 0x8000 else value


def prime_factors(value: int) -> list[int]:
    factors: list[int] = []
    divisor = 2
    while divisor * divisor <= value:
        if value % divisor == 0:
            factors.append(divisor)
            while value % divisor == 0:
                value //= divisor
        divisor += 1
    if value > 1:
        factors.append(value)
    return factors


def primitive_root() -> int:
    for candidate in range(2, Q):
        if (pow(candidate, N, Q) == 1
                and all(pow(candidate, N // p, Q) != 1
                        for p in prime_factors(N))
                and pow(candidate, 144, Q) == ALPHA):
            return candidate
    raise AssertionError("alpha-oriented primitive-864 root not found")


def parse_reference_zetas(source: Path) -> list[int]:
    text = source.read_text(encoding="utf-8")
    match = re.search(
        r"const\s+int16_t\s+zetas\s*\[\s*288\s*\]\s*=\s*\{(.*?)\};",
        text,
        re.DOTALL,
    )
    assert match is not None
    values = [int(token) for token in re.findall(r"-?\d+", match.group(1))]
    assert len(values) == POINTS
    return values


def parse_basemul_table(source: Path) -> list[int]:
    tail = source.read_text(encoding="utf-8").split("zetas_mul:", 1)
    assert len(tail) == 2
    lines = "\n".join(line for line in tail[1].splitlines()
                      if ".hword" in line)
    return [signed16(int(token, 0))
            for token in re.findall(r"0x[0-9a-fA-F]+|-?\d+", lines)]


def grid_lookup() -> dict[int, tuple[int, int, int, int]]:
    theta = primitive_root()
    eta = pow(theta, 96, Q)
    result: dict[int, tuple[int, int, int, int]] = {}
    for top, residue in ((0, 1), (1, 5)):
        exponents = list(range(residue, 96, 6))
        assert len(exponents) == 16
        for column, exponent in enumerate(exponents):
            lam = pow(theta, exponent, Q)
            for row in range(9):
                root = lam * pow(eta, row, Q) % Q
                assert root not in result
                assert pow(root, 144, Q) == (ALPHA if top == 0 else BETA)
                result[root] = (top, row, column, exponent)
    assert len(result) == POINTS
    return result


def build(repo: Path) -> tuple[list[int], dict[str, object]]:
    reference = repo / "ntruplus-ntt-Optimized/Reference_Implementation/NTRU+864/ntt.c"
    base = repo / "ntruplus-ntt-Optimized/Additional_Implementation/aarch64/NTRU+864/asm/base.s"
    zetas = parse_reference_zetas(reference)
    table = parse_basemul_table(base)
    assert len(table) == 8 + POINTS
    leaf_table = table[8:]

    expected: list[int] = []
    for pair in range(18):
        roots = zetas[144 + 8 * pair:152 + 8 * pair]
        expected.extend(roots)
        expected.extend(signed16(-root) for root in roots)
    assert leaf_table == expected, "Official BaseMul leaf table changed"

    lookup = grid_lookup()
    r_inverse = pow(R, -1, Q)
    mapping = [-1] * N
    coordinates: list[str] = []
    for leaf, root_mont in enumerate(leaf_table):
        root = root_mont * r_inverse % Q
        top, row, column, exponent = lookup[root]
        group, lane = divmod(leaf, 8)
        for component in range(3):
            official = 24 * group + 8 * component + lane
            fr0 = (top * 18 + row * 2 + column // 8) * 24 \
                + 8 * component + column % 8
            assert mapping[official] == -1
            mapping[official] = fr0
        coordinates.append(
            f"{leaf},{top},{row},{column},{exponent},{root_mont},{root}"
        )

    assert sorted(mapping) == list(range(N)), "ABI map is not a permutation"
    coordinate_hash = hashlib.sha256(
        "\n".join(coordinates).encode("ascii")
    ).hexdigest()
    mapping_hash = hashlib.sha256(
        b"".join(value.to_bytes(2, "little") for value in mapping)
    ).hexdigest()
    proof: dict[str, object] = {
        "gate": "M5O_FR0_to_Official_ABI",
        "status": "pass",
        "entries": len(mapping),
        "bijection": True,
        "source_leaf_table_matches_scalar_zetas": True,
        "coordinate_sha256": coordinate_hash,
        "mapping_sha256": mapping_hash,
    }
    return mapping, proof


def emit_header(path: Path, mapping: list[int], proof: dict[str, object]) -> None:
    lines = [
        "/* Generated by generate_official_map.py; do not edit. */",
        "#ifndef GT864_FR0_TO_OFFICIAL_MAP_H",
        "#define GT864_FR0_TO_OFFICIAL_MAP_H",
        "#include <stdint.h>",
        f"/* mapping_sha256={proof['mapping_sha256']} */",
        "static const uint16_t gt864_fr0_for_official[864] = {",
    ]
    for start in range(0, len(mapping), 12):
        lines.append("    " + ", ".join(str(v) for v in mapping[start:start + 12]) + ",")
    lines.extend(["};", "#endif", ""])
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    repo = Path(__file__).resolve().parents[8]
    mapping, proof = build(repo)
    if len(sys.argv) == 3:
        emit_header(Path(sys.argv[1]), mapping, proof)
        Path(sys.argv[2]).write_text(json.dumps(proof, indent=2) + "\n",
                                     encoding="utf-8")
    else:
        print(json.dumps(proof, indent=2))


if __name__ == "__main__":
    main()
