#!/usr/bin/env python3
"""Generate straight-line ordered pack8 and paired-pack16 boundaries."""

from pathlib import Path

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"

COMMON = r'''/* Generated by prepare.py; do not edit. */
#include "paired_pack16.h"
#include <arm_neon.h>
#include <string.h>
static const uint8_t pack_index[16] __attribute__((aligned(16))) =
 {0,1,16,2,3,18,4,5,20,6,7,22,255,255,255,255};
static inline int16x8_t normq(int16x8_t x) {
 const int16x8_t q=vdupq_n_s16(3457), r=vdupq_n_s16(9);
 int16x8_t t=vqrdmulhq_s16(x,r); x=vmlsq_s16(x,t,q);
 return vaddq_s16(x,vandq_s16(vshrq_n_s16(x,15),q));
}
static inline __attribute__((unused)) void pack8(uint8_t *out,int16x8_t x) {
 uint16x8_t u=vreinterpretq_u16_s16(x);
 uint16x8_t e=vuzp1q_u16(u,u),o=vuzp2q_u16(u,u);
 uint16x8_t lo=vorrq_u16(e,vshlq_n_u16(o,12)),hi=vshrq_n_u16(o,4);
 uint8x16x2_t t={{vreinterpretq_u8_u16(lo),vreinterpretq_u8_u16(hi)}};
 uint8x16_t b=vqtbl2q_u8(t,vld1q_u8(pack_index));
 uint32_t tail=vgetq_lane_u32(vreinterpretq_u32_u8(b),2);
 vst1_u8(out,vget_low_u8(b)); memcpy(out+8,&tail,4);
}
static inline __attribute__((unused)) void pack16(uint8_t *out,int16x8_t x,int16x8_t y) {
 uint16x8_t ux=vreinterpretq_u16_s16(x),uy=vreinterpretq_u16_s16(y);
 uint16x8_t ex=vuzp1q_u16(ux,ux),ox=vuzp2q_u16(ux,ux);
 uint16x8_t ey=vuzp1q_u16(uy,uy),oy=vuzp2q_u16(uy,uy);
 uint16x8_t e=vcombine_u16(vget_low_u16(ex),vget_low_u16(ey));
 uint16x8_t o=vcombine_u16(vget_low_u16(ox),vget_low_u16(oy));
 uint8x8_t b0=vmovn_u16(e),b2=vshrn_n_u16(o,4);
 uint16x8_t mid=vshrq_n_u16(e,8); mid=vsliq_n_u16(mid,o,4);
 uint8x8_t b1=vmovn_u16(mid); uint8x8x3_t bytes={{b0,b1,b2}};
 vst3_u8(out,bytes);
}
'''


def main() -> None:
    BUILD.mkdir(exist_ok=True)
    pack8_lines = [COMMON, "void gt864_pack8_ordered(uint8_t out[1296],const int16_t in[864]) {"]
    for offset in range(0, 864, 8):
        pack8_lines.append(
            f" pack8(out+{12 * (offset // 8)},normq(vld1q_s16(in+{offset})));"
        )
    pack8_lines.extend(["}", ""])
    pair_lines = [COMMON, "void gt864_pack16_ordered(uint8_t out[1296],const int16_t in[864]) {"]
    for offset in range(0, 864, 16):
        pair_lines.append(
            f" pack16(out+{24 * (offset // 16)},normq(vld1q_s16(in+{offset})),"
            f"normq(vld1q_s16(in+{offset + 8})));"
        )
    pair_lines.extend(["}", ""])
    (BUILD / "pack8.c").write_text("\n".join(pack8_lines), encoding="utf-8")
    (BUILD / "pack16.c").write_text("\n".join(pair_lines), encoding="utf-8")
    print("p3b9_generated pack8_outputs=108 pack16_pairs=54")


if __name__ == "__main__":
    main()
