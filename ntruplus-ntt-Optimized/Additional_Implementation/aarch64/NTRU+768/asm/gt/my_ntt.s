    add row0_ptr, sp, #32
    add row1_ptr, sp, #544
    add row2_ptr, sp, #1056

    .include "asm/slothy/my_ntt_phase123.n1.opt.s"

    # Phase 4 32-point NTT
    adr zetas_ptr, zetas
    ldr q0, [zetas_ptr]

    ldr dst, [sp, #MY_NTT_SAVED_DST_OFFSET]
    add row0_ptr, sp, #32
    mov x10, dst
    CALL_NTT32_8WAY

    ldr dst, [sp, #MY_NTT_SAVED_DST_OFFSET]
    add row0_ptr, sp, #544
    add x10, dst, #256
    CALL_NTT32_8WAY

    ldr dst, [sp, #MY_NTT_SAVED_DST_OFFSET]
    add row0_ptr, sp, #1056
    add x10, dst, #512
    CALL_NTT32_8WAY

    add sp, sp, #MY_NTT_FRAME_SIZE
    ldp x30, x0, [sp], #16
    ldp d14, d15, [sp, #48]
    ldp d12, d13, [sp, #32]
    ldp d10, d11, [sp, #16]
    ldp d8, d9, [sp], #64
    ret

