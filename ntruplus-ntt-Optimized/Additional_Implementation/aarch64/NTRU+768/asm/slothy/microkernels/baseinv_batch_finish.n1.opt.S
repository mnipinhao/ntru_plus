/*
 * Slothy symbolic prototype for the GT batch baseinv finish block.
 *
 * This file is intentionally not wired into production.  It models one
 * baseinv_8_finish() block from poly_gt_baseinv_batch.c for later Slothy
 * allocation and scheduling.
 *
 * C dataflow covered:
 *
 *   n = vld4q_s16(dst)
 *   neg_den_inv = vnegq_s16(den_inv)
 *   n0 = fqmul_neon(n0,  den_inv, con)
 *   n1 = fqmul_neon(n1, -den_inv, con)
 *   n2 = fqmul_neon(n2,  den_inv, con)
 *   n3 = fqmul_neon(n3, -den_inv, con)
 *   vst4q_s16(dst, n)
 *
 * Block-major memory layout for one public block i:
 *
 *   dst[4*j + 0] = numerator or output coefficient 0 for lane j
 *   dst[4*j + 1] = numerator or output coefficient 1 for lane j
 *   dst[4*j + 2] = numerator or output coefficient 2 for lane j
 *   dst[4*j + 3] = numerator or output coefficient 3 for lane j
 *   j = 0..7, so the block is 32 int16 coefficients, 64 bytes.
 *
 * Prototype ABI:
 *
 *   x0 = dst block pointer, equivalent to baseinv_8_finish(dst, ...)
 *   x1 = pointer to the int16x8 den_inv vector for this block
 *   v0.h[0] = q = 3457
 *   v0.h[2] = qinv = -12929 for Montgomery reduction
 *
 * In the C helper, den_inv is a vector argument already loaded from den[i].
 * This prototype loads it from x1 to make the one-block Slothy source
 * standalone.  That ABI choice is not production wiring.
 *
 * Negation is expressed as zero - den_inv instead of NEON neg so the local
 * symbolic checker can classify the defining instruction.  The lane operation
 * is equivalent to vnegq_s16(den_inv).
 */

