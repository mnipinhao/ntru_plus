#!/usr/bin/env python3
"""Generate C-callable wrappers for the baseline and Slothy chunk candidates."""

from pathlib import Path


EXP = Path(__file__).resolve().parent
ROOT = EXP.parents[1]
OUTPUT = ROOT / "asm/gt/experiment/canonical_pack_chunk_candidates.S"

VARIANTS = {
    "baseline": (
        EXP / "baseline-pack-chunk0.S",
        "slothy_start_gt_canonical_pack_chunk0_baseline",
        "slothy_end_gt_canonical_pack_chunk0_baseline",
        112,
    ),
    "p1": (
        EXP / "pack_chunk_p1.fixed.opt.s",
        "slothy_start_gt_canonical_pack_chunk_p1",
        "slothy_end_gt_canonical_pack_chunk_p1",
        108,
    ),
    "p2": (
        EXP / "pack_chunk_p2.fixed.opt.s",
        "slothy_start_gt_canonical_pack_chunk_p2",
        "slothy_end_gt_canonical_pack_chunk_p2",
        100,
    ),
    "p3": (
        EXP / "pack_chunk_p3.fixed.opt.s",
        "slothy_start_gt_canonical_pack_chunk_p3",
        "slothy_end_gt_canonical_pack_chunk_p3",
        100,
    ),
}


def extract_instructions(path: Path, start: str, end: str) -> list[str]:
    body: list[str] = []
    active = False
    for raw in path.read_text().splitlines():
        stripped = raw.strip()
        if stripped == f"{start}:":
            active = True
            continue
        if stripped == f"{end}:":
            break
        if not active or not stripped or stripped.startswith("//"):
            continue
        instruction = stripped.split("//", 1)[0].rstrip()
        if instruction and not instruction.endswith(":"):
            body.append(instruction)
    if not active:
        raise ValueError(f"missing start label {start} in {path}")
    return body


def emit_function(name: str, instructions: list[str]) -> list[str]:
    symbol = f"poly_tobytes_gt_chunk0_{name}"
    lines = [
        ".p2align 4",
        f".global {symbol}",
        f".global _{symbol}",
        f"{symbol}:",
        f"_{symbol}:",
        "    sub sp, sp, #64",
        "    stp d8, d9, [sp, #0]",
        "    stp d10, d11, [sp, #16]",
        "    stp d12, d13, [sp, #32]",
        "    stp d14, d15, [sp, #48]",
        "    mov w2, #3457",
        "    dup v0.8h, w2",
    ]
    lines.extend(f"    {instruction}" for instruction in instructions)
    lines.extend(
        [
            "    ldp d8, d9, [sp, #0]",
            "    ldp d10, d11, [sp, #16]",
            "    ldp d12, d13, [sp, #32]",
            "    ldp d14, d15, [sp, #48]",
            "    add sp, sp, #64",
            "    ret",
            "",
        ]
    )
    return lines


def main() -> None:
    output = [
        "// Generated by experiments/canonical_pack_next_wave/generate_chunk_wrappers.py.",
        "// Experiment only; production default is unchanged.",
        ".text",
        "",
    ]
    for name, (path, start, end, expected) in VARIANTS.items():
        instructions = extract_instructions(path, start, end)
        if len(instructions) != expected:
            raise ValueError(
                f"{name}: expected {expected} instructions, got {len(instructions)}"
            )
        output.extend(emit_function(name, instructions))
    OUTPUT.write_text("\n".join(output))
    print(OUTPUT)


if __name__ == "__main__":
    main()
