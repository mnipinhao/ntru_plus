#!/usr/bin/env python3
"""Expand each verified chunk schedule across all 12 canonical pack chunks."""

import re
from pathlib import Path

from generate_chunk_wrappers import EXP, ROOT, VARIANTS, extract_instructions


PRODUCTION = ROOT / "asm/gt/support/poly_canonical_pack.S"
OUTPUT = ROOT / "asm/gt/experiment/canonical_pack_full_candidates.S"
P1_OUTPUT = ROOT / "asm/gt/support/poly_canonical_pack_p1.S"
LOAD_RE = re.compile(r"^(ldr d\d+, \[x1, #)(\d+)(\])$")


def production_chunk_offsets() -> list[list[int]]:
    chunks: list[list[int]] = []
    current: list[int] | None = None
    for line in PRODUCTION.read_text().splitlines():
        stripped = line.strip()
        if stripped.startswith("poly_frombytes_gt_canonical:"):
            break
        if re.fullmatch(r"// canonical blocks \d+\.\.\d+", stripped):
            if current is not None:
                chunks.append(current)
            current = []
            continue
        if current is not None:
            match = re.match(r"ldr d\d+, \[x1, #(\d+)\]", stripped)
            if match and len(current) < 16:
                current.append(int(match.group(1)))
    if current is not None:
        chunks.append(current)
    if len(chunks) != 12 or any(len(chunk) != 16 for chunk in chunks):
        raise ValueError(f"unexpected production chunk map: {[len(c) for c in chunks]}")
    if any(len(set(chunk)) != 16 for chunk in chunks):
        raise ValueError("each production chunk must contain 16 distinct GT offsets")
    return chunks


def remap_chunk(instructions: list[str], source: list[int], target: list[int]) -> list[str]:
    mapping = dict(zip(source, target))
    seen: list[int] = []
    output: list[str] = []
    for instruction in instructions:
        match = LOAD_RE.match(instruction)
        if match:
            old_offset = int(match.group(2))
            if old_offset not in mapping:
                raise ValueError(f"candidate load offset {old_offset} is not in chunk 0")
            seen.append(old_offset)
            instruction = f"{match.group(1)}{mapping[old_offset]}{match.group(3)}"
        output.append(instruction)
    if sorted(seen) != sorted(source):
        raise ValueError("candidate load multiset does not match production chunk 0")
    return output


def emit_function(name: str, chunk0: list[str], offsets: list[list[int]]) -> list[str]:
    symbol = f"poly_tobytes_gt_canonical_{name}"
    lines = [
        ".p2align 4",
        f".global {symbol}",
        f".global _{symbol}",
        f"{symbol}:",
        f"_{symbol}:",
        "    sub sp, sp, #64",
        "    stp d8, d9, [sp, #0]",
        "    stp d10, d11, [sp, #16]",
        "    stp d12, d13, [sp, #32]",
        "    stp d14, d15, [sp, #48]",
        "    adr x2, .Lcanonical_pack_candidate_q",
        "    ldr q0, [x2]",
    ]
    for index, target in enumerate(offsets):
        lines.append(f"    // canonical blocks {16 * index}..{16 * index + 15}")
        lines.extend(
            f"    {instruction}"
            for instruction in remap_chunk(chunk0, offsets[0], target)
        )
    lines.extend(
        [
            "    ldp d8, d9, [sp, #0]",
            "    ldp d10, d11, [sp, #16]",
            "    ldp d12, d13, [sp, #32]",
            "    ldp d14, d15, [sp, #48]",
            "    add sp, sp, #64",
            "    ret",
            "",
        ]
    )
    return lines


def main() -> None:
    offsets = production_chunk_offsets()
    output = [
        "// Generated by experiments/canonical_pack_next_wave/generate_full_pack_candidates.py.",
        "// Experiment only; production default is unchanged.",
        ".text",
        "",
    ]
    for name in ("p1", "p2", "p3"):
        path, start, end, expected = VARIANTS[name]
        instructions = extract_instructions(path, start, end)
        if len(instructions) != expected:
            raise ValueError(
                f"{name}: expected {expected} instructions, got {len(instructions)}"
            )
        output.extend(emit_function(name, instructions, offsets))
    output.extend(
        [
            ".p2align 4",
            ".Lcanonical_pack_candidate_q:",
            "    .hword 3457, 3457, 3457, 3457",
            "    .hword 3457, 3457, 3457, 3457",
            "",
        ]
    )
    OUTPUT.write_text("\n".join(output))
    path, start, end, expected = VARIANTS["p1"]
    instructions = extract_instructions(path, start, end)
    if len(instructions) != expected:
        raise ValueError(f"p1: expected {expected} instructions, got {len(instructions)}")
    p1_output = [
        "// Generated selected P1 full canonical pack; GT production keygen path.",
        ".text",
        "",
        *emit_function("p1", instructions, offsets),
        ".p2align 4",
        ".Lcanonical_pack_candidate_q:",
        "    .hword 3457, 3457, 3457, 3457",
        "    .hword 3457, 3457, 3457, 3457",
        "",
    ]
    P1_OUTPUT.write_text("\n".join(p1_output))
    print(OUTPUT)
    print(P1_OUTPUT)


if __name__ == "__main__":
    main()
