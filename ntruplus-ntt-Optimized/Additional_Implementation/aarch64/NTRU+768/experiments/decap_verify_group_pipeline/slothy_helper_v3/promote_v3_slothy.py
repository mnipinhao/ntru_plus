#!/usr/bin/env python3
"""Promote the audited V3+Slothy kernel to production and clean-release form."""

from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re


HERE = Path(__file__).resolve().parent
NTRU768 = HERE.parents[2]
REPO = NTRU768.parents[3]
CANDIDATE = (
    NTRU768
    / "asm/gt/experiment/decap/"
    "verify_pointwise_group_pipeline_v3_slothy.S"
)
PRODUCTION = NTRU768 / "asm/gt/decap/verify_pointwise_group_pipeline.S"
DEFAULT_RELEASE = (
    REPO
    / "ntruplus-GT-Production/Additional_Implementation/aarch64/NTRU+768"
)
METADATA = HERE / "production-promotion.json"

BODY_MARKER = "// Compact production backend generated by "
HELPER_LABEL = ".Lfused_gather_mul_group:"
INSTRUCTION_RE = re.compile(r"^\s*([a-z][a-z0-9.]*)\b", re.IGNORECASE)
VECTOR_RE = re.compile(r"\bv([0-9]|[12][0-9]|3[01])\b", re.IGNORECASE)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def helper_instructions(text: str) -> list[str]:
    start = text.index(HELPER_LABEL) + len(HELPER_LABEL)
    lines = text[start:].splitlines()
    end = next(i for i, line in enumerate(lines) if line.strip() == "ret")
    return [line for line in lines[:end] if INSTRUCTION_RE.match(line)]


def mnemonic_counter(lines: list[str]) -> Counter[str]:
    return Counter(
        match.group(1).lower()
        for line in lines
        if (match := INSTRUCTION_RE.match(line))
    )


def production_source(candidate: str) -> str:
    start = candidate.index(BODY_MARKER)
    source = candidate[start:]
    source = source.replace(
        "// Compact production backend generated by "
        "generate_fused_gather_pointwise.py.",
        "// Production decapsulation verification backend: "
        "V3 gather pipeline with Slothy-scheduled shared helper.",
        1,
    )
    if "group_pipeline_v3_slothy" in source:
        raise SystemExit("experiment symbol leaked into production source")
    return source


def flatten_release(source: str) -> str:
    lines = source.splitlines()
    output: list[str] = [
        "// Flattened production decapsulation verification backend.",
        "// V3 gather pipeline with Slothy-scheduled shared helper.",
    ]
    skip = False
    for line in lines[1:]:
        if line.startswith("#ifndef "):
            skip = True
            continue
        if skip:
            if line == "#endif":
                skip = False
            continue
        output.append(line)
    text = "\n".join(output) + "\n"
    text = text.replace(
        "GT_DECAP_VERIFY_POINTWISE_DARWIN_SYMBOL",
        "_gt_decap_verify_pointwise",
    )
    text = text.replace(
        "GT_DECAP_VERIFY_POINTWISE_SYMBOL",
        "gt_decap_verify_pointwise",
    )
    if (
        re.search(r"(?m)^#", text)
        or "GT_DECAP_" in text
        or "group_pipeline_v3_slothy" in text
    ):
        raise SystemExit("release flattening left a selector or experiment token")
    return text


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--release-root",
        type=Path,
        default=DEFAULT_RELEASE,
        help="clean NTRU+768 release root",
    )
    args = parser.parse_args()

    candidate_bytes = CANDIDATE.read_bytes()
    candidate = candidate_bytes.decode("ascii")
    production = production_source(candidate)
    release = flatten_release(production)

    candidate_helper = helper_instructions(candidate)
    production_helper = helper_instructions(production)
    if len(candidate_helper) != 100 or len(production_helper) != 100:
        raise SystemExit("production helper must contain exactly 100 instructions")
    if mnemonic_counter(candidate_helper) != mnemonic_counter(production_helper):
        raise SystemExit("production helper changed the mnemonic multiset")
    used_vectors = {
        int(match.group(1))
        for line in production_helper
        for match in VECTOR_RE.finditer(line)
    }
    reserved_touches = sorted(used_vectors.intersection(range(24, 32)))
    if reserved_touches:
        raise SystemExit(f"production helper touches q24-q31: {reserved_touches}")
    if production.count("bl .Lfused_gather_mul_group") != 24:
        raise SystemExit("production source must call the helper 24 times")

    release_root = args.release_root.resolve()
    release_output = release_root / "asm/internal/decap_verify.S"
    if not (release_root / "scripts/check_release.py").is_file():
        raise SystemExit(f"invalid release root: {release_root}")

    PRODUCTION.write_text(production, encoding="ascii")
    release_output.write_text(release, encoding="ascii")
    METADATA.write_text(
        json.dumps(
            {
                "candidate": str(CANDIDATE.relative_to(NTRU768)),
                "candidate_sha256": sha256(candidate_bytes),
                "production": str(PRODUCTION.relative_to(NTRU768)),
                "production_sha256": sha256(PRODUCTION.read_bytes()),
                "release": str(release_output.relative_to(release_root)),
                "release_sha256": sha256(release_output.read_bytes()),
                "helper_calls": 24,
                "helper_instruction_count": 100,
                "mnemonic_multiset_unchanged": True,
                "q24_q31_touches": reserved_touches,
                "production_default_profile": "pipeline",
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="ascii",
    )
    print(f"production={PRODUCTION}")
    print(f"release={release_output}")
    print(f"metadata={METADATA}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
