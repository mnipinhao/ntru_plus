#!/usr/bin/env python3
"""Convert the Slothy output into a parameterized three-output GAS macro."""

from __future__ import annotations

import re
from pathlib import Path


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SOURCE = ROOT / "asm/slothy/experiments/invntt_next_wave/post_branchfold_three_outputs.n1.opt.s"
OUTPUT = ROOT / "asm/slothy/experiments/invntt_next_wave/post_branchfold_three_outputs.n1.inc"
START = "slothy_start_invntt_post_branchfold_three_outputs:"
END = "slothy_end_invntt_post_branchfold_three_outputs:"
INSTRUCTION = re.compile(r"^\s+[a-z][a-z0-9.]*\s")

STORE_MAP = {
    "str d4, [x11, #0]": "str d4, [\\ptr0, #\\off0_lo]",
    "str d13, [x11, #768]": "str d13, [\\ptr0, #\\off0_hi]",
    "str d31, [x12, #0]": "str d31, [\\ptr1, #\\off1_lo]",
    "str d25, [x12, #768]": "str d25, [\\ptr1, #\\off1_hi]",
    "str d10, [x13, #0]": "str d10, [\\ptr2, #\\off2_lo]",
    "str d21, [x13, #768]": "str d21, [\\ptr2, #\\off2_hi]",
}


def main() -> int:
    lines = SOURCE.read_text(encoding="utf-8").splitlines()
    start = next(i for i, line in enumerate(lines) if line.strip() == START)
    end = next(i for i, line in enumerate(lines) if line.strip() == END)
    body = []
    stores = set()
    for line in lines[start + 1 : end]:
        code = line.split("//", 1)[0].strip()
        if not code or not INSTRUCTION.match("        " + code):
            continue
        if code in STORE_MAP:
            stores.add(code)
            code = STORE_MAP[code]
        if "<" in code or ">" in code:
            raise ValueError(f"unallocated symbolic register in {code}")
        body.append("    " + code)
    if len(body) != 69:
        raise ValueError(f"expected 69 instructions, got {len(body)}")
    if stores != set(STORE_MAP):
        raise ValueError(f"store mapping incomplete: {set(STORE_MAP) - stores}")

    out = [
        "/* Generated by integrate_post_branchfold.py; do not edit. */",
        ".macro INVNTT_POST_BRANCHFOLD_THREE_SLOTHY ptr0, off0_lo, off0_hi, ptr1, off1_lo, off1_hi, ptr2, off2_lo, off2_hi",
        *body,
        ".endm",
        "",
    ]
    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"generated={OUTPUT}")
    print("instructions=69")
    print("stores=6")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
