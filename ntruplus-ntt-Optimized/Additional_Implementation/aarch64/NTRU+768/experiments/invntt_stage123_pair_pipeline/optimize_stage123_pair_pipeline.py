#!/usr/bin/env python3
"""Slothy-schedule the six fixed-register Stage123 pair windows."""

import argparse
import importlib
import logging
import os
import re
import sys
from collections import Counter
from pathlib import Path


HERE = Path(__file__).resolve().parent
LABEL_RE = re.compile(r"^\s*([A-Za-z_.$][\w.$]*):\s*$")
PAIRS = [
    f"row{row}_pair{pair}{pair + 1}"
    for row in range(3)
    for pair in (0, 2)
]
WINDOWS = [f"{pair}_{part}" for pair in PAIRS for part in ("xover", "tail")]


def add_instruction_models(arch, target):
    class LdrDImmediate(arch.Ldr_D):
        pattern = "ldr <Da>, [<Xc>, <imm>]"
        inputs = ["Xc"]
        outputs = ["Da"]

        @classmethod
        def make(cls, src):
            obj = arch.AArch64Instruction.build(cls, src)
            obj.increment = None
            obj.pre_index = obj.immediate
            obj.addr = obj.args_in[0]
            return obj

    arch.Instruction.all_subclass_leaves = arch.all_subclass_leaves(arch.Instruction)


def region_counter(lines, start, end):
    inside = False
    result = []
    for line in lines:
        match = LABEL_RE.match(line)
        if match and match.group(1) == start:
            inside = True
            continue
        if match and match.group(1) == end:
            break
        code = line.split("//", 1)[0].strip()
        if inside and code and not code.startswith(".") and not code.endswith(":"):
            result.append(" ".join(code.lower().split()))
    return Counter(result)


def region_lines(lines, start, end):
    inside = False
    result = []
    for line in lines:
        match = LABEL_RE.match(line)
        if match and match.group(1) == start:
            inside = True
            continue
        if match and match.group(1) == end:
            break
        if inside and line.strip() and not line.lstrip().startswith("//"):
            result.append(line)
    return result


def emit_include(output_lines, path):
    lines = ["// Generated by optimize_stage123_pair_pipeline.py."]
    for row in range(3):
        lines.append(f".macro INVNTT_STAGE123_PAIR_ROW{row}_BODY")
        lines.extend([
            "    add x14, sp, #1568",
            "    adr x7, invntt32_stage123_consts",
            "    ldr q1, [x7]",
            "    ldr q2, [x7, #16]",
        ])
        for pair in (0, 2):
            name = f"row{row}_pair{pair}{pair + 1}"
            lines.extend(region_lines(
                output_lines,
                f"invntt_stage123_{name}_slothy_start",
                f"invntt_stage123_{name}_slothy_end",
            ))
        lines.append(".endm")
        lines.append("")
    path.write_text("\n".join(lines), encoding="ascii")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", type=Path, default=HERE / "stage123_pair_pipeline.sym.S")
    parser.add_argument("--output", type=Path, default=HERE / "stage123_pair_pipeline.opt.S")
    parser.add_argument("--include", type=Path, default=HERE / "stage123_pair_pipeline.opt.inc")
    parser.add_argument("--window", default="all")
    parser.add_argument("--stalls", type=int, default=384)
    parser.add_argument("--timeout", type=int, default=1800)
    args = parser.parse_args()

    sys.path.insert(0, os.environ.get("SLOTHY_PATH", str(Path.home() / "slothy")))
    from slothy import Slothy
    import slothy.targets.aarch64.aarch64_neon as arch

    target = importlib.import_module(
        "slothy.targets.aarch64.neoverse_n1_experimental"
    )
    add_instruction_models(arch, target)
    logging.basicConfig(level=logging.INFO)
    slothy = Slothy(arch, target, logger=logging.getLogger("invntt-stage123-pair"))
    slothy.load_source_from_file(str(args.input))
    slothy.config.variable_size = True
    slothy.config.inputs_are_outputs = True
    slothy.config.selftest = False
    slothy.config.allow_useless_instructions = False
    slothy.config.constraints.allow_spills = False
    slothy.config.constraints.allow_renaming = False
    slothy.config.constraints.stalls_first_attempt = args.stalls
    slothy.config.timeout = args.timeout
    slothy.config.split_heuristic = True
    slothy.config.split_heuristic_stepsize = 0.10
    slothy.config.split_heuristic_factor = 8.0
    slothy.config.split_heuristic_repeat = 0
    slothy.config.split_heuristic_estimate_performance = False
    allowed_gprs = {"x3", "x4", "x14"}
    slothy.config.reserved_regs = [
        *[f"x{i}" for i in range(31) if f"x{i}" not in allowed_gprs],
        "sp", "v0", "v1", "v2", "v31",
    ]
    slothy.config.outputs = ["x3", "x4", "x14"]

    windows = WINDOWS if args.window == "all" else [args.window]
    source_lines = args.input.read_text(encoding="ascii").splitlines()
    before = {}
    for name in windows:
        start = f"invntt_stage123_{name}_slothy_start"
        end = f"invntt_stage123_{name}_slothy_end"
        before[name] = region_counter(source_lines, start, end)
        slothy.config.outputs = ["x3", "x4", "x14"]
        if name.endswith("_xover"):
            # The next group's assembled Q vectors cross this artificial
            # scheduling cut and are consumed by the adjacent tail window.
            slothy.config.outputs.extend(f"v{i}" for i in range(13, 21))
        slothy.optimize(start=start, end=end)

    slothy.write_source_to_file(str(args.output))
    output_lines = args.output.read_text(encoding="ascii").splitlines()
    for name in windows:
        start = f"invntt_stage123_{name}_slothy_start"
        end = f"invntt_stage123_{name}_slothy_end"
        if before[name] != region_counter(output_lines, start, end):
            raise SystemExit(f"{name}: instruction multiset changed")
    if windows == WINDOWS:
        emit_include(output_lines, args.include)
    print(f"optimized_windows={','.join(windows)}")
    print(f"output={args.output}")


if __name__ == "__main__":
    main()
