#!/usr/bin/env python3
"""Generate fixed-register two-group Stage123 scheduling windows."""

from pathlib import Path


HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "stage123_pair_pipeline.sym.S"

ROWS = {
    0: [
        [0, 24, 48, 72, 96, 120, 144, 168],
        [192, 216, 240, 264, 288, 312, 336, 360],
        [384, 408, 432, 456, 480, 504, 528, 552],
        [576, 600, 624, 648, 672, 696, 720, 744],
    ],
    1: [
        [256, 280, 304, 328, 352, 376, 400, 424],
        [448, 472, 496, 520, 544, 568, 592, 616],
        [640, 664, 688, 712, 736, 760, 16, 40],
        [64, 88, 112, 136, 160, 184, 208, 232],
    ],
    2: [
        [512, 536, 560, 584, 608, 632, 656, 680],
        [704, 728, 752, 8, 32, 56, 80, 104],
        [128, 152, 176, 200, 224, 248, 272, 296],
        [320, 344, 368, 392, 416, 440, 464, 488],
    ],
}


def load_group(lines, data_regs, offsets):
    high_regs = range(23, 31)
    for dst, high, offset in zip(data_regs, high_regs, offsets):
        lines.append(f"    ldr d{dst}, [x3, #{offset}]")
        lines.append(f"    ldr d{high}, [x4, #{offset}]")
    for dst, high in zip(data_regs, high_regs):
        lines.append(f"    mov v{dst}.d[1], v{high}.d[0]")


def identity(lines, lo, hi, tmp):
    lines.extend([
        # AArch64 MOV (vector) is an alias of ORR with identical sources.  Use
        # the canonical spelling because Slothy's generic MOV datatype parser
        # rejects the otherwise valid `.16b, .16b` alias.
        f"    orr v{tmp}.16b, v{lo}.16b, v{lo}.16b",
        f"    add v{lo}.8h, v{lo}.8h, v{hi}.8h",
        f"    sub v{hi}.8h, v{tmp}.8h, v{hi}.8h",
    ])


def multiply(lines, lo, hi, lane, prod, tmp):
    lines.extend([
        f"    sqrdmulh v{tmp}.8h, v{hi}.8h, v2.h[{lane}]",
        f"    mul v{prod}.8h, v{hi}.8h, v1.h[{lane}]",
        f"    mls v{prod}.8h, v{tmp}.8h, v0.h[0]",
        f"    orr v{tmp}.16b, v{lo}.16b, v{lo}.16b",
        f"    add v{lo}.8h, v{lo}.8h, v{prod}.8h",
        f"    sub v{hi}.8h, v{tmp}.8h, v{prod}.8h",
    ])


def stage123(lines, regs, prod, tmp):
    r0, r1, r2, r3, r4, r5, r6, r7 = regs
    for lo, hi in ((r0, r1), (r2, r3), (r4, r5), (r6, r7)):
        identity(lines, lo, hi, tmp)
    identity(lines, r0, r2, tmp)
    multiply(lines, r1, r3, 1, prod, tmp)
    identity(lines, r4, r6, tmp)
    multiply(lines, r5, r7, 1, prod, tmp)
    identity(lines, r0, r4, tmp)
    multiply(lines, r1, r5, 2, prod, tmp)
    multiply(lines, r2, r6, 3, prod, tmp)
    multiply(lines, r3, r7, 4, prod, tmp)


def store_group(lines, regs, group):
    for stripe, reg in enumerate(regs):
        lines.append(f"    str q{reg}, [x14, #{64 * stripe + 16 * group}]")


def group_registers(second):
    regs = list(range(13, 21)) if second else list(range(3, 11))
    prod, tmp = (21, 22) if second else (11, 12)
    return regs, prod, tmp


def main():
    lines = [
        "// Generated by generate_stage123_pair_pipeline.py.",
        "// Fixed-register source order; Slothy schedules only labeled pair windows.",
        ".text",
    ]
    for row, groups in ROWS.items():
        for pair_start in (0, 2):
            pair_name = f"row{row}_pair{pair_start}{pair_start + 1}"
            lines.extend([
                "// live-in: x3, x4, x14, v0, v1, v2; two fixed-offset input groups",
                "// live-out: sixteen q vectors in distinct Stage123 stripe-scratch slots",
                "// coefficient range: identical to production rminus1 lazy Stage123 bounds",
                "// reserved physical registers: all GPRs except x3/x4/x14; v0-v2 and v31 fixed",
            ])
            lines.append(f"invntt_stage123_{pair_name}_slothy_start:")
            regs0, prod0, tmp0 = group_registers(False)
            regs1, prod1, tmp1 = group_registers(True)
            load_group(lines, regs0, groups[pair_start])
            lines.extend([
                "// live-in: x3, x4, x14, v0-v2, and group-N q vectors v3-v10",
                "// live-out: group-N scratch stores and assembled group-N+1 v13-v20",
                "// coefficient range: production lazy Stage123 bounds remain unchanged",
                "// reserved physical registers: all GPRs except x3/x4/x14; v0-v2 and v31 fixed",
            ])
            lines.append(f"invntt_stage123_{pair_name}_xover_slothy_start:")
            stage123(lines, regs0, prod0, tmp0)
            store_group(lines, regs0, pair_start)
            load_group(lines, regs1, groups[pair_start + 1])
            lines.append(f"invntt_stage123_{pair_name}_xover_slothy_end:")
            lines.extend([
                "// live-in: x14, v0-v2, and assembled group-N+1 q vectors v13-v20",
                "// live-out: group-N+1 Stage123 stripe-scratch stores",
                "// coefficient range: production lazy Stage123 bounds remain unchanged",
                "// reserved physical registers: all GPRs except x3/x4/x14; v0-v2 and v31 fixed",
            ])
            lines.append(f"invntt_stage123_{pair_name}_tail_slothy_start:")
            stage123(lines, regs1, prod1, tmp1)
            store_group(lines, regs1, pair_start + 1)
            lines.append(f"invntt_stage123_{pair_name}_tail_slothy_end:")
            lines.append(f"invntt_stage123_{pair_name}_slothy_end:")
    instructions = [line for line in lines if line.startswith("    ")]
    if len(instructions) != 6 * 166:
        raise SystemExit(f"unexpected instruction count: {len(instructions)}")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
