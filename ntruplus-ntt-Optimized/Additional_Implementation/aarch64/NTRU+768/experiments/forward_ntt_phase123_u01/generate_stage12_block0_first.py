#!/usr/bin/env python3
"""Generate source-order all-row Phase123 -> stage12 block0-first scaffold."""

from __future__ import annotations

from pathlib import Path

import generate_stage12_allrows_scratch as even_u01
import generate_stage12_allrows_u23_scratch as even_u23
import generate_stage12_allrows_u01_odd_scratch as odd_u01
import generate_stage12_allrows_u23_odd_scratch as odd_u23


ROOT = Path(__file__).resolve().parent
OUT = ROOT / "phase123_stage12_block0_first_allrows.sym.s"

ROW_SCRATCH_BASE = {"row0": 0, "row1": 512, "row2": 1024}


def qoff(row: str, q_index: int) -> int:
    return ROW_SCRATCH_BASE[row] + 16 * q_index


def emit_raw_slot(
    lines: list[str],
    module,
    typ: str,
    local_slot: int,
    q_index: int,
    comment_slot: str,
) -> None:
    a_name, b_name, c_name = module.TYPE_SLOTS[typ][local_slot]
    a, b, c = module.Z[a_name], module.Z[b_name], module.Z[c_name]
    lines.extend(
        [
            f"    // Type {typ.upper()} {comment_slot}: a={a_name}, b={b_name}, c={c_name} -> raw Q{q_index}.",
            f"    sub v6.8h, {b}.8h, {c}.8h",
            "    sqrdmulh v7.8h, v6.8h, v0.h[3]",
            "    mul v8.8h, v6.8h, v0.h[2]",
            "    mls v8.8h, v7.8h, v0.h[0]",
            f"    add v9.8h, {a}.8h, {b}.8h",
            f"    add v9.8h, v9.8h, {c}.8h",
            f"    sub v10.8h, {a}.8h, {c}.8h",
            "    add v10.8h, v10.8h, v8.8h",
            f"    sub v11.8h, {a}.8h, {b}.8h",
            "    sub v11.8h, v11.8h, v8.8h",
            f"    str q9, [x13, #{qoff('row0', q_index)}]",
            f"    str q10, [x13, #{qoff('row1', q_index)}]",
            f"    str q11, [x13, #{qoff('row2', q_index)}]",
            "",
        ]
    )


def emit_family(
    lines: list[str],
    module,
    iterations: tuple[tuple[int, str], ...],
    q_base_delta: int,
    family_name: str,
    slot_comment_base: int,
) -> None:
    lines.append(f"    // ---- {family_name} raw Q producer ----")
    for iteration, typ in iterations:
        module.emit_common_prefix(lines, iteration)
        emit_raw_slot(
            lines,
            module,
            typ,
            0,
            4 * iteration + q_base_delta,
            f"{family_name} slot{slot_comment_base}",
        )
        emit_raw_slot(
            lines,
            module,
            typ,
            1,
            4 * iteration + q_base_delta + 1,
            f"{family_name} slot{slot_comment_base + 1}",
        )


def emit_stage12_stripe(lines: list[str], row: str, stripe: int) -> None:
    q0, q8, q16, q24 = stripe, stripe + 8, stripe + 16, stripe + 24
    lines.extend(
        [
            f"    // Stage12 {row} stripe{stripe}: out0 feeds block0 Q{q0}.",
            f"    ldr q24, [x13, #{qoff(row, q0)}]",
            f"    ldr q28, [x13, #{qoff(row, q8)}]",
            f"    ldr q5, [x13, #{qoff(row, q16)}]",
            f"    ldr q13, [x13, #{qoff(row, q24)}]",
            "    add v16.8h, v28.8h, v13.8h",
            "    sqrdmulh v17.8h, v16.8h, v2.h[0]",
            "    mls v16.8h, v17.8h, v0.h[0]",
            "    sub v18.8h, v28.8h, v13.8h",
            "    sqrdmulh v19.8h, v18.8h, v4.h[0]",
            "    mul v18.8h, v18.8h, v3.h[0]",
            "    mls v18.8h, v19.8h, v0.h[0]",
            "    add v20.8h, v24.8h, v5.8h",
            "    sub v21.8h, v24.8h, v5.8h",
            "    add v22.8h, v20.8h, v16.8h",
            "    sub v23.8h, v20.8h, v16.8h",
            "    add v26.8h, v21.8h, v18.8h",
            "    sub v27.8h, v21.8h, v18.8h",
            f"    str q22, [x13, #{qoff(row, q0)}]    // block0 Q{q0}",
            f"    str q23, [x13, #{qoff(row, q8)}]    // later block1 Q{q8}",
            f"    str q26, [x13, #{qoff(row, q16)}]   // later block2 Q{q16}",
            f"    str q27, [x13, #{qoff(row, q24)}]   // later block3 Q{q24}",
            "",
        ]
    )


def main() -> int:
    lines: list[str] = [
        "// Generated source-order scaffold for block0-first Stage12 -> Stage345 work.",
        "//",
        "// Do not edit this file by hand; edit generate_stage12_block0_first.py.",
        "//",
        "// Live-in: x1=input base, x3=Phase123 twist base,",
        "//          x12=gt_ntt32_batch8_twiddle_vecs, x13=row-major scratch,",
        "//          v0=q/constants.",
        "// Live-out: x13 row-major post-stage12 Q0..Q31 for rows0/1/2.",
        "// Block0-ready subset:",
        "//   row0 x13+0..112, row1 x13+512..624, row2 x13+1024..1136.",
        "",
        ".text",
        "",
        "slothy_start_phase123_stage12_block0_first_allrows:",
    ]

    emit_family(lines, even_u01, even_u01.EVEN_ITERS, 0, "even U01", 0)
    emit_family(lines, even_u23, even_u23.EVEN_ITERS, 2, "even U23", 2)
    emit_family(lines, odd_u01, odd_u01.ODD_ITERS, 0, "odd U01", 0)
    emit_family(lines, odd_u23, odd_u23.ODD_ITERS, 2, "odd U23", 2)

    lines.extend(
        [
            "    // NTT32 stage12 twiddles. Production resets the table pointer",
            "    // before every stripe; all stripes use lane 0 of these vectors.",
            "    ldr q2, [x12, #16]",
            "    ldr q3, [x12, #32]",
            "    ldr q4, [x12, #48]",
            "",
        ]
    )

    for row in ("row0", "row1", "row2"):
        lines.append(f"    // ---- {row}: produce block0 Q0..Q7 first in row scratch ----")
        for stripe in range(8):
            emit_stage12_stripe(lines, row, stripe)
        lines.append(f"    // {row}: stage345 block0 can consume Q0..Q7 from x13 now.")
        lines.append("")

    lines.append("slothy_end_phase123_stage12_block0_first_allrows:")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
