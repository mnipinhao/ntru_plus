#!/usr/bin/env python3
"""Generate U01v2 shared-prefix even/odd block-first body.

U01v2 keeps the production Phase123 shared prefix intact for each iteration.
It changes only the order:

  iter0,2,4,6 -> stage12 stripes0..3
  iter1,3,5,7 -> stage12 stripes4..7

The first version still uses row-major scratch.  It is a layout/order
experiment, not a no-scratch fusion.
"""

from __future__ import annotations

from pathlib import Path

from generate_stage12_block0_first import emit_stage12_stripe


ROOT = Path(__file__).resolve().parent
NTRU_ROOT = ROOT.parents[1]
PHASE123 = NTRU_ROOT / "asm/slothy/inputs/my_ntt_phase123_flat.sym.s"
OUT = ROOT / "phase123_shared_prefix_v2_allrows.sym.s"


def extract_region(lines: list[str], start: str, end: str) -> list[str]:
    inside = False
    out: list[str] = []
    for line in lines:
        if line.strip() == f"{start}:":
            inside = True
            continue
        if line.strip() == f"{end}:":
            return out
        if inside:
            out.append(line)
    raise ValueError(f"missing region {start}..{end}")


def emit_phase123_iter(out: list[str], phase_lines: list[str], iteration: int) -> None:
    out.extend(
        [
            f"    // Production Phase123 iter{iteration}, shared prefix once.",
            f"    add x1, x14, #{iteration * 32}",
            f"    add x3, x15, #{iteration * 384}",
            f"    add x4, x13, #{iteration * 64}",
            f"    add x5, x13, #{512 + iteration * 64}",
            f"    add x6, x13, #{1024 + iteration * 64}",
        ]
    )
    out.extend(extract_region(
        phase_lines,
        f"slothy_start_ntt_phase123_iter{iteration}",
        f"slothy_end_ntt_phase123_iter{iteration}",
    ))
    out.append("")


def emit_stage12_group(out: list[str], stripes: range, name: str) -> None:
    out.extend(
        [
            f"    // Stage12 {name} twiddles.",
            "    ldr q2, [x12, #16]",
            "    ldr q3, [x12, #32]",
            "    ldr q4, [x12, #48]",
            "",
        ]
    )
    for row in ("row0", "row1", "row2"):
        out.append(f"    // ---- {row}: Stage12 {name} ----")
        for stripe in stripes:
            emit_stage12_stripe(out, row, stripe)
        out.append("")


def main() -> int:
    phase_lines = PHASE123.read_text().splitlines()
    lines: list[str] = [
        "// Generated U01v2 shared-prefix even/odd block-first body.",
        "//",
        "// Do not edit this file by hand; edit",
        "// experiments/forward_ntt_phase123_u01/generate_phase123_shared_prefix_v2.py.",
        "//",
        "// Live-in: x14=input base, x15=Phase123 twist base,",
        "//          x12=ntt32_twiddle_vecs, x13=row-major scratch,",
        "//          v0=q/constants.",
        "// Live-out: x13 row-major post-stage12 Q0..Q31 for rows0/1/2.",
        "",
        ".text",
        "",
        "u01v2_shared_prefix_body:",
        "    // Even Phase123 iterations produce raw Q0..Q3, Q8..Q11,",
        "    // Q16..Q19, Q24..Q27.  Those are exactly Stage12 stripes0..3.",
    ]

    for iteration in (0, 2, 4, 6):
        emit_phase123_iter(lines, phase_lines, iteration)
    emit_stage12_group(lines, range(0, 4), "stripes0..3")

    lines.extend(
        [
            "    // Odd Phase123 iterations produce raw Q4..Q7, Q12..Q15,",
            "    // Q20..Q23, Q28..Q31.  Those are exactly Stage12 stripes4..7.",
        ]
    )
    for iteration in (1, 3, 5, 7):
        emit_phase123_iter(lines, phase_lines, iteration)
    emit_stage12_group(lines, range(4, 8), "stripes4..7")

    lines.append("u01v2_shared_prefix_body_end:")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
