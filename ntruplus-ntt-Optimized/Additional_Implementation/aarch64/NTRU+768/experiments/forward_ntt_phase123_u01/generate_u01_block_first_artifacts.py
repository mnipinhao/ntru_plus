#!/usr/bin/env python3
"""Generate U01 block-first callable tables and C test vectors."""

from __future__ import annotations

from pathlib import Path

from verify_stage12_block0_first_symbolic import expected_allrows
from verify_stage12_row0_symbolic import parse_gt_ntt32_batch8_twiddle_mem
from verify_u01_symbolic import ROOT, make_input, parse_hwords


OUT_TABLES = ROOT / "asm/gt/experiment/forward_ntt/u01_block_first_tables.inc"
OUT_VECTORS = (
    ROOT
    / "experiments/forward_ntt_phase123_u01/u01_block_first_vectors.inc"
)
VECTOR_COUNT = 16
BLOCK0_OFFSETS = [
    row_base + q * 16
    for row_base in (0, 512, 1024)
    for q in range(8)
]


def hword_line(values: list[int], *, indent: str = "    ") -> str:
    return indent + ".hword " + ", ".join(str(v) for v in values)


def c_array_line(values: list[int], *, indent: str = "\t\t") -> str:
    return indent + ", ".join(str(v) for v in values) + ","


def write_tables(zetas: list[int], twist: list[int], ntt32_twiddles: list[int]) -> None:
    lines: list[str] = [
        "/* Generated by experiments/forward_ntt_phase123_u01/generate_u01_block_first_artifacts.py. */",
        "/* Do not edit by hand. */",
        "",
        ".align 4",
        "u01_block_first_zetas:",
        hword_line(zetas),
        "",
        ".align 4",
        "u01_block_first_twist_table:",
    ]
    for i in range(0, len(twist), 8):
        lines.append(hword_line(twist[i : i + 8]))
    lines.extend(
        [
            "",
            ".align 4",
            "u01_block_first_gt_ntt32_batch8_twiddle_vecs:",
        ]
    )
    for i in range(0, len(ntt32_twiddles), 8):
        lines.append(hword_line(ntt32_twiddles[i : i + 8]))
    lines.append("")
    OUT_TABLES.write_text("\n".join(lines))


def block0_expected_flat(want: dict[int, list[int]]) -> list[int]:
    out: list[int] = []
    for offset in BLOCK0_OFFSETS:
        out.extend(want[offset])
    return out


def write_vectors(zetas: list[int], twist: list[int]) -> None:
    lines: list[str] = [
        "/* Generated by experiments/forward_ntt_phase123_u01/generate_u01_block_first_artifacts.py. */",
        "/* Do not edit by hand. */",
        "",
        f"#define U01_BLOCK_FIRST_VECTOR_COUNT {VECTOR_COUNT}",
        "#define U01_BLOCK_FIRST_EXPECTED_WORDS 192",
        "",
        "static const int16_t u01_block_first_inputs[U01_BLOCK_FIRST_VECTOR_COUNT][NTRUPLUS_N] = {",
    ]
    for seed in range(VECTOR_COUNT):
        values = make_input(seed)
        lines.append("\t{")
        for i in range(0, len(values), 12):
            lines.append(c_array_line(values[i : i + 12]))
        lines.append("\t},")
    lines.append("};")
    lines.append("")
    lines.append(
        "static const int16_t u01_block_first_expected[U01_BLOCK_FIRST_VECTOR_COUNT][U01_BLOCK_FIRST_EXPECTED_WORDS] = {"
    )
    for seed in range(VECTOR_COUNT):
        values = block0_expected_flat(expected_allrows(seed, zetas, twist))
        lines.append("\t{")
        for i in range(0, len(values), 12):
            lines.append(c_array_line(values[i : i + 12]))
        lines.append("\t},")
    lines.append("};")
    lines.append("")
    OUT_VECTORS.write_text("\n".join(lines))


def main() -> int:
    zetas, twist = parse_hwords(ROOT / "asm/gt/ntt/poly_ntt_body.inc")
    ntt32_twiddles = parse_gt_ntt32_batch8_twiddle_mem()
    write_tables(zetas, twist, ntt32_twiddles)
    write_vectors(zetas, twist)
    print(OUT_TABLES)
    print(OUT_VECTORS)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
