#!/usr/bin/env python3
"""Generate the U01 same-boundary production semantic oracle body.

The generated body is intentionally source-order:

  production Phase123 full raw row scratch
  -> NTT32 stage12 stripes0..7 for rows0/1/2

It is used as a callable correctness/PMU boundary for the U01 block-first
candidate.  It is not the final production scheduled forward-NTT baseline.
"""

from __future__ import annotations

from pathlib import Path

from generate_stage12_block0_first import emit_stage12_stripe


ROOT = Path(__file__).resolve().parent
OUT = ROOT / "phase123_production_stage12_block0_oracle_allrows.sym.s"


def main() -> int:
    lines: list[str] = [
        "// Generated source-order production semantic oracle for U01 block-first.",
        "//",
        "// Do not edit this file by hand; edit",
        "// experiments/forward_ntt_phase123_u01/generate_phase123_production_stage12_oracle.py.",
        "//",
        "// Live-in: x1=input base, x3=Phase123 twist base,",
        "//          x4=row0 scratch base, x5=row1 scratch base, x6=row2 scratch base,",
        "//          x12=ntt32_twiddle_vecs, x13=row-major scratch,",
        "//          v0=q/constants.",
        "// Live-out: x13 row-major post-stage12 Q0..Q31 for rows0/1/2.",
        "// Block0-ready subset:",
        "//   row0 x13+0..112, row1 x13+512..624, row2 x13+1024..1136.",
        "",
        ".text",
        "",
        "u01_block_first_production_oracle_body:",
        "    // Full production Phase123, source-order, stores raw Q0..Q31",
        "    // into row0/row1/row2 scratch via x4/x5/x6.",
        '    .include "asm/slothy/inputs/my_ntt_phase123_flat.sym.s"',
        "",
        "    // NTT32 stage12 twiddles. Production resets the table pointer",
        "    // before every stripe; all stripes use lane 0 of these vectors.",
        "    ldr q2, [x12, #16]",
        "    ldr q3, [x12, #32]",
        "    ldr q4, [x12, #48]",
        "",
    ]

    for row in ("row0", "row1", "row2"):
        lines.append(f"    // ---- {row}: production same-boundary stage12 ----")
        for stripe in range(8):
            emit_stage12_stripe(lines, row, stripe)
        lines.append("")

    lines.append("u01_block_first_production_oracle_body_end:")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
