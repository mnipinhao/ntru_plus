#!/usr/bin/env python3
"""Generate U01v2 diagnostic with Stage12 block0 out0 stores removed.

This is not a correctness candidate.  It estimates the upper-bound value of
removing the Stage12 Q0..Q7 store side of a future Stage12->Stage345 block0
fusion.  Later block stores Q8/Q16/Q24 are retained.
"""

from __future__ import annotations

from pathlib import Path

from generate_phase123_shared_prefix_v2 import PHASE123, extract_region
from generate_stage12_block0_first import qoff


ROOT = Path(__file__).resolve().parent
OUT = ROOT / "phase123_shared_prefix_v2_no_out0_store_allrows.sym.s"


def emit_phase123_iter(out: list[str], phase_lines: list[str], iteration: int) -> None:
    out.extend(
        [
            f"    // Production Phase123 iter{iteration}, shared prefix once.",
            f"    add x1, x14, #{iteration * 32}",
            f"    add x3, x15, #{iteration * 384}",
            f"    add x4, x13, #{iteration * 64}",
            f"    add x5, x13, #{512 + iteration * 64}",
            f"    add x6, x13, #{1024 + iteration * 64}",
        ]
    )
    out.extend(extract_region(
        phase_lines,
        f"slothy_start_ntt_phase123_iter{iteration}",
        f"slothy_end_ntt_phase123_iter{iteration}",
    ))
    out.append("")


def emit_stage12_stripe_no_out0(lines: list[str], row: str, stripe: int) -> None:
    q0, q8, q16, q24 = stripe, stripe + 8, stripe + 16, stripe + 24
    lines.extend(
        [
            f"    // Stage12 {row} stripe{stripe}: out0 Q{q0} store omitted.",
            f"    ldr q24, [x13, #{qoff(row, q0)}]",
            f"    ldr q28, [x13, #{qoff(row, q8)}]",
            f"    ldr q5, [x13, #{qoff(row, q16)}]",
            f"    ldr q13, [x13, #{qoff(row, q24)}]",
            "    add v16.8h, v28.8h, v13.8h",
            "    sqrdmulh v17.8h, v16.8h, v2.h[0]",
            "    mls v16.8h, v17.8h, v0.h[0]",
            "    sub v18.8h, v28.8h, v13.8h",
            "    sqrdmulh v19.8h, v18.8h, v4.h[0]",
            "    mul v18.8h, v18.8h, v3.h[0]",
            "    mls v18.8h, v19.8h, v0.h[0]",
            "    add v20.8h, v24.8h, v5.8h",
            "    sub v21.8h, v24.8h, v5.8h",
            "    add v22.8h, v20.8h, v16.8h",
            "    sub v23.8h, v20.8h, v16.8h",
            "    add v26.8h, v21.8h, v18.8h",
            "    sub v27.8h, v21.8h, v18.8h",
            f"    // str q22, [x13, #{qoff(row, q0)}] omitted",
            f"    str q23, [x13, #{qoff(row, q8)}]    // later block1 Q{q8}",
            f"    str q26, [x13, #{qoff(row, q16)}]   // later block2 Q{q16}",
            f"    str q27, [x13, #{qoff(row, q24)}]   // later block3 Q{q24}",
            "",
        ]
    )


def emit_stage12_group(out: list[str], stripes: range, name: str) -> None:
    out.extend(
        [
            f"    // Stage12 {name} twiddles.",
            "    ldr q2, [x12, #16]",
            "    ldr q3, [x12, #32]",
            "    ldr q4, [x12, #48]",
            "",
        ]
    )
    for row in ("row0", "row1", "row2"):
        out.append(f"    // ---- {row}: Stage12 {name}, no out0 store ----")
        for stripe in stripes:
            emit_stage12_stripe_no_out0(out, row, stripe)
        out.append("")


def main() -> int:
    phase_lines = PHASE123.read_text().splitlines()
    lines: list[str] = [
        "// Generated U01v2 diagnostic: no Stage12 block0 out0 stores.",
        "//",
        "// Do not edit this file by hand; edit",
        "// experiments/forward_ntt_phase123_u01/generate_phase123_shared_prefix_v2_no_out0_store.py.",
        "//",
        "// This is not a correctness candidate.",
        "",
        ".text",
        "",
        "u01v2_no_out0_store_body:",
    ]

    for iteration in (0, 2, 4, 6):
        emit_phase123_iter(lines, phase_lines, iteration)
    emit_stage12_group(lines, range(0, 4), "stripes0..3")

    for iteration in (1, 3, 5, 7):
        emit_phase123_iter(lines, phase_lines, iteration)
    emit_stage12_group(lines, range(4, 8), "stripes4..7")

    lines.append("u01v2_no_out0_store_body_end:")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
